import { useCallback, useState } from 'react'
import type { Challenge, LanguageBundle, Level, RootIndex, TestQuestion } from '../curriculum/types'
import { moveItem } from './arrayHelpers'
import { cloneBundle, cloneRootIndex, patchBundle, patchSectionLevels } from './curriculumPatch'
import { loadLanguageBundle, loadRootIndex } from '../curriculum/loadCurriculum'
import {
  createDefaultChallenge,
  createDefaultLanguage,
  createDefaultLevel,
  createDefaultMcqQuestion,
  createDefaultSection,
  createDefaultShortTextQuestion,
  newId,
} from './curriculumDefaults'
import {
  loadDraftBundle,
  loadDraftHomeLead,
  loadDraftRootIndex,
  listDraftBundleIds,
  removeDraftBundle,
  removeDraftRootIndex,
  saveDraftBundle,
  saveDraftHomeLead,
  saveDraftRootIndex,
} from './curriculumDraftStorage'
import { downloadJson } from './exportCurriculum'
import { DEFAULT_HOME_LEAD } from './editorConstants'
import {
  isAutoGeneratedSectionId,
  renameSectionInBundle,
  slugifySectionTitle,
  uniqueSectionSlug,
} from './curriculumSlug'

/** A course's lessons after an edit, or null to leave them as they are. */
type BundleEdit = (bundle: LanguageBundle) => LanguageBundle | null

/**
 * The editable copy of the curriculum: the catalog, each course's lessons and the home
 * page text. Every edit is saved as a local draft straight away.
 */
export function useCurriculumDraft({ onImport }: { onImport: () => void }) {
  const [rootIndex, setRootIndex] = useState<RootIndex | null>(() => loadDraftRootIndex())
  const [bundles, setBundles] = useState<Record<string, LanguageBundle>>({})
  const [homeLead, setHomeLead] = useState(() => loadDraftHomeLead() ?? DEFAULT_HOME_LEAD)

  /** Starts from the published catalog, unless there is a draft (or a copy) already. */
  const syncRootIndex = useCallback((fetched: RootIndex) => {
    setRootIndex((prev) => {
      if (prev) return prev
      const draft = loadDraftRootIndex()
      return draft ?? cloneRootIndex(fetched)
    })
  }, [])

  /** Starts a course from its published lessons, unless there is a draft (or a copy) already. */
  const syncBundle = useCallback((langId: string, fetched: LanguageBundle) => {
    setBundles((prev) => {
      if (prev[langId]) return prev
      const draft = loadDraftBundle(langId)
      return { ...prev, [langId]: draft ?? cloneBundle(fetched) }
    })
  }, [])

  const persistRoot = useCallback((next: RootIndex) => {
    setRootIndex(next)
    saveDraftRootIndex(next)
  }, [])

  const persistBundle = useCallback((langId: string, next: LanguageBundle) => {
    setBundles((prev) => ({ ...prev, [langId]: next }))
    saveDraftBundle(langId, next)
  }, [])

  const getBundle = useCallback((langId: string) => bundles[langId] ?? null, [bundles])

  /** Applies an edit to a loaded course and saves it. False when nothing changed. */
  const editBundle = useCallback(
    (langId: string, edit: BundleEdit): boolean => {
      const bundle = bundles[langId]
      if (!bundle) return false
      const next = edit(bundle)
      if (!next) return false
      persistBundle(langId, next)
      return true
    },
    [bundles, persistBundle],
  )

  /** Applies an edit to one lesson of a loaded course and saves it. */
  const editLevel = useCallback(
    (langId: string, sectionId: string, levelId: string, patch: (level: Level) => Level): boolean =>
      editBundle(langId, (bundle) => patchBundle(bundle, sectionId, levelId, patch)),
    [editBundle],
  )

  const updateLanguage = useCallback(
    (langId: string, patch: { title?: string; id?: string }) => {
      if (!rootIndex) return
      const next = cloneRootIndex(rootIndex)
      const lang = next.languages.find((l) => l.id === langId)
      if (!lang) return
      if (patch.title !== undefined) lang.title = patch.title
      if (patch.id !== undefined) lang.id = patch.id
      persistRoot(next)
    },
    [rootIndex, persistRoot],
  )

  const updateHomeLead = useCallback((text: string) => {
    setHomeLead(text)
    saveDraftHomeLead(text)
  }, [])

  const updateLanguageTitle = useCallback(
    (langId: string, title: string) => {
      const changed = editBundle(langId, (bundle) => {
        const next = cloneBundle(bundle)
        next.index.title = title
        return next
      })
      if (changed) updateLanguage(langId, { title })
    },
    [editBundle, updateLanguage],
  )

  const updateSectionTitle = useCallback(
    (langId: string, sectionId: string, title: string, options?: { commit?: boolean }) => {
      editBundle(langId, (bundle) => {
        let next = cloneBundle(bundle)
        const secRef = next.index.sections.find((s) => s.id === sectionId)
        const loaded = next.sections.find((s) => s.sectionRef.id === sectionId)
        if (secRef) secRef.title = title
        if (loaded) {
          loaded.sectionRef.title = title
          loaded.file.title = title
        }

        // A new section's placeholder id becomes a slug of its title once the title is set.
        if (options?.commit && isAutoGeneratedSectionId(sectionId)) {
          const slug = slugifySectionTitle(title)
          if (slug) {
            const taken = next.index.sections.map((s) => s.id).filter((id) => id !== sectionId)
            const slugId = uniqueSectionSlug(slug, taken)
            if (slugId !== sectionId) {
              next = renameSectionInBundle(next, sectionId, slugId, title)
            }
          }
        }
        return next
      })
    },
    [editBundle],
  )

  const updateLevelTitle = useCallback(
    (langId: string, sectionId: string, levelId: string, title: string) => {
      editLevel(langId, sectionId, levelId, (lvl) => ({ ...lvl, title }))
    },
    [editLevel],
  )

  const updateLevelIntro = useCallback(
    (langId: string, sectionId: string, levelId: string, patch: Partial<Level['intro']>) => {
      editLevel(langId, sectionId, levelId, (lvl) => ({ ...lvl, intro: { ...lvl.intro, ...patch } }))
    },
    [editLevel],
  )

  const updateChallenge = useCallback(
    (langId: string, sectionId: string, levelId: string, challengeId: string, patch: Partial<Challenge>) => {
      editLevel(langId, sectionId, levelId, (lvl) => ({
        ...lvl,
        challenges: lvl.challenges.map((ch) => (ch.id === challengeId ? { ...ch, ...patch } : ch)),
      }))
    },
    [editLevel],
  )

  const updateTestPassingScore = useCallback(
    (langId: string, sectionId: string, levelId: string, score: number) => {
      editLevel(langId, sectionId, levelId, (lvl) => ({
        ...lvl,
        test: { ...lvl.test, passingScorePercent: score },
      }))
    },
    [editLevel],
  )

  const updateTestQuestion = useCallback(
    (langId: string, sectionId: string, levelId: string, questionId: string, question: TestQuestion) => {
      editLevel(langId, sectionId, levelId, (lvl) => ({
        ...lvl,
        test: {
          ...lvl.test,
          questions: lvl.test.questions.map((q) => (q.id === questionId ? question : q)),
        },
      }))
    },
    [editLevel],
  )

  const addLanguage = useCallback((): string | null => {
    if (!rootIndex) return null
    const langId = newId('lang')
    const { rootEntry, bundle } = createDefaultLanguage(langId)
    const nextRoot = cloneRootIndex(rootIndex)
    nextRoot.languages.push(rootEntry)
    persistRoot(nextRoot)
    persistBundle(langId, bundle)
    return langId
  }, [rootIndex, persistRoot, persistBundle])

  const removeLanguage = useCallback(
    (langId: string) => {
      if (!rootIndex) return
      const nextRoot = cloneRootIndex(rootIndex)
      nextRoot.languages = nextRoot.languages.filter((l) => l.id !== langId)
      persistRoot(nextRoot)
      setBundles((prev) => {
        const next = { ...prev }
        delete next[langId]
        return next
      })
    },
    [rootIndex, persistRoot],
  )

  const moveLanguage = useCallback(
    (langId: string, direction: -1 | 1) => {
      if (!rootIndex) return
      const index = rootIndex.languages.findIndex((l) => l.id === langId)
      if (index < 0) return
      const nextRoot = cloneRootIndex(rootIndex)
      nextRoot.languages = moveItem(nextRoot.languages, index, direction)
      persistRoot(nextRoot)
    },
    [rootIndex, persistRoot],
  )

  const addSection = useCallback(
    (langId: string): string | null => {
      const { sectionId, path, sectionFile } = createDefaultSection()
      const added = editBundle(langId, (bundle) => {
        const next = cloneBundle(bundle)
        next.index.sections.push({ id: sectionId, title: sectionFile.title ?? '', path })
        next.sections.push({
          sectionRef: { id: sectionId, title: sectionFile.title ?? '', path },
          file: sectionFile,
        })
        return next
      })
      return added ? sectionId : null
    },
    [editBundle],
  )

  const removeSection = useCallback(
    (langId: string, sectionId: string) => {
      editBundle(langId, (bundle) => {
        const next = cloneBundle(bundle)
        next.index.sections = next.index.sections.filter((s) => s.id !== sectionId)
        next.sections = next.sections.filter((s) => s.sectionRef.id !== sectionId)
        return next
      })
    },
    [editBundle],
  )

  const moveSection = useCallback(
    (langId: string, sectionId: string, direction: -1 | 1) => {
      editBundle(langId, (bundle) => {
        const index = bundle.index.sections.findIndex((s) => s.id === sectionId)
        if (index < 0) return null
        const next = cloneBundle(bundle)
        next.index.sections = moveItem(next.index.sections, index, direction)
        next.sections = moveItem(next.sections, index, direction)
        return next
      })
    },
    [editBundle],
  )

  const addLevel = useCallback(
    (langId: string, sectionId: string): string | null => {
      const level = createDefaultLevel()
      const added = editBundle(langId, (bundle) => patchSectionLevels(bundle, sectionId, (levels) => [...levels, level]))
      return added ? level.id : null
    },
    [editBundle],
  )

  const removeLevel = useCallback(
    (langId: string, sectionId: string, levelId: string) => {
      editBundle(langId, (bundle) =>
        patchSectionLevels(bundle, sectionId, (levels) => levels.filter((l) => l.id !== levelId)),
      )
    },
    [editBundle],
  )

  const moveLevel = useCallback(
    (langId: string, sectionId: string, levelId: string, direction: -1 | 1) => {
      editBundle(langId, (bundle) => {
        const section = bundle.sections.find((s) => s.sectionRef.id === sectionId)
        if (!section) return null
        const index = section.file.levels.findIndex((l) => l.id === levelId)
        if (index < 0) return null
        return patchSectionLevels(bundle, sectionId, (levels) => moveItem(levels, index, direction))
      })
    },
    [editBundle],
  )

  const addChallenge = useCallback(
    (langId: string, sectionId: string, levelId: string): string | null => {
      const challenge = createDefaultChallenge()
      const added = editLevel(langId, sectionId, levelId, (lvl) => ({
        ...lvl,
        challenges: [...lvl.challenges, challenge],
      }))
      return added ? challenge.id : null
    },
    [editLevel],
  )

  const removeChallenge = useCallback(
    (langId: string, sectionId: string, levelId: string, challengeId: string) => {
      editLevel(langId, sectionId, levelId, (lvl) => ({
        ...lvl,
        challenges: lvl.challenges.filter((ch) => ch.id !== challengeId),
      }))
    },
    [editLevel],
  )

  const moveChallenge = useCallback(
    (langId: string, sectionId: string, levelId: string, challengeId: string, direction: -1 | 1) => {
      editBundle(langId, (bundle) => {
        const section = bundle.sections.find((s) => s.sectionRef.id === sectionId)
        const level = section?.file.levels.find((l) => l.id === levelId)
        if (!level) return null
        const index = level.challenges.findIndex((ch) => ch.id === challengeId)
        if (index < 0) return null
        return patchBundle(bundle, sectionId, levelId, (lvl) => ({
          ...lvl,
          challenges: moveItem(lvl.challenges, index, direction),
        }))
      })
    },
    [editBundle],
  )

  const addTestQuestion = useCallback(
    (langId: string, sectionId: string, levelId: string, type: 'mcq' | 'shortText'): string | null => {
      const question = type === 'mcq' ? createDefaultMcqQuestion() : createDefaultShortTextQuestion()
      const added = editLevel(langId, sectionId, levelId, (lvl) => ({
        ...lvl,
        test: { ...lvl.test, questions: [...lvl.test.questions, question] },
      }))
      return added ? question.id : null
    },
    [editLevel],
  )

  const removeTestQuestion = useCallback(
    (langId: string, sectionId: string, levelId: string, questionId: string) => {
      editLevel(langId, sectionId, levelId, (lvl) => ({
        ...lvl,
        test: { ...lvl.test, questions: lvl.test.questions.filter((q) => q.id !== questionId) },
      }))
    },
    [editLevel],
  )

  const moveTestQuestion = useCallback(
    (langId: string, sectionId: string, levelId: string, questionId: string, direction: -1 | 1) => {
      editBundle(langId, (bundle) => {
        const section = bundle.sections.find((s) => s.sectionRef.id === sectionId)
        const level = section?.file.levels.find((l) => l.id === levelId)
        if (!level) return null
        const index = level.test.questions.findIndex((q) => q.id === questionId)
        if (index < 0) return null
        return patchBundle(bundle, sectionId, levelId, (lvl) => ({
          ...lvl,
          test: { ...lvl.test, questions: moveItem(lvl.test.questions, index, direction) },
        }))
      })
    },
    [editBundle],
  )

  const exportRootIndex = useCallback(() => {
    if (!rootIndex) return
    downloadJson('index.json', rootIndex)
  }, [rootIndex])

  const exportLanguageIndex = useCallback(
    (langId: string) => {
      const bundle = bundles[langId]
      if (!bundle) return
      downloadJson(`${langId}/index.json`, bundle.index)
    },
    [bundles],
  )

  const exportSection = useCallback(
    (langId: string, sectionId: string) => {
      const bundle = bundles[langId]
      if (!bundle) return
      const section = bundle.sections.find((s) => s.sectionRef.id === sectionId)
      if (!section) return
      const filename = section.sectionRef.path.split('/').pop() ?? `${sectionId}.json`
      downloadJson(filename, section.file)
    },
    [bundles],
  )

  /** Replaces the drafts with the published content, then shows the drafts. */
  const importFromGitHub = useCallback(
    async (baseUrl: string) => {
      const fetchedRoot = await loadRootIndex(baseUrl)
      persistRoot(cloneRootIndex(fetchedRoot))
      for (const lang of fetchedRoot.languages) {
        const bundle = await loadLanguageBundle(baseUrl, lang.path, { fresh: true })
        persistBundle(lang.id, cloneBundle(bundle))
      }
      onImport()
    },
    [persistRoot, persistBundle, onImport],
  )

  const saveToGitHub = useCallback(
    async (onProgress?: (label: string, index: number, total: number) => void) => {
      if (!rootIndex) throw new Error('No local curriculum to save.')
      // Loaded on demand: only editors ever save.
      const { saveCurriculumToGitHub } = await import('./githubCurriculumApi')
      await saveCurriculumToGitHub(rootIndex, bundles, onProgress)
    },
    [rootIndex, bundles],
  )

  /** Saves everything as drafts (catalog, courses, home text). */
  const persistAllDrafts = useCallback(() => {
    if (rootIndex) saveDraftRootIndex(rootIndex)
    for (const [langId, bundle] of Object.entries(bundles)) {
      saveDraftBundle(langId, bundle)
    }
    saveDraftHomeLead(homeLead)
  }, [rootIndex, bundles, homeLead])

  /** Puts back an earlier version of the drafts (discarding edits), in memory and storage. */
  const restoreDrafts = useCallback(
    (snapshot: { rootIndex: RootIndex | null; bundles: Record<string, LanguageBundle>; homeLead: string }) => {
      setRootIndex(snapshot.rootIndex)
      if (snapshot.rootIndex) saveDraftRootIndex(snapshot.rootIndex)
      else removeDraftRootIndex()
      setBundles(snapshot.bundles)
      const snapshotLangIds = new Set(Object.keys(snapshot.bundles))
      for (const [langId, bundle] of Object.entries(snapshot.bundles)) {
        saveDraftBundle(langId, bundle)
      }
      for (const langId of listDraftBundleIds()) {
        if (!snapshotLangIds.has(langId)) removeDraftBundle(langId)
      }
      setHomeLead(snapshot.homeLead)
      saveDraftHomeLead(snapshot.homeLead)
    },
    [],
  )

  /** Replaces the drafts with content just read from disk (dev server). */
  const replaceDrafts = useCallback((root: RootIndex, loadedBundles: Record<string, LanguageBundle>) => {
    setRootIndex(root)
    saveDraftRootIndex(root)
    setBundles(loadedBundles)
    for (const [langId, bundle] of Object.entries(loadedBundles)) {
      saveDraftBundle(langId, bundle)
    }
  }, [])

  return {
    rootIndex,
    bundles,
    homeLead,
    syncRootIndex,
    syncBundle,
    getBundle,
    updateLanguage,
    updateHomeLead,
    updateLanguageTitle,
    updateSectionTitle,
    updateLevelTitle,
    updateLevelIntro,
    updateChallenge,
    updateTestPassingScore,
    updateTestQuestion,
    addLanguage,
    removeLanguage,
    moveLanguage,
    addSection,
    removeSection,
    moveSection,
    addLevel,
    removeLevel,
    moveLevel,
    addChallenge,
    removeChallenge,
    moveChallenge,
    addTestQuestion,
    removeTestQuestion,
    moveTestQuestion,
    exportRootIndex,
    exportLanguageIndex,
    exportSection,
    importFromGitHub,
    saveToGitHub,
    persistAllDrafts,
    restoreDrafts,
    replaceDrafts,
  }
}
