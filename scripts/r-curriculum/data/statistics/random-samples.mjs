      solution: 'set.seed(1)\nsd_10 <- round(sd(replicate(1000, mean(sample(1:6, 10, replace = TRUE)))), 2)\nsd_100 <- round(sd(replicate(1000, mean(sample(1:6, 100, replace = TRUE)))), 2)',
