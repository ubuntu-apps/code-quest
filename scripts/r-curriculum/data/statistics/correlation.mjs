// Statistics: Correlation.
import { code, makeTopic, mc, near, qShort, same, snippet, task } from '../_builders.mjs'
import { STUDY } from './stats-data.mjs'

export default makeTopic({
  id: 'correlation',
  title: 'Correlation',
  paragraphs: [
    'Do students who revise more score higher? A **correlation** measures how closely two numeric columns move together, as one number from −1 to 1:',
    '| r | Means |\n| --- | --- |\n| near 1 | When one is high, the other is high (a strong positive link) |\n| near 0 | No straight-line link |\n| near −1 | When one is high, the other is low (a strong negative link) |',
    code(...STUDY.trim().split('\n'), 'cor(study$hours, study$score)    # 0.93: strongly positive', 'cor(study$phone, study$score)    # -0.91: strongly negative'),
    '`cor()` on a whole table of numbers gives every pair at once, as a matrix: `cor(study[, c("hours", "phone", "sleep", "score")])`.',
    '`cor()` measures **straight-line** links, and one unusual value can pull it a long way. `method = "spearman"` uses ranks instead, so it is less affected by outliers.',
    'And the big warning: **correlation is not causation**. Revising and phone use are linked (r = −0.91), so either could be behind the scores, or something else behind both. A correlation tells you two things go together, not why.',
  ],
  sandboxCode: STUDY + 'cor(study$hours, study$score)\nround(cor(study[, c("hours", "phone", "sleep", "score")]), 2)',
  sandboxSnippets: [snippet('One outlier', 'x <- c(1, 2, 3, 4, 5, 6)\ny <- c(2, 4, 5, 4, 5, 6)\ncor(x, y)\ny[6] <- 30\ncor(x, y)\ncor(x, y, method = "spearman")'), snippet('Every pair', STUDY + 'round(cor(study[c("hours", "phone", "sleep", "score")]), 2)'), snippet('One point matters', 'x <- c(1, 2, 3, 4, 5, 6)\ny <- c(2, 4, 5, 4, 5, 6)\ncor(x, y)\ncor(c(x, 20), c(y, 0))')],
  readMore: { label: 'R documentation: cor()', url: 'https://stat.ethz.ch/R-manual/R-devel/library/stats/html/cor.html', source: 'R documentation' },
  challenges: [
    task('easy', 'Revision and score', {
      prompt: 'Make `r_hours` the correlation between hours of revision and score, rounded to 2 decimal places.',
      starter: STUDY,
      hint: '`round(cor(study$hours, study$score), 2)`',
      solution: STUDY + 'r_hours <- round(cor(study$hours, study$score), 2)',
      tests: [['r_hours is 0.93', near('r_hours', 0.93)]],
    }),
    task('easy', 'Phones and score', {
      prompt: 'Make `r_phone` the correlation between phone hours and score, rounded to 2 decimal places.',
      starter: STUDY,
      hint: '`round(cor(study$phone, study$score), 2)`',
      solution: STUDY + 'r_phone <- round(cor(study$phone, study$score), 2)',
      tests: [['r_phone is -0.91', near('r_phone', -0.91)]],
    }),
    task('easy', 'Sleep and score', {
      prompt: 'Make `r_sleep` the correlation between sleep and score, rounded to 2 decimal places. Is the link strong?',
      starter: STUDY,
      hint: 'Same as before, with `study$sleep`. A value near 0 means a weak link.',
      solution: STUDY + 'r_sleep <- round(cor(study$sleep, study$score), 2)',
      tests: [['r_sleep is 0.2', near('r_sleep', 0.2)]],
    }),
    task('medium', 'Every pair', {
      prompt: 'Make `m` the correlation matrix of the four number columns, rounded to 2 decimal places.',
      starter: STUDY,
      hint: '`round(cor(study[, c("hours", "phone", "sleep", "score")]), 2)`, or `study[, -1]` for every column but the name.',
      solution: STUDY + 'm <- round(cor(study[, c("hours", "phone", "sleep", "score")]), 2)',
      tests: [['m is the 4 by 4 correlation matrix', 'is.matrix(m) && isTRUE(all.equal(m, round(cor(study[, c("hours", "phone", "sleep", "score")]), 2)))']],
    }),
    task('medium', 'The strongest link', {
      prompt: 'Make `strongest` the name of the column (hours, phone or sleep) most strongly linked to score, either way.',
      starter: STUDY,
      hint: 'Work out the three correlations with score in a named vector, then take the name of the largest `abs()`.',
      solution: STUDY + 'r <- c(hours = cor(study$hours, study$score), phone = cor(study$phone, study$score), sleep = cor(study$sleep, study$score))\nstrongest <- names(which.max(abs(r)))',
      tests: [['strongest is "hours"', 'identical(strongest, "hours")']],
    }),
    task('medium', 'Ranks instead', {
      prompt: 'Make `rho` the Spearman (rank) correlation between hours and score, rounded to 2 decimal places.',
      starter: STUDY,
      hint: '`cor(..., method = "spearman")`',
      solution: STUDY + 'rho <- round(cor(study$hours, study$score, method = "spearman"), 2)',
      tests: [['rho is 0.9', near('rho', 0.9)]],
    }),
    task('hard', 'One outlier', {
      prompt: 'Make `before` the correlation of `x` and `y`, then change the last `y` to 30 and make `after` the new correlation, both rounded to 2 decimal places.',
      starter: 'x <- c(1, 2, 3, 4, 5, 6)\ny <- c(2, 4, 5, 4, 5, 6)\n',
      hint: '`before <- round(cor(x, y), 2)`, then `y[6] <- 30`, then `after <- round(cor(x, y), 2)`.',
      solution: 'x <- c(1, 2, 3, 4, 5, 6)\ny <- c(2, 4, 5, 4, 5, 6)\nbefore <- round(cor(x, y), 2)\ny[6] <- 30\nafter <- round(cor(x, y), 2)',
      tests: [['before is 0.86', near('before', 0.86)], ['after is 0.71', near('after', 0.71)]],
    }),
    task('hard', 'Without one student', {
      prompt: 'Make `r_without` the correlation between `hours` and `score` with Cy left out.',
      starter: STUDY,
      hint: 'Keep the other rows first: `sub <- study[study$student != "Cy", ]`, then `cor(sub$hours, sub$score)`.',
      solution: STUDY + 'sub <- study[study$student != "Cy", ]\nr_without <- cor(sub$hours, sub$score)',
      tests: [['r_without is right', near('r_without', 'cor(study$hours[study$student != "Cy"], study$score[study$student != "Cy"])')]],
    }),
    task('expert', 'Is it significant?', {
      prompt: 'With only 8 students, a correlation could be luck. `cor.test()` gives a p-value. Make `p` the p-value for hours and score, rounded to 4 decimal places.',
      starter: STUDY,
      hint: '`cor.test(study$hours, study$score)$p.value`',
      solution: STUDY + 'p <- round(cor.test(study$hours, study$score)$p.value, 4)',
      tests: [['p is 0.0009', near('p', 9e-04)]],
    }),
    task('expert', 'Strongest link first', {
      prompt: 'Make `links` the correlations of `score` with `hours`, `phone` and `sleep`, named, with the strongest (largest in size, plus or minus) first.',
      starter: STUDY,
      hint: '`r <- cor(study[c("hours", "phone", "sleep")], study$score)[, 1]` gives the three, named. Sort them with `r[order(-abs(r))]`.',
      solution: STUDY + 'r <- cor(study[c("hours", "phone", "sleep")], study$score)[, 1]\nlinks <- r[order(-abs(r))]',
      tests: [['links is in order of strength, with names', same('links', 'local({ r <- sapply(c("hours", "phone", "sleep"), function(v) cor(study[[v]], study$score)); r[order(-abs(r))] })')]],
    }),
  ],
  questions: [
    mc('A correlation of −0.9 means…', ['No link', 'A strong link: when one is high, the other is low', 'A weak positive link', 'An error'], 1,
      'The sign is the direction; the size is the strength.'),
    mc('What does `cor(c(1, 2, 3), c(2, 4, 6))` give?', ['`1`', '`2`', '`0`', '`0.5`'], 0,
      'A perfect straight line going up.',
      { code: 'cor(c(1, 2, 3), c(2, 4, 6))', output: '[1] 1' }),
    mc('Why can one unusual point change a correlation a lot in a small sample?', ['With few points, each one carries a big share of the calculation', 'cor() ignores the others', 'Outliers are counted twice', 'It can\'t'], 0,
      'Plot the data, or compare with `method = "spearman"`.'),
    mc('Revision hours and scores have r = 0.93. What can you say?', ['Revising causes higher scores', 'They go together strongly; the reason needs more evidence', 'They are unrelated', 'Every student who revises scores 93'], 1,
      'Correlation is not causation.'),
    mc('Which range can a correlation take?', ['0 to 1', '−1 to 1', '0 to 100', 'Any number'], 1,
      '±1 is a perfect straight line.'),
    mc('Why use `method = "spearman"`?', ['It is always bigger', 'It uses ranks, so one unusual value has less pull', 'It works on text', 'It gives p-values'], 1,
      'Ranks don\'t care how far out an outlier is.'),
    mc('What does `cor()` give for a data frame of numbers?', ['One number', 'A matrix of the correlation of every pair of columns', 'An error', 'A list'], 1,
      'The diagonal is always 1: each column with itself.'),
    mc('A correlation near 0 means…', ['No link of any kind', 'No **straight-line** link; there could still be a curved one', 'A perfect link', 'Missing values'], 1,
      'A U-shape can have r near 0.',
      { code: 'x <- -3:3\nround(cor(x, x^2), 2)', output: '[1] 0' }),
    qShort('Which function measures how two numeric vectors move together?', 'cor',
      '`cor(x, y)`'),
  ],
})
