      hint: '`squares <- sapply(1:6, \\(n) n ^ 2)`',
      solution: 'squares <- sapply(1:6, \\(n) n ^ 2)',
      tests: [['squares is 1, 4, 9, 16, 25, 36', near('squares', 'c(1, 4, 9, 16, 25, 36)')], ['Uses sapply()', uses('sapply(')]],
