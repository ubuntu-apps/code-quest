// Types, text and factors: Converting types.
import { code, isText, isTexts, makeTopic, mc, near, qShort, same, snippet, task, uses } from '../_builders.mjs'

export default makeTopic({
  id: 'converting',
  title: 'Converting types',
  paragraphs: [
    'Data often arrives as the wrong type. A spreadsheet column of prices might come in as text, or a code like `"007"` might come in as a number. The `as.` functions convert values:',
    '| Function | Turns into | Example | Result |\n| --- | --- | --- | --- |\n| `as.numeric()` | a number | `as.numeric("4.5")` | `4.5` |\n| `as.integer()` | a whole number | `as.integer(3.9)` | `3` |\n| `as.character()` | text | `as.character(42)` | `"42"` |\n| `as.logical()` | TRUE/FALSE | `as.logical("TRUE")` | `TRUE` |',
    'They work on whole vectors, so one call fixes a whole column: `as.numeric(c("12", "8", "15"))` is `12 8 15`.',
    'When a value can\'t be converted, you get `NA` and a warning, "NAs introduced by coercion". That is useful: it finds the values that aren\'t really numbers.',
    code('as.numeric(c("12", "8", "n/a", "15"))   # 12 8 NA 15, with a warning'),
    'Two surprises. `as.integer()` doesn\'t round, it cuts off the decimals: `as.integer(3.9)` is 3. And `as.logical()` understands `"TRUE"`, `"true"`, `"T"` and `"FALSE"`, but not `"yes"`, and turns the numbers 0 and 1 into FALSE and TRUE.',
    'Converting to text and back loses nothing for simple numbers, but leading zeros vanish when text becomes a number: `as.numeric("007")` is 7. That\'s why codes such as postcodes or IDs should stay as text.',
  ],
  sandboxCode: 'as.numeric("4.5")\nas.numeric(c("12", "8", "n/a", "15"))\nas.integer(3.9)\nas.character(42)\nas.logical(c(0, 1))',
  sandboxSnippets: [
    snippet('Lost zeros', 'as.numeric("007")\nas.character(7)'),
    snippet('Text to TRUE/FALSE', 'as.logical(c("TRUE", "true", "T", "yes"))'),
    snippet('Find the odd ones', 'raw <- c("12", "8", "n/a", "15", "?")\nnums <- suppressWarnings(as.numeric(raw))\nraw[is.na(nums)]'),
  ],
  readMore: { label: 'R documentation: as.numeric()', url: 'https://stat.ethz.ch/R-manual/R-devel/library/base/html/numeric.html', source: 'R documentation' },
  challenges: [
    task('easy', 'Text to numbers', {
      prompt: 'The prices came in as text. Make `prices` a numeric vector of the same values.',
      starter: 'prices_text <- c("2.5", "3.4", "4.2")\n',
      hint: '`prices <- as.numeric(prices_text)`',
      solution: 'prices_text <- c("2.5", "3.4", "4.2")\nprices <- as.numeric(prices_text)',
      tests: [
        ['prices is 2.5, 3.4, 4.2', near('prices', 'c(2.5, 3.4, 4.2)')],
        ['Uses as.numeric()', uses('as.numeric(')],
      ],
    }),
    task('easy', 'Numbers to text', {
      prompt: 'Make `labels` the table numbers as text.',
      starter: 'tables <- c(1, 2, 3)\n',
      hint: '`labels <- as.character(tables)`',
      solution: 'tables <- c(1, 2, 3)\nlabels <- as.character(tables)',
      tests: [['labels is "1" "2" "3"', isTexts('labels', '1', '2', '3')]],
    }),
    task('easy', 'Now it adds up', {
      prompt: 'Make `total` the total of the visits, which came in as text.',
      starter: 'visits <- c("41", "38", "52")\n',
      hint: 'Convert first, then add: `total <- sum(as.numeric(visits))`.',
      solution: 'visits <- c("41", "38", "52")\ntotal <- sum(as.numeric(visits))',
      tests: [['total is 131', near('total', 131)]],
    }),
    task('medium', 'Whole boxes', {
      prompt: 'Make `full_boxes` the number of full boxes, by cutting the decimals off `boxes` with `as.integer()`.',
      starter: 'boxes <- 50 / 6\n',
      hint: '`full_boxes <- as.integer(boxes)`. It cuts off the decimals rather than rounding.',
      solution: 'boxes <- 50 / 6\nfull_boxes <- as.integer(boxes)',
      tests: [['full_boxes is 8', 'identical(full_boxes, 8L)']],
    }),
    task('medium', 'Spot the bad values', {
      prompt: 'Convert `raw` to numbers in `amounts`. Values that aren\'t numbers become NA. Then make `n_bad` how many there were.',
      starter: 'raw <- c("12", "8", "n/a", "15", "?")\n',
      hint: '`amounts <- as.numeric(raw)` (you will see a warning), then `n_bad <- sum(is.na(amounts))`.',
      solution: 'raw <- c("12", "8", "n/a", "15", "?")\namounts <- as.numeric(raw)\nn_bad <- sum(is.na(amounts))',
      tests: [
        ['amounts is 12, 8, NA, 15, NA', same('amounts', 'c(12, 8, NA, 15, NA)')],
        ['n_bad is 2', near('n_bad', 2)],
      ],
    }),
    task('medium', 'Yes or no', {
      prompt: 'Make `answered` TRUE or FALSE for each value: 1 means answered, 0 means not.',
      starter: 'codes <- c(1, 0, 0, 1, 1)\n',
      hint: '`answered <- as.logical(codes)`',
      solution: 'codes <- c(1, 0, 0, 1, 1)\nanswered <- as.logical(codes)',
      tests: [['answered is TRUE FALSE FALSE TRUE TRUE', same('answered', 'c(TRUE, FALSE, FALSE, TRUE, TRUE)')]],
    }),
    task('hard', 'Which values were bad', {
      prompt: 'Make `bad` the original texts that couldn\'t be turned into numbers.',
      starter: 'raw <- c("12", "8", "n/a", "15", "?")\namounts <- suppressWarnings(as.numeric(raw))\n',
      hint: 'Pick from `raw` where `amounts` is NA: `raw[is.na(amounts)]`.',
      solution: 'raw <- c("12", "8", "n/a", "15", "?")\namounts <- suppressWarnings(as.numeric(raw))\nbad <- raw[is.na(amounts)]',
      tests: [['bad is "n/a" "?"', isTexts('bad', 'n/a', '?')]],
    }),
    task('expert', 'Keep the zeros', {
      prompt: 'Member IDs were stored as numbers and lost their leading zeros. Make `ids` the IDs as 4-character text, such as `"0042"`, using `sprintf("%04d", …)`.',
      starter: 'id_numbers <- c(42, 7, 1350)\n',
      hint: '`%04d` means "a whole number, 4 characters wide, padded with zeros": `ids <- sprintf("%04d", id_numbers)`.',
      solution: 'id_numbers <- c(42, 7, 1350)\nids <- sprintf("%04d", id_numbers)',
      tests: [
        ['ids is "0042" "0007" "1350"', isTexts('ids', '0042', '0007', '1350')],
        ['Uses sprintf()', uses('sprintf(')],
      ],
    }),
  ],
  questions: [
    mc('What does `as.numeric("4.5") * 2` give?', ['An error', '`9`', '`"9"`', '`4.54.5`'], 1,
      'Once converted, it is a number you can multiply.',
      { code: 'as.numeric("4.5") * 2', output: '[1] 9' }),
    mc('What does `as.numeric("abc")` give?', ['`0`', 'An error', '`NA`, with a warning', '`"abc"`'], 2,
      'Text that isn\'t a number becomes NA, and R warns you.',
      { code: 'suppressWarnings(as.numeric("abc"))', output: '[1] NA' }),
    mc('What does `as.integer(3.9)` give?', ['`4`', '`3`', '`3.9`', '`NA`'], 1,
      '`as.integer()` cuts off the decimals; it doesn\'t round.',
      { code: 'as.integer(3.9)', output: '[1] 3' }),
    mc('What does `as.numeric("007")` give?', ['`7`', '`007`', '`"007"`', '`NA`'], 0,
      'As a number, the leading zeros are lost.',
      { code: 'as.numeric("007")', output: '[1] 7' }),
    mc('What does `as.logical(c(0, 1, 2))` give?', ['`[1] FALSE  TRUE  TRUE`', '`[1] FALSE TRUE NA`', '`[1] 0 1 2`', 'An error'], 0,
      '0 becomes FALSE, and any other number becomes TRUE.',
      { code: 'as.logical(c(0, 1, 2))', output: '[1] FALSE  TRUE  TRUE' }),
    mc('What does `as.logical("yes")` give?', ['`TRUE`', '`FALSE`', '`NA`', 'An error'], 2,
      '`as.logical()` knows "TRUE", "true" and "T", but not "yes".',
      { code: 'as.logical("yes")', output: '[1] NA' }),
    mc('What does `as.character(3.50)` give?', ['`"3.50"`', '`"3.5"`', '`3.5`', '`"3"`'], 1,
      'R drops trailing zeros when it turns a number into text.',
      { code: 'as.character(3.50)', output: '[1] "3.5"' }),
    mc('What does `sprintf("%04d", 42)` give?', ['`"42"`', '`"0042"`', '`"4200"`', '`42`'], 1,
      '`%04d` pads a whole number with zeros to 4 characters.',
      { code: 'sprintf("%04d", 42)', output: '[1] "0042"' }),
    qShort('Which function turns text like "4.5" into a number?', 'as.numeric',
      '`as.numeric()` converts to a number, giving NA for values that aren\'t numbers.'),
  ],
})
