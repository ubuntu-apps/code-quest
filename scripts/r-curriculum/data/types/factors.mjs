// Types, text and factors: Factors.
import { code, isTexts, makeTopic, mc, near, qShort, snippet, task, uses } from '../_builders.mjs'

export default makeTopic({
  id: 'factors',
  title: 'Factors',
  paragraphs: [
    'Much data is a choice from a short, fixed list: a T-shirt size, a ticket type, a rating from "poor" to "great". R has a special type for this, the **factor**. A factor stores the values together with the list of allowed values, called its **levels**.',
    code('sizes <- factor(c("M", "S", "L", "M", "M"))', 'sizes', 'levels(sizes)    # "L" "M" "S"'),
    'R shows the values without quotes, then the levels underneath. By default the levels are sorted alphabetically, which is rarely the natural order. Give the order yourself with `levels =`:',
    code('sizes <- factor(c("M", "S", "L", "M", "M"), levels = c("S", "M", "L"))', 'levels(sizes)    # "S" "M" "L"'),
    'Why bother? The level order is used everywhere later: in counts, summaries and charts, S, M, L comes out in a sensible order instead of L, M, S. Levels also show categories that have no values yet, which matters when you count them.',
    'A value that isn\'t one of the levels becomes `NA`, which catches typos: `factor(c("S", "XL"), levels = c("S", "M", "L"))` gives `S <NA>`. `nlevels()` counts the levels, and `as.character()` turns a factor back into plain text.',
    'For categories that have a real order, such as ratings, use `ordered = TRUE`. Then comparisons work: `rating > "ok"` is TRUE for "good" and "great".',
  ],
  sandboxCode: 'sizes <- factor(c("M", "S", "L", "M", "M"))\nsizes\nlevels(sizes)\nsizes <- factor(c("M", "S", "L", "M", "M"), levels = c("S", "M", "L"))\nlevels(sizes)',
  sandboxSnippets: [
    snippet('Typos become NA', 'factor(c("S", "XL", "M"), levels = c("S", "M", "L"))'),
    snippet('An ordered factor', 'rating <- factor(c("good", "poor", "great"), levels = c("poor", "ok", "good", "great"), ordered = TRUE)\nrating\nrating > "ok"'),
    snippet('Back to text', 'sizes <- factor(c("M", "S"))\nas.character(sizes)\nnlevels(sizes)'),
  ],
  readMore: { label: 'R documentation: factor()', url: 'https://stat.ethz.ch/R-manual/R-devel/library/base/html/factor.html', source: 'R documentation' },
  challenges: [
    task('easy', 'Make a factor', {
      prompt: 'Make `tickets` a factor of the ticket types.',
      starter: 'types <- c("adult", "child", "adult", "senior", "child")\n',
      hint: '`tickets <- factor(types)`',
      solution: 'types <- c("adult", "child", "adult", "senior", "child")\ntickets <- factor(types)',
      tests: [
        ['tickets is a factor', 'is.factor(tickets)'],
        ['tickets has the five values', 'identical(as.character(tickets), types)'],
      ],
    }),
    task('easy', 'The levels', {
      prompt: 'Make `kinds` the levels of the `tickets` factor.',
      starter: 'tickets <- factor(c("adult", "child", "adult", "senior", "child"))\n',
      hint: '`kinds <- levels(tickets)`',
      solution: 'tickets <- factor(c("adult", "child", "adult", "senior", "child"))\nkinds <- levels(tickets)',
      tests: [['kinds is adult, child, senior', isTexts('kinds', 'adult', 'child', 'senior')]],
    }),
    task('easy', 'How many levels', {
      prompt: 'Make `n_sizes` the number of different sizes in the factor, using a function.',
      starter: 'sizes <- factor(c("M", "S", "L", "M", "XL", "S"))\n',
      hint: '`n_sizes <- nlevels(sizes)`',
      solution: 'sizes <- factor(c("M", "S", "L", "M", "XL", "S"))\nn_sizes <- nlevels(sizes)',
      tests: [
        ['n_sizes is 4', near('n_sizes', 4)],
        ['Uses nlevels()', uses('nlevels(')],
      ],
    }),
    task('medium', 'A sensible order', {
      prompt: 'Make `sizes` a factor with the levels in the order S, M, L.',
      starter: 'orders <- c("M", "S", "L", "M", "M")\n',
      hint: '`sizes <- factor(orders, levels = c("S", "M", "L"))`',
      solution: 'orders <- c("M", "S", "L", "M", "M")\nsizes <- factor(orders, levels = c("S", "M", "L"))',
      tests: [
        ['sizes has levels S, M, L', 'is.factor(sizes) && identical(levels(sizes), c("S", "M", "L"))'],
        ['sizes has the five orders', 'identical(as.character(sizes), orders)'],
      ],
    }),
    task('medium', 'Catch the typo', {
      prompt: 'Make `sizes` a factor with levels S, M and L, then make `n_bad` the number of values that weren\'t one of them.',
      starter: 'orders <- c("M", "S", "LL", "M", "m")\n',
      hint: 'Values outside the levels become NA: `n_bad <- sum(is.na(sizes))`.',
      solution: 'orders <- c("M", "S", "LL", "M", "m")\nsizes <- factor(orders, levels = c("S", "M", "L"))\nn_bad <- sum(is.na(sizes))',
      tests: [
        ['sizes has levels S, M, L', 'is.factor(sizes) && identical(levels(sizes), c("S", "M", "L"))'],
        ['n_bad is 2', near('n_bad', 2)],
      ],
    }),
    task('medium', 'Back to text', {
      prompt: 'Make `as_text` the values of the factor as plain text.',
      starter: 'tickets <- factor(c("adult", "child", "adult"))\n',
      hint: '`as_text <- as.character(tickets)`',
      solution: 'tickets <- factor(c("adult", "child", "adult"))\nas_text <- as.character(tickets)',
      tests: [['as_text is adult, child, adult', isTexts('as_text', 'adult', 'child', 'adult')]],
    }),
    task('hard', 'An ordered rating', {
      prompt: 'Make `rating` an **ordered** factor with the levels `poor`, `ok`, `good`, `great`, in that order.',
      starter: 'answers <- c("good", "poor", "great", "ok", "good")\n',
      hint: '`factor(answers, levels = c("poor", "ok", "good", "great"), ordered = TRUE)`',
      solution: 'answers <- c("good", "poor", "great", "ok", "good")\nrating <- factor(answers, levels = c("poor", "ok", "good", "great"), ordered = TRUE)',
      tests: [
        ['rating is ordered', 'is.ordered(rating)'],
        ['rating has the levels poor, ok, good, great', 'identical(levels(rating), c("poor", "ok", "good", "great"))'],
      ],
    }),
    task('expert', 'Better than ok', {
      prompt: 'Make `happy` the number of ratings better than `"ok"`, comparing the ordered factor with `"ok"`.',
      starter: 'answers <- c("good", "poor", "great", "ok", "good")\nrating <- factor(answers, levels = c("poor", "ok", "good", "great"), ordered = TRUE)\n',
      hint: 'Ordered factors can be compared: `happy <- sum(rating > "ok")`.',
      solution: 'answers <- c("good", "poor", "great", "ok", "good")\nrating <- factor(answers, levels = c("poor", "ok", "good", "great"), ordered = TRUE)\nhappy <- sum(rating > "ok")',
      tests: [
        ['happy is 3', near('happy', 3)],
        ['Compares the factor', uses('rating >')],
      ],
    }),
  ],
  questions: [
    mc('What does `levels(factor(c("b", "a", "b")))` give?', ['`[1] "b" "a"`', '`[1] "a" "b"`', '`[1] "b" "a" "b"`', '`[1] 2`'], 1,
      'By default the levels are sorted alphabetically, each once.',
      { code: 'levels(factor(c("b", "a", "b")))', output: '[1] "a" "b"' }),
    mc('What does `nlevels(factor(c("b", "a", "b")))` give?', ['`3`', '`2`', '`1`', '`"a" "b"`'], 1,
      'There are two different values, so two levels.',
      { code: 'nlevels(factor(c("b", "a", "b")))', output: '[1] 2' }),
    mc('What does `factor(c("S", "XL"), levels = c("S", "M", "L"))` give for "XL"?', ['`XL`', '`NA`', '`L`', 'An error'], 1,
      'A value that isn\'t one of the levels becomes NA.',
      { code: 'as.character(factor(c("S", "XL"), levels = c("S", "M", "L")))[2]', output: '[1] NA' }),
    mc('What does `levels(factor(c("M", "S"), levels = c("S", "M", "L")))` give?', ['`[1] "M" "S"`', '`[1] "S" "M" "L"`', '`[1] "L" "M" "S"`', '`[1] "S" "M"`'], 1,
      'The levels you give are kept, in your order, even "L", which has no values.',
      { code: 'levels(factor(c("M", "S"), levels = c("S", "M", "L")))', output: '[1] "S" "M" "L"' }),
    mc('What does `class(factor(c("a", "b")))` give?', ['`"character"`', '`"factor"`', '`"levels"`', '`"integer"`'], 1,
      'A factor is its own type.',
      { code: 'class(factor(c("a", "b")))', output: '[1] "factor"' }),
    mc('What does `as.character(factor(c("x", "y")))` give?', ['`[1] "x" "y"`', '`[1] 1 2`', '`[1] x y`', 'An error'], 0,
      'It gives the values back as plain text.',
      { code: 'as.character(factor(c("x", "y")))', output: '[1] "x" "y"' }),
    mc('For an ordered factor with levels poor < ok < good, what does `rating > "ok"` give for `"good"`?', ['`FALSE`', '`TRUE`', '`NA`', 'An error'], 1,
      'In an ordered factor, "good" comes after "ok".',
      { code: 'factor("good", levels = c("poor", "ok", "good"), ordered = TRUE) > "ok"', output: '[1] TRUE' }),
    mc('Why give a factor its levels in an order like S, M, L?', ['It saves memory', 'Counts, summaries and charts then come out in that order', 'R needs it to make a factor', 'It sorts the values'], 1,
      'Without it, levels are alphabetical: L, M, S.'),
    qShort('Which function gives the allowed values of a factor?', 'levels',
      '`levels(f)` lists them, in order.'),
  ],
})
