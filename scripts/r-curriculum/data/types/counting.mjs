      starter: 'customers <- c("Ana", "Ben", "Ana", "Cy", "Dee", "Ben", "Ana")\n',
      hint: 'Count with `table()`, keep the counts over 1, and take their names: `names(counts[counts > 1])`.',
      solution: 'customers <- c("Ana", "Ben", "Ana", "Cy", "Dee", "Ben", "Ana")\ncounts <- table(customers)\nregulars <- names(counts[counts > 1])',
