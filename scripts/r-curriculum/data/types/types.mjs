// Types, text and factors: Types and class().
import { code, isText, isTexts, makeTopic, mc, near, qShort, snippet, task, uses } from '../_builders.mjs'

export default makeTopic({
  id: 'types',
  title: 'Types and class()',
  paragraphs: [
    'Every value in R has a **type**, and the type decides what you can do with it. You can add numbers but not text; you can count TRUEs but not words. Most surprises in data analysis come from a value having a different type than you thought.',
    'The four types you will meet all the time:',
    '| Type | Examples | `class()` gives |\n| --- | --- | --- |\n| numbers with decimals | `4.5`, `-2`, `1e6` | `"numeric"` |\n| whole numbers | `5L`, `1:3` | `"integer"` |\n| text | `"kale"`, `"42"` | `"character"` |\n| TRUE/FALSE | `TRUE`, `x > 3` | `"logical"` |',
    '`class()` tells you the type of a value or a vector. Use it whenever something doesn\'t behave as you expect:',
    code('class(4.5)        # "numeric"', 'class("4.5")      # "character": the quotes make it text', 'class(1:3)        # "integer"', 'class(TRUE)       # "logical"'),
    'Plain numbers like `5` are "numeric", even without decimals. An `L` after a number (`5L`) makes an **integer**, a whole number stored as such. Sequences made with `:` are integers too. In practice numeric and integer work the same for maths.',
    'There are also yes/no checks for each type: `is.numeric()`, `is.character()` and `is.logical()`. `is.numeric()` is TRUE for integers too.',
    'Remember from the vectors quest: a vector holds one type. Mix types in `c()` and R picks the type that can hold everything: logical becomes numeric, and numeric becomes character. So `c(1, TRUE)` is `1 1`, and `c(1, "a")` is `"1" "a"`.',
  ],
  sandboxCode: 'class(4.5)\nclass("4.5")\nclass(1:3)\nclass(TRUE)\nclass(c(1, "a"))',
  sandboxSnippets: [
    snippet('Is it a number?', 'is.numeric(42)\nis.numeric("42")\nis.character("42")'),
    snippet('Mixing types', 'c(1, TRUE, FALSE)\nc(1, "a", TRUE)'),
    snippet('Integers', 'class(5)\nclass(5L)\nclass(1:10)'),
    snippet('Ask before you use it', 'x <- "18.5"\nclass(x)\nis.numeric(x)\nis.character(x)'),
  ],
  readMore: { label: 'R documentation: class()', url: 'https://stat.ethz.ch/R-manual/R-devel/library/base/html/class.html', source: 'R documentation' },
  challenges: [
    task('easy', 'What type is it', {
      prompt: 'Make `kind` the class of the value in `reading`, using a function.',
      starter: 'reading <- "18.5"\n',
      hint: '`kind <- class(reading)`. The quotes matter.',
      solution: 'reading <- "18.5"\nkind <- class(reading)',
      tests: [
        ['kind is "character"', isText('kind', 'character')],
        ['Uses class()', uses('class(')],
      ],
    }),
    task('easy', 'A number, not text', {
      typedOk: true,
      prompt: 'Make `price` the number 3.4 (not text), so that `class(price)` is `"numeric"`.',
      starter: 'price <- "3.4"\n',
      hint: 'Remove the quotes.',
      solution: 'price <- 3.4',
      tests: [['price is the number 3.4', near('price', 3.4)]],
    }),
    task('easy', 'An integer', {
      prompt: 'Make `guests` the whole number 12, stored as an integer.',
      hint: 'Add an `L`: `guests <- 12L`.',
      solution: 'guests <- 12L',
      tests: [['guests is the integer 12', 'identical(guests, 12L)']],
    }),
    task('medium', 'Check before you add', {
      prompt: 'Make `can_add` the answer to: is `amount` a number?',
      starter: 'amount <- "250"\n',
      hint: '`can_add <- is.numeric(amount)`',
      solution: 'amount <- "250"\ncan_add <- is.numeric(amount)',
      tests: [
        ['can_add is FALSE', 'identical(can_add, FALSE)'],
        ['Uses is.numeric()', uses('is.numeric(')],
      ],
    }),
    task('medium', 'Types of three vectors', {
      typedOk: true,
      prompt: 'Make `kinds` a vector of the classes of `weights`, `codes` and `heavy`, in that order.',
      starter: 'weights <- c(2, 4, 6)\ncodes <- c("2", "4")\nheavy <- weights > 3\n',
      hint: '`kinds <- c(class(weights), class(codes), class(heavy))`',
      solution: 'weights <- c(2, 4, 6)\ncodes <- c("2", "4")\nheavy <- weights > 3\nkinds <- c(class(weights), class(codes), class(heavy))',
      tests: [['kinds is numeric, character, logical', isTexts('kinds', 'numeric', 'character', 'logical')]],
    }),
    task('medium', 'Why won\'t it add up', {
      prompt: 'One value in the vector is in quotes, so the whole vector is text and `sum()` fails. Fix the first line so `total` works out.',
      starter: 'sales <- c(12, 8, "15", 10)\ntotal <- sum(sales)',
      hint: 'Run `class(sales)` to see the problem, then remove the quotes around 15.',
      solution: 'sales <- c(12, 8, 15, 10)\ntotal <- sum(sales)',
      tests: [['total is 45', near('total', 45)]],
    }),
    task('hard', 'Mixed together', {
      prompt: 'Make `mixed` the result of combining the number `1`, `TRUE` and the text `"a"` with `c()`, then make `mixed_class` its class.',
      hint: '`mixed <- c(1, TRUE, "a")` and `mixed_class <- class(mixed)`. Predict the answer first.',
      solution: 'mixed <- c(1, TRUE, "a")\nmixed_class <- class(mixed)',
      tests: [
        ['mixed is "1" "TRUE" "a"', isTexts('mixed', '1', 'TRUE', 'a')],
        ['mixed_class is "character"', isText('mixed_class', 'character')],
      ],
    }),
    task('hard', 'Total from text', {
      prompt: 'The counts came in as text. Make `total` their sum as a number.',
      starter: 'counts <- c("12", "7", "15")\n',
      hint: 'Turn them into numbers first: `sum(as.numeric(counts))`.',
      solution: 'counts <- c("12", "7", "15")\ntotal <- sum(as.numeric(counts))',
      tests: [['total is 34', near('total', 34)]],
    }),
    task('expert', 'Count the yes answers', {
      alt: 'answers <- c(FALSE, FALSE, TRUE, FALSE, FALSE, TRUE)\n',
      prompt: 'Make `n_yes` the number of TRUE values in `answers`. Use `class()` in your head first: TRUE and FALSE count as 1 and 0.',
      starter: 'answers <- c(TRUE, FALSE, TRUE, TRUE, FALSE, TRUE)\n',
      hint: '`n_yes <- sum(answers)`',
      solution: 'answers <- c(TRUE, FALSE, TRUE, TRUE, FALSE, TRUE)\nn_yes <- sum(answers)',
      tests: [['n_yes is 4', near('n_yes', 4)]],
    }),
    task('expert', 'Name the types', {
      prompt: 'Make `kinds` a vector with the class of `a`, then `b`, then `flag`.',
      starter: 'a <- "4"\nb <- 2.5\nflag <- TRUE\n',
      alt: 'a <- 4L\nb <- "2.5"\nflag <- 3\n',
      hint: '`class()` gives one text each; put them together with `c()`.',
      solution: 'a <- "4"\nb <- 2.5\nflag <- TRUE\nkinds <- c(class(a), class(b), class(flag))',
      tests: [['kinds is character, numeric, logical', isTexts('kinds', 'character', 'numeric', 'logical')]],
    }),
  ],
  questions: [
    mc('What does `class("42")` give?', ['`"numeric"`', '`"character"`', '`"integer"`', '`"text"`'], 1,
      'The quotes make it text, which R calls "character".',
      { code: 'class("42")', output: '[1] "character"' }),
    mc('What does `class(42)` give?', ['`"numeric"`', '`"integer"`', '`"number"`', '`"double"`'], 0,
      'Plain numbers are "numeric", with or without decimals.',
      { code: 'class(42)', output: '[1] "numeric"' }),
    mc('What does `class(1:5)` give?', ['`"numeric"`', '`"sequence"`', '`"integer"`', '`"vector"`'], 2,
      'Sequences made with `:` are integers.',
      { code: 'class(1:5)', output: '[1] "integer"' }),
    mc('What does `class(3 > 2)` give?', ['`"logical"`', '`"numeric"`', '`"character"`', '`"TRUE"`'], 0,
      'A comparison gives TRUE or FALSE, which are logical values.',
      { code: 'class(3 > 2)', output: '[1] "logical"' }),
    mc('Why does `c(1, TRUE, FALSE)` give `[1] 1 1 0`?', ['A vector has one type, so TRUE becomes 1 and FALSE becomes 0 to fit with the number', 'TRUE is short for 1', 'R rounds them', 'It is a bug'], 0,
      'That is also why `sum()` of TRUE/FALSE values counts the TRUEs.',
      { code: 'c(1, TRUE, FALSE)', output: '[1] 1 1 0' }),
    mc('What does `class(c(2, "b"))` give?', ['`"numeric"`', '`"mixed"`', '`"character"`', 'An error'], 2,
      'Mixed with text, everything becomes text.',
      { code: 'class(c(2, "b"))', output: '[1] "character"' }),
    mc('What does `is.numeric(7L)` give?', ['`TRUE`', '`FALSE`', '`NA`', 'An error'], 0,
      'Integers are numbers too.',
      { code: 'is.numeric(7L)', output: '[1] TRUE' }),
    mc('What does `sum(c(TRUE, TRUE, FALSE))` give?', ['`TRUE`', '`2`', '`3`', 'An error'], 1,
      'TRUE counts as 1 and FALSE as 0.',
      { code: 'sum(c(TRUE, TRUE, FALSE))', output: '[1] 2' }),
    qShort('Which function tells you the type of a value, such as "numeric" or "character"?', 'class',
      '`class(x)` gives the type.'),
  ],
})
