// Reshaping and combining: Sets and match().
import { code, isTexts, makeTopic, mc, near, qShort, same, sameFrame, snippet, task, uses } from '../_builders.mjs'

const CLUBS = 'chess <- c("Ana", "Ben", "Cy")\nchoir <- c("Cy", "Dee", "Ana", "Eli")\n'
const MENU = 'menu <- data.frame(drink = c("latte", "tea", "mocha", "chai"), price = c(3.4, 2.5, 4.2, 3.8))\norders <- c("tea", "latte", "latte", "flat white", "chai")\n'

export default makeTopic({
  id: 'sets_and_match',
  title: 'Sets and match()',
  paragraphs: [
    'Before combining tables, and after, you often ask questions about **sets** of values: who is in both clubs, which codes are new, which orders aren\'t on the menu. R has a function for each:',
    code(...CLUBS.trim().split('\n'), 'union(chess, choir)        # in either: Ana Ben Cy Dee Eli', 'intersect(chess, choir)    # in both: Ana Cy', 'setdiff(chess, choir)      # in chess but not choir: Ben'),
    'Each gives every value once, in the order it first appears. `setdiff()` is one-sided: `setdiff(choir, chess)` is Dee and Eli.',
    '`match(x, table)` gives, for each value of `x`, its **position** in `table`, or NA if it isn\'t there. That makes it a quick lookup: use the positions to pick from another column of the same table.',
    code(...MENU.trim().split('\n'), 'match(orders, menu$drink)                  # 2 1 1 NA 4', 'menu$price[match(orders, menu$drink)]      # the price of each order'),
    'This is what `merge()` does under the hood, but `match()` keeps the orders in their own order, one result per order, with NA for anything unknown, which makes the gaps easy to find.',
  ],
  sandboxCode: CLUBS + 'union(chess, choir)\nintersect(chess, choir)\nsetdiff(chess, choir)',
  sandboxSnippets: [snippet('Look up prices', MENU + 'pos <- match(orders, menu$drink)\npos\nmenu$price[pos]'), snippet('Either but not both', CLUBS + 'setdiff(union(chess, choir), intersect(chess, choir))'), snippet('Reorder with match()', MENU + 'wanted <- c("chai", "latte", "tea", "mocha")\nmenu[match(wanted, menu$drink), ]')],
  readMore: { label: 'R documentation: set operations', url: 'https://stat.ethz.ch/R-manual/R-devel/library/base/html/sets.html', source: 'R documentation' },
  challenges: [
    task('easy', 'Everyone', {
      prompt: 'Make `members` everyone in chess or choir, each once.',
      starter: CLUBS,
      hint: '`union(chess, choir)`',
      solution: CLUBS + 'members <- union(chess, choir)',
      tests: [['members is Ana, Ben, Cy, Dee, Eli', isTexts('members', 'Ana', 'Ben', 'Cy', 'Dee', 'Eli')]],
    }),
    task('easy', 'In both', {
      prompt: 'Make `both` the pupils in both clubs.',
      starter: CLUBS,
      hint: '`intersect(chess, choir)`',
      solution: CLUBS + 'both <- intersect(chess, choir)',
      tests: [['both is Ana, Cy', isTexts('both', 'Ana', 'Cy')]],
    }),
    task('easy', 'Choir only', {
      prompt: 'Make `choir_only` the pupils in choir but not chess.',
      starter: CLUBS,
      hint: 'Order matters: `setdiff(choir, chess)`.',
      solution: CLUBS + 'choir_only <- setdiff(choir, chess)',
      tests: [['choir_only is Dee, Eli', isTexts('choir_only', 'Dee', 'Eli')]],
    }),
    task('medium', 'Where on the menu', {
      prompt: 'Make `pos` the position of each order on the menu.',
      starter: MENU,
      hint: '`match(orders, menu$drink)`',
      solution: MENU + 'pos <- match(orders, menu$drink)',
      tests: [['pos is 2, 1, 1, NA, 4', 'identical(pos, c(2L, 1L, 1L, NA, 4L))']],
    }),
    task('medium', 'Price of each order', {
      prompt: 'Make `prices` the price of each order, NA for anything not on the menu.',
      starter: MENU,
      hint: '`menu$price[match(orders, menu$drink)]`',
      solution: MENU + 'prices <- menu$price[match(orders, menu$drink)]',
      tests: [['prices is 2.5, 3.4, 3.4, NA, 3.8', same('prices', 'c(2.5, 3.4, 3.4, NA, 3.8)')], ['Uses match()', uses('match(')]],
    }),
    task('medium', 'Not on the menu', {
      alt: (s) => s.replace('"flat white", "chai")', '"cocoa", "chai")'),
      prompt: 'Make `missing_drinks` the orders that aren\'t on the menu, each once.',
      starter: MENU,
      hint: '`setdiff(orders, menu$drink)`',
      solution: MENU + 'missing_drinks <- setdiff(orders, menu$drink)',
      tests: [['missing_drinks is "flat white"', isTexts('missing_drinks', 'flat white')]],
    }),
    task('hard', 'The bill so far', {
      prompt: 'Make `known_total` the total of the orders that have a price, and `n_unknown` the number of orders without one.',
      starter: MENU,
      hint: 'Look up the prices with `match()`, then `sum(prices, na.rm = TRUE)` and `sum(is.na(prices))`.',
      solution: MENU + 'prices <- menu$price[match(orders, menu$drink)]\nknown_total <- sum(prices, na.rm = TRUE)\nn_unknown <- sum(is.na(prices))',
      tests: [['known_total is 13.1', near('known_total', 13.1)], ['n_unknown is 1', near('n_unknown', 1)]],
    }),
    task('hard', 'In exactly one club', {
      prompt: 'Make `one_club` the people who are in chess or choir, but not both.',
      starter: CLUBS,
      hint: 'Everyone, minus the ones in both: `setdiff(union(chess, choir), intersect(chess, choir))`.',
      solution: CLUBS + 'one_club <- setdiff(union(chess, choir), intersect(chess, choir))',
      tests: [['one_club is Ben, Dee, Eli', isTexts('one_club', 'Ben', 'Dee', 'Eli')]],
    }),
    task('expert', 'Signed up twice?', {
      prompt: 'Two sign-up sheets were typed by different people. Make `on_both` the names that appear on both sheets, after trimming and making them small letters.',
      starter: 'sheet1 <- c("Ana ", "ben", "Cy", "DEE")\nsheet2 <- c("dee", " Eli", "ANA", "Fay")\n',
      hint: 'Clean each sheet with `tolower(trimws())` first, then `intersect()`.',
      solution: 'sheet1 <- c("Ana ", "ben", "Cy", "DEE")\nsheet2 <- c("dee", " Eli", "ANA", "Fay")\non_both <- intersect(tolower(trimws(sheet1)), tolower(trimws(sheet2)))',
      tests: [['on_both is ana, dee', isTexts('on_both', 'ana', 'dee')]],
    }),
    task('expert', 'Menu in a new order', {
      prompt: 'Make `menu2` the menu rows in the order given by `wanted`.',
      starter: MENU + 'wanted <- c("chai", "latte", "tea", "mocha")\n',
      hint: '`match(wanted, menu$drink)` gives the row of each wanted drink. Use it as the rows: `menu[..., ]`.',
      solution: MENU + 'wanted <- c("chai", "latte", "tea", "mocha")\nmenu2 <- menu[match(wanted, menu$drink), ]',
      tests: [['menu2 is chai, latte, tea, mocha', sameFrame('menu2', 'menu[c(4, 1, 2, 3), ]')]],
    }),
  ],
  questions: [
    mc('What does `union(c(1, 2, 2), c(2, 3))` give?', ['`[1] 1 2 3`', '`[1] 1 2 2 2 3`', '`[1] 2`', '`[1] 1 3`'], 0,
      'Everything in either, each once.',
      { code: 'union(c(1, 2, 2), c(2, 3))', output: '[1] 1 2 3' }),
    mc('What does `intersect(c("a", "b", "c"), c("c", "a"))` give?', ['`[1] "a" "c"`', '`[1] "c" "a"`', '`[1] "b"`', '`[1] "a" "b" "c"`'], 0,
      'Values in both, in the order of the first.',
      { code: 'intersect(c("a", "b", "c"), c("c", "a"))', output: '[1] "a" "c"' }),
    mc('Why does `setdiff(a, b)` give a different answer from `setdiff(b, a)`?', ['It keeps what is in the first vector but not the second, so the order matters', 'setdiff() is random', 'It sorts the inputs', 'It doesn\'t'], 0,
      '`union()` and `intersect()` give the same values either way round.'),
    mc('What does `match(c("b", "z"), c("a", "b", "c"))` give?', ['`[1]  2 NA`', '`[1] TRUE FALSE`', '`[1] "b"`', '`[1] 2 0`'], 0,
      'Positions in the table, NA when missing.',
      { code: 'match(c("b", "z"), c("a", "b", "c"))', output: '[1]  2 NA' }),
    mc('How is `match()` different from `%in%`?', ['They are the same', '`%in%` says whether each value is there; `match()` says where', '`match()` only works on numbers', '`%in%` gives positions'], 1,
      '`x %in% t` is the same as `!is.na(match(x, t))`.'),
    mc('Why use `match()` for a lookup instead of `merge()`?', ['It is the only way', 'It keeps one result per value, in the original order, with NA for unknowns', 'It drops unknown values', 'It sorts the result'], 1,
      '`merge()` sorts by the key and, by default, drops unmatched rows.'),
    mc('What does `c(10, 20, 30)[match(c("y", "x"), c("x", "y", "z"))]` give?', ['`[1] 20 10`', '`[1] 10 20`', '`[1] 2 1`', '`[1] 20`'], 0,
      '"y" is at position 2 and "x" at 1.',
      { code: 'c(10, 20, 30)[match(c("y", "x"), c("x", "y", "z"))]', output: '[1] 20 10' }),
    mc('Why clean text before `intersect()`?', ['It is faster', '"Ana " and "ANA" are different texts until they are tidied', 'intersect() needs small letters', 'It isn\'t needed'], 1,
      'Set functions compare exact values.'),
    qShort('Which function gives the values in the first vector that aren\'t in the second?', 'setdiff',
      '`setdiff(a, b)` is one-sided; swap them for the other way.'),
  ],
})
