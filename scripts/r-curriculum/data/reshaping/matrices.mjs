      prompt: 'Make `per_drink` the total of each drink over the week.',
      starter: SALES,
      hint: '`rowSums(sales)`',
      solution: SALES + 'per_drink <- rowSums(sales)',
      tests: [['per_drink is latte 75, tea 41, mocha 33', same('per_drink', 'c(latte = 75, tea = 41, mocha = 33)')]],
