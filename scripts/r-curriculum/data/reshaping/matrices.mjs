  id: 'matrices',
  title: 'Matrices',
  paragraphs: [
    'A **matrix** is a grid of values that are all the same type, with rows and columns. It is like a data frame where every column is numbers, and it is how R stores things like counts by two categories. `matrix()` fills it **column by column** from a vector:',
    code(...SALES.trim().split('\n'), 'sales'),
    '`dimnames` gives the rows and columns names (a list: row names first, then column names). Add `byrow = TRUE` to fill row by row instead. `dim(sales)` gives the size: 3 rows, 5 columns.',
    'Pick values with `[row, column]`, by position or by name, just like a data frame: `sales["tea", "Wed"]`, `sales[1, ]` (a whole row), `sales[, "Fri"]` (a whole column).',
    '| Function | Gives |\n| --- | --- |\n| `rowSums(m)`, `rowMeans(m)` | one value per row |\n| `colSums(m)`, `colMeans(m)` | one value per column |\n| `t(m)` | the matrix turned on its side: rows become columns |\n| `rbind(m, new)`, `cbind(m, new)` | a new row or column added |',
    'Maths on a matrix works value by value, like a vector: `sales * 2` doubles every count. A vector as long as the number of rows is reused down each column, so it lines up with the rows: `sales * c(3.4, 2.5, 4.2)` multiplies each drink\'s counts by its price.',
  ],
