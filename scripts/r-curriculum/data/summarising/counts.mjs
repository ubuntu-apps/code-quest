// Summarising data: Counts and percentages.
import { code, isText, makeTopic, mc, near, prints, qShort, same, snippet, task, uses } from '../_builders.mjs'
import { ORDERS } from '../datasets.mjs'

export default makeTopic({
  id: 'counts_percentages',
  title: 'Counts and percentages',
  paragraphs: [
    'This quest is about **summarising**: turning a table of rows into a few numbers that tell its story. The first question is usually "how many of each?", and for a column of categories, `table()` answers it.',
    code(...ORDERS.trim().split('\n')),
    code('table(orders$drink)', 'table(orders$size)'),
    'Counts are hard to compare between groups of different sizes, so we often report **percentages** instead. `prop.table()` turns counts into shares that add up to 1; multiply by 100 and round:',
    code('round(prop.table(table(orders$drink)) * 100)'),
    'Rounded percentages don\'t always add up to exactly 100. That\'s normal; say so in a report, or show one decimal place instead.',
    'For a TRUE/FALSE question about each row, the share is simply the `mean()`: `mean(orders$price > 3)` is the share of orders over 3, because TRUE counts as 1. Multiply by 100 for a percentage.',
    'Use a factor with ordered levels when the order matters, such as sizes S, M, L: `table(factor(orders$size, levels = c("S", "M", "L")))`.',
  ],
  sandboxCode: ORDERS + 'table(orders$drink)\nround(prop.table(table(orders$drink)) * 100)\nmean(orders$price > 3)',
  sandboxSnippets: [snippet('Sizes in order', ORDERS + 'table(factor(orders$size, levels = c("S", "M", "L")))')],
  readMore: { label: 'R documentation: prop.table()', url: 'https://stat.ethz.ch/R-manual/R-devel/library/base/html/proportions.html', source: 'R documentation' },
  challenges: [
    task('easy', 'Orders per drink', {
      prompt: 'Make `per_drink` a table counting the orders of each drink.',
      starter: ORDERS,
      hint: '`per_drink <- table(orders$drink)`',
      solution: ORDERS + 'per_drink <- table(orders$drink)',
      tests: [['per_drink counts chai 1, latte 4, mocha 2, tea 3', 'identical(as.vector(per_drink), c(1L, 4L, 2L, 3L)) && identical(names(per_drink), c("chai", "latte", "mocha", "tea"))']],
    }),
    task('easy', 'Orders per day', {
      prompt: 'Make `per_day` a table of orders per day, with the days in week order Mon to Fri.',
      starter: ORDERS,
      hint: '`table(factor(orders$day, levels = c("Mon", "Tue", "Wed", "Thu", "Fri")))`',
      solution: ORDERS + 'per_day <- table(factor(orders$day, levels = c("Mon", "Tue", "Wed", "Thu", "Fri")))',
      tests: [['per_day is Mon 2, Tue 3, Wed 2, Thu 1, Fri 2', 'identical(as.vector(per_day), c(2L, 3L, 2L, 1L, 2L)) && identical(names(per_day), c("Mon", "Tue", "Wed", "Thu", "Fri"))']],
    }),
    task('easy', 'Share of lattes', {
      prompt: 'Make `latte_share` the share of orders that were lattes, as a number between 0 and 1.',
      starter: ORDERS,
      hint: '`latte_share <- mean(orders$drink == "latte")`',
      solution: ORDERS + 'latte_share <- mean(orders$drink == "latte")',
      tests: [['latte_share is 0.4', near('latte_share', 0.4)]],
    }),
    task('medium', 'Percent per size', {
      prompt: 'Make `size_pct` the percentage of orders of each size, rounded to whole numbers.',
      starter: ORDERS,
      hint: '`round(prop.table(table(orders$size)) * 100)`',
      solution: ORDERS + 'size_pct <- round(prop.table(table(orders$size)) * 100)',
      tests: [['size_pct is L 30, M 40, S 30', 'identical(as.vector(size_pct), c(30, 40, 30)) && identical(names(size_pct), c("L", "M", "S"))']],
    }),
    task('medium', 'Over three', {
      prompt: 'Make `pct_over_3` the percentage of orders that cost more than 3.',
      starter: ORDERS,
      hint: '`pct_over_3 <- mean(orders$price > 3) * 100`',
      solution: ORDERS + 'pct_over_3 <- mean(orders$price > 3) * 100',
      tests: [['pct_over_3 is 60', near('pct_over_3', 60)]],
    }),
    task('medium', 'The most popular', {
      prompt: 'Make `top_drink` the most ordered drink.',
      starter: ORDERS,
      hint: '`names(which.max(table(orders$drink)))`',
      solution: ORDERS + 'top_drink <- names(which.max(table(orders$drink)))',
      tests: [['top_drink is "latte"', isText('top_drink', 'latte')]],
    }),
    task('hard', 'One decimal place', {
      prompt: 'Make `drink_pct` the percentage of each drink with one decimal place, most popular first.',
      starter: ORDERS,
      hint: 'Round to 1 place, then `sort(…, decreasing = TRUE)`.',
      solution: ORDERS + 'drink_pct <- sort(round(prop.table(table(orders$drink)) * 100, 1), decreasing = TRUE)',
      tests: [['drink_pct is latte 40, tea 30, mocha 20, chai 10', 'identical(as.vector(drink_pct), c(40, 30, 20, 10)) && identical(names(drink_pct), c("latte", "tea", "mocha", "chai"))']],
    }),
    task('expert', 'A sentence for the report', {
      prompt: 'Show `latte: 40% of orders`, working out the drink and the percentage in R.',
      starter: ORDERS,
      hint: 'Find the top drink and its share, then `cat(top, ": ", pct, "% of orders\\n", sep = "")`.',
      solution: ORDERS + 'counts <- table(orders$drink)\ntop <- names(which.max(counts))\npct <- round(max(counts) / sum(counts) * 100)\ncat(top, ": ", pct, "% of orders\\n", sep = "")',
      tests: [['Shows latte: 40% of orders', prints('latte: 40% of orders')], ['Works it out with table()', uses('table(')]],
    }),
  ],
  questions: [
    mc('What does `mean(c(TRUE, FALSE, TRUE, TRUE))` give?', ['`3`', '`0.75`', '`TRUE`', '`0.5`'], 1,
      'Three TRUEs out of four: a share of 0.75.',
      { code: 'mean(c(TRUE, FALSE, TRUE, TRUE))', output: '[1] 0.75' }),
    mc('What do the values of `prop.table(table(x))` add up to?', ['100', '1', 'The number of rows', 'It depends'], 1,
      'They are shares of the whole.',
      { code: 'sum(prop.table(table(c("a", "b", "b"))))', output: '[1] 1' }),
    mc('What does `round(prop.table(table(c("a", "b", "b", "b"))) * 100)` give for "b"?', ['`3`', '`75`', '`0.75`', '`25`'], 1,
      'Three of four values: 75%.',
      { code: 'as.vector(round(prop.table(table(c("a", "b", "b", "b"))) * 100))[2]', output: '[1] 75' }),
    mc('Three groups are 1/3 each. Rounded percentages are 33, 33, 33. Is something wrong?', ['Yes, they must add up to 100', 'No, rounding can make the total 99 or 101', 'Yes, use floor()', 'Yes, prop.table is wrong'], 1,
      'Rounding each value separately can lose or gain a point.'),
    mc('Why report percentages and not just counts?', ['They are always more exact', 'They compare groups of different sizes fairly', 'R needs them', 'Counts can\'t be rounded'], 1,
      '20 of 40 and 30 of 120 are easier to compare as 50% and 25%.'),
    mc('What does `mean(c(2.5, 3.4, 4.2) > 3) * 100` give?', ['`66.7`', '`66.66667`', '`2`', '`3.37`'], 1,
      'Two of three are over 3: 66.67%, shown with R\'s usual 7 digits.',
      { code: 'mean(c(2.5, 3.4, 4.2) > 3) * 100', output: '[1] 66.66667' }),
    mc('What order does `table()` list text values in?', ['The order they appear', 'Alphabetical', 'Most common first', 'Random'], 1,
      'Text is sorted alphabetically, unless it is a factor with its own levels.'),
    mc('Which gives the most common value of `x`?', ['`max(x)`', '`names(which.max(table(x)))`', '`table(x)[1]`', '`mode(x)`'], 1,
      '`mode()` in R tells you the storage type, not the most common value.'),
    qShort('Which function turns a table of counts into shares that add up to 1?', 'prop.table',
      '`prop.table(table(x))`'),
  ],
})
