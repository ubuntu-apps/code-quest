// Summarising data: Spread: sd, IQR and quantile.
import { code, makeTopic, mc, near, qShort, snippet, task, uses } from '../_builders.mjs'
import { DELIVERIES } from '../datasets.mjs'

export default makeTopic({
  id: 'spread',
  title: 'Spread: sd, IQR and quantile',
  paragraphs: [
    'Two bakeries can both average 30 minutes per delivery, one always 28 to 32, the other anywhere from 10 to 60. The centre is the same, the **spread** very different. These measure spread:',
    '| Function | Gives |\n| --- | --- |\n| `range(x)` | the smallest and largest value |\n| `sd(x)` | the standard deviation: roughly, how far values typically are from the mean |\n| `var(x)` | the variance, `sd(x)` squared |\n| `quantile(x, 0.9)` | the value 90% of the data is below |\n| `IQR(x)` | the interquartile range: the spread of the middle half |',
    code(...DELIVERIES.trim().split('\n')),
    code('range(deliveries$minutes)                  # 19 74', 'round(sd(deliveries$minutes), 1)          # 14.6', 'quantile(deliveries$minutes)               # 0%, 25%, 50%, 75%, 100%', 'IQR(deliveries$minutes)                    # 10'),
    '`quantile()` without a second argument gives the **quartiles**: the values a quarter, half and three quarters of the way through the sorted data. The 50% quartile is the median. The IQR is the 75% quartile minus the 25% one, so it covers the middle half of the data.',
    'Like the median, the IQR isn\'t pulled about by one extreme value, while the standard deviation is. Here the 74-minute delivery makes the sd 14.6, though the middle half of deliveries are within 10 minutes of each other.',
    'Quantiles answer practical questions: "90% of deliveries arrive within how many minutes?" is `quantile(minutes, 0.9)`. All of these take `na.rm = TRUE`.',
  ],
  sandboxCode: DELIVERIES + 'range(deliveries$minutes)\nsd(deliveries$minutes)\nquantile(deliveries$minutes)\nIQR(deliveries$minutes)\nquantile(deliveries$minutes, 0.9)',
  sandboxSnippets: [snippet('Same mean, different spread', 'steady <- c(28, 30, 31, 29, 32)\nwild <- c(10, 60, 25, 15, 40)\nc(mean(steady), mean(wild))\nc(sd(steady), sd(wild))')],
  readMore: { label: 'R documentation: quantile()', url: 'https://stat.ethz.ch/R-manual/R-devel/library/stats/html/quantile.html', source: 'R documentation' },
  challenges: [
    task('easy', 'Fastest and slowest', {
      prompt: 'Make `fast_slow` the shortest and longest delivery time, in one call.',
      starter: DELIVERIES,
      hint: '`fast_slow <- range(deliveries$minutes)`',
      solution: DELIVERIES + 'fast_slow <- range(deliveries$minutes)',
      tests: [['fast_slow is 19, 74', near('fast_slow', 'c(19, 74)')]],
    }),
    task('easy', 'Standard deviation', {
      prompt: 'Make `spread_sd` the standard deviation of the times, rounded to 1 decimal place.',
      starter: DELIVERIES,
      hint: '`round(sd(deliveries$minutes), 1)`',
      solution: DELIVERIES + 'spread_sd <- round(sd(deliveries$minutes), 1)',
      tests: [['spread_sd is 14.6', near('spread_sd', 14.6)], ['Uses sd()', uses('sd(')]],
    }),
    task('easy', 'The middle half', {
      prompt: 'Make `middle_half` the interquartile range of the times.',
      starter: DELIVERIES,
      hint: '`middle_half <- IQR(deliveries$minutes)`',
      solution: DELIVERIES + 'middle_half <- IQR(deliveries$minutes)',
      tests: [['middle_half is 10', near('middle_half', 10)]],
    }),
    task('medium', 'The quartiles', {
      prompt: 'Make `quarts` the quartiles of the times, from `quantile()`.',
      starter: DELIVERIES,
      hint: '`quarts <- quantile(deliveries$minutes)`',
      solution: DELIVERIES + 'quarts <- quantile(deliveries$minutes)',
      tests: [['quarts is 19, 23.5, 28, 33.5, 74', 'isTRUE(all.equal(unname(quarts), c(19, 23.5, 28, 33.5, 74)))']],
    }),
    task('medium', '90% arrive within', {
      prompt: 'Make `within90` the time that 90% of deliveries arrive within, rounded to 1 decimal place.',
      starter: DELIVERIES,
      hint: '`round(unname(quantile(deliveries$minutes, 0.9)), 1)`. `unname()` drops the "90%" label.',
      solution: DELIVERIES + 'within90 <- round(unname(quantile(deliveries$minutes, 0.9)), 1)',
      tests: [['within90 is the 90% quantile', near('within90', 'round(unname(quantile(deliveries$minutes, 0.9)), 1)')]],
    }),
    task('medium', 'Variance', {
      prompt: 'Make `v` the variance of the times, and check it: make `same` the answer to whether `sqrt(v)` equals `sd()` of the times.',
      starter: DELIVERIES,
      hint: '`v <- var(deliveries$minutes)` and `same <- isTRUE(all.equal(sqrt(v), sd(deliveries$minutes)))`.',
      solution: DELIVERIES + 'v <- var(deliveries$minutes)\nsame <- isTRUE(all.equal(sqrt(v), sd(deliveries$minutes)))',
      tests: [['v is the variance', near('v', 'var(deliveries$minutes)')], ['same is TRUE', 'identical(same, TRUE)']],
    }),
    task('hard', 'Which area is steadier', {
      prompt: 'Make `sd_north` and `sd_south` the standard deviation of the times in each area, rounded to 1 decimal place.',
      starter: DELIVERIES,
      hint: '`round(sd(subset(deliveries, area == "north")$minutes), 1)`, and the same for `"south"`.',
      solution: DELIVERIES + 'sd_north <- round(sd(subset(deliveries, area == "north")$minutes), 1)\nsd_south <- round(sd(subset(deliveries, area == "south")$minutes), 1)',
      tests: [
        ['sd_north is right', near('sd_north', 'round(sd(deliveries$minutes[deliveries$area == "north"]), 1)')],
        ['sd_south is right', near('sd_south', 'round(sd(deliveries$minutes[deliveries$area == "south"]), 1)')],
      ],
    }),
    task('expert', 'One line of spread', {
      prompt: 'Show `Median 28, IQR 10, range 19 to 74` with one `cat()`, letting R work out the numbers.',
      starter: DELIVERIES,
      hint: '`cat()` puts a space before each comma; use `paste0()` for "28," or give the commas as part of the text: `cat("Median ", m, ", IQR ", …, sep = "")`.',
      solution: DELIVERIES + 'm <- deliveries$minutes\ncat("Median ", median(m), ", IQR ", IQR(m), ", range ", min(m), " to ", max(m), "\\n", sep = "")',
      tests: [['Shows the line', 'identical(trimws(._cq_stdout), "Median 28, IQR 10, range 19 to 74")'], ['Works out the IQR', uses('IQR(')]],
    }),
  ],
  questions: [
    mc('What does `unname(quantile(c(1, 2, 3, 4, 5), 0.5))` give?', ['`3`', '`2.5`', '`0.5`', '`5`'], 0,
      'The 50% quantile is the median.',
      { code: 'unname(quantile(c(1, 2, 3, 4, 5), 0.5))', output: '[1] 3' }),
    mc('What does `sd(c(4, 4, 4))` give?', ['`4`', '`0`', '`1`', '`NA`'], 1,
      'All the values are the same, so there is no spread.',
      { code: 'sd(c(4, 4, 4))', output: '[1] 0' }),
    mc('What does `quantile(1:9, 0.5)` give?', ['`4.5`', '`5`', '`9`', '`0.5`'], 1,
      'The 50% quantile is the median, 5.',
      { code: 'unname(quantile(1:9, 0.5))', output: '[1] 5' }),
    mc('What does `IQR(c(1, 2, 3, 4, 5, 6, 7, 8, 100))` give?', ['`99`', '`4`', '`31.4`', '`5`'], 1,
      'The middle half runs from 3 to 7, so the IQR is 4. The 100 doesn\'t change it.',
      { code: 'IQR(c(1, 2, 3, 4, 5, 6, 7, 8, 100))', output: '[1] 4' }),
    mc('Which measure of spread is pulled up most by one extreme value?', ['The IQR', 'The standard deviation', 'The median', 'The 25% quantile'], 1,
      'The sd uses every value\'s distance from the mean, so one far value counts a lot.'),
    mc('What does `var(c(1, 3))` give?', ['`1`', '`2`', '`4`', '`1.41`'], 1,
      'The sd of 1 and 3 is 1.414, and the variance is its square, 2.',
      { code: 'var(c(1, 3))', output: '[1] 2' }),
    mc('What does `quantile(x, 0.9)` answer?', ['The 9th value', 'The value 90% of the data is below', '90% of the mean', 'The top 10 values'], 1,
      'For delivery times: 90% arrive within that many minutes.'),
    mc('Two bakeries both average 30 minutes. One has sd 2, the other sd 15. Which is more reliable?', ['The one with sd 15', 'The one with sd 2', 'They are the same', 'You can\'t tell'], 1,
      'A small sd means times stay close to the average.'),
    qShort('Which function gives the standard deviation?', 'sd',
      '`sd(x)`'),
  ],
})
