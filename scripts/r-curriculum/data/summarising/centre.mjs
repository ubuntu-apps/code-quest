// Summarising data: Centre: mean and median.
import { code, makeTopic, mc, near, qShort, snippet, task, uses } from '../_builders.mjs'
import { DELIVERIES } from '../datasets.mjs'

export default makeTopic({
  id: 'centre',
  title: 'Centre: mean and median',
  paragraphs: [
    'A "typical" value for a column of numbers is called its **centre**. The two you will use most are the mean and the median. This stage uses a bakery\'s delivery times:',
    code(...DELIVERIES.trim().split('\n')),
    'The **mean** adds everything up and divides by the count. The **median** is the middle value when they are sorted. Here the mean is about 31.6 minutes but the median is 28: one delivery took 74 minutes (a flat tyre), and that single value pulls the mean up.',
    code('mean(deliveries$minutes)      # 31.58', 'median(deliveries$minutes)    # 28'),
    'Which to report? When values are fairly even, the mean and median are close and the mean is fine. When a few values are extreme, as with delivery times, incomes or house prices, the median describes the typical case better. Reporting both is often the most honest.',
    'A **trimmed mean** is a middle way: `mean(x, trim = 0.1)` drops the lowest and highest 10% of values before averaging.',
    'And always remember `na.rm = TRUE` when a column has gaps, or the answer is `NA`.',
  ],
  sandboxCode: DELIVERIES + 'mean(deliveries$minutes)\nmedian(deliveries$minutes)\nmean(deliveries$minutes, trim = 0.1)',
  sandboxSnippets: [snippet('Without the flat tyre', DELIVERIES + 'mean(deliveries$minutes[deliveries$minutes < 60])')],
  readMore: { label: 'R documentation: mean()', url: 'https://stat.ethz.ch/R-manual/R-devel/library/base/html/mean.html', source: 'R documentation' },
  challenges: [
    task('easy', 'The mean time', {
      prompt: 'Make `avg` the mean delivery time, rounded to 1 decimal place.',
      starter: DELIVERIES,
      hint: '`avg <- round(mean(deliveries$minutes), 1)`',
      solution: DELIVERIES + 'avg <- round(mean(deliveries$minutes), 1)',
      tests: [['avg is 31.6', near('avg', 31.6)]],
    }),
    task('easy', 'The median time', {
      prompt: 'Make `mid` the median delivery time.',
      starter: DELIVERIES,
      hint: '`mid <- median(deliveries$minutes)`',
      solution: DELIVERIES + 'mid <- median(deliveries$minutes)',
      tests: [['mid is 28', near('mid', 28)], ['Uses median()', uses('median(')]],
    }),
    task('easy', 'How far apart', {
      prompt: 'Make `gap` how much bigger the mean is than the median, rounded to 1 decimal place.',
      starter: DELIVERIES,
      hint: '`round(mean(deliveries$minutes) - median(deliveries$minutes), 1)`',
      solution: DELIVERIES + 'gap <- round(mean(deliveries$minutes) - median(deliveries$minutes), 1)',
      tests: [['gap is 3.6', near('gap', 3.6)]],
    }),
    task('medium', 'A trimmed mean', {
      prompt: 'Make `trimmed` the mean with the lowest and highest 10% left out, rounded to 1 decimal place.',
      starter: DELIVERIES,
      hint: '`round(mean(deliveries$minutes, trim = 0.1), 1)`',
      solution: DELIVERIES + 'trimmed <- round(mean(deliveries$minutes, trim = 0.1), 1)',
      tests: [['trimmed is the 10% trimmed mean', near('trimmed', 'round(mean(deliveries$minutes, trim = 0.1), 1)')], ['Uses trim', uses('trim')]],
    }),
    task('medium', 'Without the flat tyre', {
      prompt: 'Make `usual` the mean of the deliveries that took less than 60 minutes, rounded to 1 decimal place.',
      starter: DELIVERIES,
      hint: '`round(mean(deliveries$minutes[deliveries$minutes < 60]), 1)`',
      solution: DELIVERIES + 'usual <- round(mean(deliveries$minutes[deliveries$minutes < 60]), 1)',
      tests: [['usual is 27.7', near('usual', 27.7)]],
    }),
    task('medium', 'The north', {
      prompt: 'Make `north_median` the median time of the deliveries to the north area.',
      starter: DELIVERIES,
      hint: '`median(subset(deliveries, area == "north")$minutes)`',
      solution: DELIVERIES + 'north_median <- median(subset(deliveries, area == "north")$minutes)',
      tests: [['north_median is the median of the north deliveries', near('north_median', 'median(deliveries$minutes[deliveries$area == "north"])')]],
    }),
    task('hard', 'With a gap', {
      prompt: 'One time didn\'t get recorded. Make `avg` the mean of the times that were, rounded to 1 decimal place.',
      starter: 'minutes <- c(24, 31, NA, 27, 35, 29)\n',
      hint: '`round(mean(minutes, na.rm = TRUE), 1)`',
      solution: 'minutes <- c(24, 31, NA, 27, 35, 29)\navg <- round(mean(minutes, na.rm = TRUE), 1)',
      tests: [['avg is 29.2', near('avg', 29.2)]],
    }),
    task('expert', 'Mean and median side by side', {
      prompt: 'Make `centres` a named vector with the mean (rounded to 1 decimal place) and the median of the times, named `mean` and `median`.',
      starter: DELIVERIES,
      hint: '`c(mean = round(mean(deliveries$minutes), 1), median = median(deliveries$minutes))`',
      solution: DELIVERIES + 'centres <- c(mean = round(mean(deliveries$minutes), 1), median = median(deliveries$minutes))',
      tests: [['centres is mean 31.6, median 28', 'isTRUE(all.equal(centres, c(mean = 31.6, median = 28)))']],
    }),
  ],
  questions: [
    mc('What does `mean(c(2, 3, 4, 31))` give?', ['`3.5`', '`10`', '`31`', '`9.5`'], 1,
      'The total, 40, divided by 4. One big value pulls the mean up.',
      { code: 'mean(c(2, 3, 4, 31))', output: '[1] 10' }),
    mc('What does `median(c(2, 3, 4, 31))` give?', ['`3.5`', '`10`', '`3`', '`4`'], 0,
      'Halfway between the two middle values, 3 and 4.',
      { code: 'median(c(2, 3, 4, 31))', output: '[1] 3.5' }),
    mc('Delivery times are mostly 20 to 35 minutes, with one of 74. Which centre describes a typical delivery better?', ['The mean', 'The median', 'The maximum', 'The sum'], 1,
      'The median isn\'t pulled about by one extreme value.'),
    mc('What does `mean(c(1, 2, 3, 4, 100), trim = 0.2)` give?', ['`22`', '`3`', '`2.5`', '`36.33`'], 1,
      'Trimming 20% drops the 1 and the 100, leaving the mean of 2, 3 and 4.',
      { code: 'mean(c(1, 2, 3, 4, 100), trim = 0.2)', output: '[1] 3' }),
    mc('What does `median(c(5, NA, 9))` give?', ['`7`', '`NA`', '`5`', '`9`'], 1,
      'Without `na.rm = TRUE`, a gap makes the answer NA.',
      { code: 'median(c(5, NA, 9))', output: '[1] NA' }),
    mc('When are the mean and the median about the same?', ['Never', 'When values are spread evenly around the middle', 'When there are no NAs', 'When there are many values'], 1,
      'Extreme values on one side pull the mean away from the median.'),
    mc('What does `mean(c(10, 20, 30, 40, 1000), trim = 0.2)` give?', ['`30`', '`220`', '`25`', '`40`'], 0,
      '20% of 5 values is 1, so the lowest (10) and highest (1000) are dropped: the mean of 20, 30 and 40.',
      { code: 'mean(c(10, 20, 30, 40, 1000), trim = 0.2)', output: '[1] 30' }),
    mc('A report says "average delivery: 31.6 minutes". What should it add, given one 74-minute delivery?', ['Nothing', 'The median, 28, to show a typical delivery', 'The number of riders', 'The sum'], 1,
      'Showing both lets readers see that one long delivery raised the mean.'),
    qShort('Which function gives the middle value of sorted numbers?', 'median',
      '`median(x)`'),
  ],
})
