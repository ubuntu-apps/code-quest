// Cleaning data: Reading CSV data.
import { code, isTexts, makeTopic, mc, near, qShort, sameFrame, snippet, task, uses } from '../_builders.mjs'

const CSV = 'loans <- read.csv(text = "\nmember,book,days\nAna,The Long Walk,12\nBen,Seed Saving,20\nCy,River Birds,9\n")\n'

export default makeTopic({
  id: 'reading_csv',
  title: 'Reading CSV data',
  paragraphs: [
    'Most data arrives as a file, and the most common kind is **CSV**: comma-separated values. It is plain text, one row per line, with commas between the values and the column names on the first line:',
    code('member,book,days', 'Ana,The Long Walk,12', 'Ben,Seed Saving,20', 'Cy,River Birds,9'),
    '`read.csv()` turns that into a data frame. Normally you give it a file name, `read.csv("loans.csv")`. In CodeQuest there are no files to open, so the challenges give the text directly with `text =`, which works exactly the same way:',
    code(...CSV.trim().split('\n')),
    'Always look at what you got with `str()` straight away. `read.csv()` guesses each column\'s type from its values: a column of numbers becomes numeric, but if even one value isn\'t a number (`"N/A"`, `"12 days"`, `"$3.40"`), the whole column comes in as text. Spotting that early saves a lot of confusion.',
    'Useful arguments: `na.strings = c("", "N/A")` tells R which texts mean "missing", and `strip.white = TRUE` removes stray spaces around values. Writing is the mirror image: `write.csv(df, "clean.csv", row.names = FALSE)`.',
    'In many countries spreadsheets save "CSV" with `;` between the values and `,` as the decimal point (`2,50`). `read.csv2()` reads that style; it is `read.csv()` with those two settings changed.',
    'The rest of this quest is about the cleaning that usually comes next.',
  ],
  sandboxCode: CSV + 'loans\nstr(loans)',
  sandboxSnippets: [
    snippet('One bad value', 'x <- read.csv(text = "\nitem,price\ntea,2.5\ncake,N/A\n")\nstr(x)'),
    snippet('Tell R what missing looks like', 'x <- read.csv(text = "\nitem,price\ntea,2.5\ncake,N/A\n", na.strings = "N/A")\nstr(x)'),
    snippet('Skip lines at the top', 'csv <- "Exported 2026-10-30\\nmember,days\\nAna,12\\nBen,20"\nread.csv(text = csv, skip = 1)'),
  ],
  readMore: { label: 'R documentation: read.csv()', url: 'https://stat.ethz.ch/R-manual/R-devel/library/utils/html/read.table.html', source: 'R documentation' },
  challenges: [
    task('easy', 'Read the loans', {
      prompt: 'Make `loans` by reading the CSV text in `csv`.',
      starter: 'csv <- "member,book,days\nAna,The Long Walk,12\nBen,Seed Saving,20\nCy,River Birds,9"\n',
      hint: '`loans <- read.csv(text = csv)`',
      solution: 'csv <- "member,book,days\nAna,The Long Walk,12\nBen,Seed Saving,20\nCy,River Birds,9"\nloans <- read.csv(text = csv)',
      tests: [['loans has the three loans', sameFrame('loans', 'data.frame(member = c("Ana", "Ben", "Cy"), book = c("The Long Walk", "Seed Saving", "River Birds"), days = c(12L, 20L, 9L))')], ['Uses read.csv()', uses('read.csv(')]],
    }),
    task('easy', 'Total days', {
      prompt: 'Make `total_days` the total of the `days` column.',
      starter: CSV,
      hint: '`total_days <- sum(loans$days)`',
      solution: CSV + 'total_days <- sum(loans$days)',
      tests: [['total_days is 41', near('total_days', 41)]],
    }),
    task('easy', 'Look before you leap', {
      prompt: 'Show the structure of `loans`.',
      starter: CSV,
      hint: '`str(loans)`',
      solution: CSV + 'str(loans)',
      tests: [['Shows the structure', 'grepl("3 obs. of  3 variables", ._cq_stdout, fixed = TRUE)']],
    }),
    task('medium', 'Why is it text', {
      prompt: 'One value isn\'t a number, so `days` came in as text. Make `bad` the value of `days` that can\'t be turned into a number.',
      starter: 'loans <- read.csv(text = "\nmember,days\nAna,12\nBen,20 days\nCy,9\n")\n',
      hint: 'Convert with `suppressWarnings(as.numeric(loans$days))`, then pick the original values where that is NA.',
      solution: 'loans <- read.csv(text = "\nmember,days\nAna,12\nBen,20 days\nCy,9\n")\nnums <- suppressWarnings(as.numeric(loans$days))\nbad <- loans$days[is.na(nums)]',
      tests: [['bad is "20 days"', isTexts('bad', '20 days')]],
    }),
    task('medium', 'Missing means missing', {
      prompt: 'Read the CSV so that both `N/A` and an empty value become `NA`, making `days` numeric. Make `n_missing` the number of missing days.',
      starter: 'csv <- "member,days\nAna,12\nBen,N/A\nCy,\nDee,9"\n',
      hint: '`read.csv(text = csv, na.strings = c("", "N/A"))`, then `sum(is.na(loans$days))`.',
      solution: 'csv <- "member,days\nAna,12\nBen,N/A\nCy,\nDee,9"\nloans <- read.csv(text = csv, na.strings = c("", "N/A"))\nn_missing <- sum(is.na(loans$days))',
      tests: [['days is numeric', 'is.numeric(loans$days)'], ['n_missing is 2', near('n_missing', 2)]],
    }),
    task('medium', 'Stray spaces', {
      prompt: 'The names have spaces around them. Read the CSV with `strip.white = TRUE` so `loans$member` is clean.',
      starter: 'csv <- "member,days\n Ana ,12\nBen  ,20\n  Cy,9"\n',
      hint: '`loans <- read.csv(text = csv, strip.white = TRUE)`',
      solution: 'csv <- "member,days\n Ana ,12\nBen  ,20\n  Cy,9"\nloans <- read.csv(text = csv, strip.white = TRUE)',
      tests: [['member is Ana, Ben, Cy', 'identical(loans$member, c("Ana", "Ben", "Cy"))']],
    }),
    task('hard', 'Write it back', {
      prompt: 'Write `loans` to a file `loans_clean.csv` without row numbers, then read it back into `again`.',
      starter: CSV,
      hint: '`write.csv(loans, "loans_clean.csv", row.names = FALSE)` then `again <- read.csv("loans_clean.csv")`.',
      solution: CSV + 'write.csv(loans, "loans_clean.csv", row.names = FALSE)\nagain <- read.csv("loans_clean.csv")',
      tests: [['again is the same as loans', sameFrame('again', 'loans')]],
    }),
    task('hard', 'A note on top', {
      prompt: 'The export starts with a note line before the column names. Make `loans` the data, read without that first line.',
      starter: 'csv <- "Library export 2026-10-30\nmember,days\nAna,12\nBen,20"\n',
      hint: '`skip = 1` tells `read.csv()` to ignore the first line: `read.csv(text = csv, skip = 1)`.',
      solution: 'csv <- "Library export 2026-10-30\nmember,days\nAna,12\nBen,20"\nloans <- read.csv(text = csv, skip = 1)',
      tests: [['loans is Ana 12, Ben 20', sameFrame('loans', 'data.frame(member = c("Ana", "Ben"), days = c(12L, 20L))')]],
    }),
    task('expert', 'A semicolon file', {
      prompt: 'Some countries\' spreadsheets save CSV with `;` between values and `,` as the decimal point. Make `prices` by reading this text with `read.csv2()`, so `price` is numeric.',
      starter: 'csv <- "item;price\ntea;2,50\ncake;4,20"\n',
      hint: '`read.csv2()` expects exactly that: `prices <- read.csv2(text = csv)`.',
      solution: 'csv <- "item;price\ntea;2,50\ncake;4,20"\nprices <- read.csv2(text = csv)',
      tests: [['prices has tea 2.5 and cake 4.2', sameFrame('prices', 'data.frame(item = c("tea", "cake"), price = c(2.5, 4.2))')]],
    }),
    task('expert', 'Keep the zeros', {
      prompt: 'The ids have leading zeros that matter. Read the CSV into `stock` so that `id` stays text, like `"007"`.',
      starter: 'csv <- "id,item\n007,tea\n012,cake"\n',
      hint: '`colClasses = c(id = "character")` tells `read.csv()` the type of that column.',
      solution: 'csv <- "id,item\n007,tea\n012,cake"\nstock <- read.csv(text = csv, colClasses = c(id = "character"))',
      tests: [['stock$id is "007", "012"', isTexts('stock$id', '007', '012')], ['stock$item is tea, cake', isTexts('stock$item', 'tea', 'cake')]],
    }),
  ],
  questions: [
    mc('Why does `read.csv()` make a whole column text when one value is `"20 days"`?', ['A column has one type, and "20 days" can\'t be a number, so the column stays text', 'read.csv() reads everything as text', 'Days are always text', 'It doesn\'t'], 0,
      'Look at `str()` straight after reading to catch this.'),
    mc('What does `nrow(read.csv(text = "a,b\\n1,2\\n3,4"))` give?', ['`3`', '`2`', '`4`', '`1`'], 1,
      'The first line is the column names, so there are 2 rows of data.',
      { code: 'nrow(read.csv(text = "a,b\\n1,2\\n3,4"))', output: '[1] 2' }),
    mc('What type is column `x` in `read.csv(text = "x\\n1\\n2\\nN/A")`?', ['numeric', 'character', 'logical', 'factor'], 1,
      'One value isn\'t a number, so the whole column is text.',
      { code: 'class(read.csv(text = "x\\n1\\n2\\nN/A")$x)', output: '[1] "character"' }),
    mc('What does `na.strings = c("", "N/A")` do?', ['Removes those rows', 'Treats empty values and "N/A" as missing', 'Replaces NA with "N/A"', 'Sorts the data'], 1,
      'Then a column of numbers with gaps still comes in as numeric.',
      { code: 'class(read.csv(text = "x\\n1\\nN/A", na.strings = "N/A")$x)', output: '[1] "integer"' }),
    mc('Why look at `str()` straight after reading?', ['It is required', 'To check each column has the type you expect', 'To sort the data', 'To save the file'], 1,
      'A numbers column that came in as text needs fixing first.'),
    mc('What does `row.names = FALSE` do in `write.csv()`?', ['Deletes the row names column from the data', 'Doesn\'t write an extra column of row numbers', 'Writes no header', 'Sorts the rows'], 1,
      'Otherwise the file gets an unnamed first column of 1, 2, 3, …'),
    mc('What does `read.csv(text = "a\\n x ", strip.white = TRUE)$a` give?', ['`" x "`', '`"x"`', '`NA`', 'An error'], 1,
      'The spaces around the value are removed.',
      { code: 'read.csv(text = "a\\n x ", strip.white = TRUE)$a', output: '[1] "x"' }),
    mc('Which reads a file that uses `;` between values and `,` for decimals?', ['`read.csv()`', '`read.csv2()`', '`read.table()` only', '`strsplit()`'], 1,
      '`read.csv2()` is made for that style.'),
    qShort('Which function reads CSV data into a data frame?', 'read.csv',
      '`read.csv("file.csv")` or `read.csv(text = …)`'),
  ],
})
