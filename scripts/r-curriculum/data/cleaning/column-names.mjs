// Cleaning data: Fixing column names.
import { code, isTexts, makeTopic, mc, qShort, snippet, task, uses } from '../_builders.mjs'

const RAW = 'members <- read.csv(text = "\nMember Name,E-mail,Age (years),Joined On\nAna Silva,ana@example.org,34,2026-09-01\nBen Okafor,ben@example.org,41,2026-09-03\n")\n'

export default makeTopic({
  id: 'column_names',
  title: 'Fixing column names',
  paragraphs: [
    'Column names in real files are written for people: `Member Name`, `E-mail`, `Age (years)`. R needs names it can use after `$`, so `read.csv()` quietly changes them, turning every space and symbol into a dot:',
    code(...RAW.trim().split('\n'), 'names(members)   # "Member.Name" "E.mail" "Age..years." "Joined.On"'),
    'Those work, but they are awkward to type and easy to get wrong. A good habit is to tidy all the names at the start: small letters, words joined with `_`, no symbols. Assign new names with `names()`:',
    code('names(members) <- c("name", "email", "age", "joined")'),
    'For many columns, clean them with text tools instead of typing every name: `tolower()`, then `gsub()` to turn runs of dots into `_` and trim `_` from the ends.',
    code('n <- tolower(names(members))', 'n <- gsub("\\\\.+", "_", n)      # one or more dots become _', 'n <- gsub("^_|_$", "", n)       # no _ at the start or end'),
    'To rename just one column, assign to that position: `names(members)[3] <- "age"`, or find it by name: `names(members)[names(members) == "E.mail"] <- "email"`.',
  ],
  sandboxCode: RAW + 'names(members)\nn <- tolower(names(members))\nn <- gsub("\\\\.+", "_", n)\ngsub("^_|_$", "", n)',
  sandboxSnippets: [snippet('Rename one', RAW + 'names(members)[names(members) == "E.mail"] <- "email"\nnames(members)')],
  readMore: { label: 'R documentation: make.names()', url: 'https://stat.ethz.ch/R-manual/R-devel/library/base/html/make.names.html', source: 'R documentation' },
  challenges: [
    task('easy', 'What R made of them', {
      prompt: 'Make `original` the column names R gave the data.',
      starter: RAW,
      hint: '`original <- names(members)`',
      solution: RAW + 'original <- names(members)',
      tests: [['original is Member.Name, E.mail, Age..years., Joined.On', isTexts('original', 'Member.Name', 'E.mail', 'Age..years.', 'Joined.On')]],
    }),
    task('easy', 'New names', {
      prompt: 'Give the columns the names `name`, `email`, `age` and `joined`.',
      starter: RAW,
      hint: '`names(members) <- c("name", "email", "age", "joined")`',
      solution: RAW + 'names(members) <- c("name", "email", "age", "joined")',
      tests: [['The names are name, email, age, joined', 'identical(names(members), c("name", "email", "age", "joined"))']],
    }),
    task('easy', 'Rename one', {
      prompt: 'Rename only the third column to `age`.',
      starter: RAW,
      hint: '`names(members)[3] <- "age"`',
      solution: RAW + 'names(members)[3] <- "age"',
      tests: [['The third name is age, the others unchanged', 'identical(names(members), c("Member.Name", "E.mail", "age", "Joined.On"))']],
    }),
    task('medium', 'Rename by name', {
      prompt: 'Rename the column `E.mail` to `email`, finding it by its name rather than its position.',
      starter: RAW,
      hint: '`names(members)[names(members) == "E.mail"] <- "email"`',
      solution: RAW + 'names(members)[names(members) == "E.mail"] <- "email"',
      tests: [['E.mail is now email', 'identical(names(members), c("Member.Name", "email", "Age..years.", "Joined.On"))'], ['Finds it by name', uses('== "E.mail"')]],
    }),
    task('medium', 'Small letters', {
      prompt: 'Make every column name small letters, keeping the dots for now.',
      starter: RAW,
      hint: '`names(members) <- tolower(names(members))`',
      solution: RAW + 'names(members) <- tolower(names(members))',
      tests: [['The names are lower case', 'identical(names(members), c("member.name", "e.mail", "age..years.", "joined.on"))']],
    }),
    task('hard', 'Dots to underscores', {
      prompt: 'Make every name small letters, with each run of dots turned into one `_`, and no `_` at the end.',
      starter: RAW,
      hint: '`gsub("\\\\.+", "_", n)` turns runs of dots into `_`; `gsub("_$", "", n)` removes one at the end.',
      solution: RAW + 'n <- tolower(names(members))\nn <- gsub("\\\\.+", "_", n)\nn <- gsub("^_|_$", "", n)\nnames(members) <- n',
      tests: [['The names are member_name, e_mail, age_years, joined_on', 'identical(names(members), c("member_name", "e_mail", "age_years", "joined_on"))']],
    }),
    task('hard', 'A name-cleaning function', {
      prompt: 'Write `clean_names(df)` that does those three steps and gives back the data frame with tidy names.',
      hint: 'Inside: `n <- tolower(names(df))`, the two `gsub()` calls, then `names(df) <- n` and `df` as the last line.',
      solution: 'clean_names <- function(df) {\n  n <- tolower(names(df))\n  n <- gsub("\\\\.+", "_", n)\n  n <- gsub("^_|_$", "", n)\n  names(df) <- n\n  df\n}',
      tests: [['clean_names() tidies the names', 'is.function(clean_names) && identical(names(clean_names(data.frame(Member.Name = 1, Age..years. = 2))), c("member_name", "age_years"))']],
    }),
    task('expert', 'Use the tidy names', {
      prompt: 'Tidy the names as in the last challenges, then make `avg_age` the mean of the `age_years` column.',
      starter: RAW,
      hint: 'After tidying, the column is `members$age_years`.',
      solution: RAW + 'n <- tolower(names(members))\nn <- gsub("\\\\.+", "_", n)\nnames(members) <- gsub("^_|_$", "", n)\navg_age <- mean(members$age_years)',
      tests: [['avg_age is 37.5', 'isTRUE(all.equal(avg_age, 37.5))'], ['The names are tidy', '"age_years" %in% names(members)']],
    }),
  ],
  questions: [
    mc('What does `names(read.csv(text = "Member Name\\nAna"))` give?', ['`"Member Name"`', '`"Member.Name"`', '`"member_name"`', '`"MemberName"`'], 1,
      '`read.csv()` turns the space into a dot.',
      { code: 'names(read.csv(text = "Member Name\\nAna"))', output: '[1] "Member.Name"' }),
    mc('What does `gsub("\\\\.+", "_", "Age..years.")` give?', ['`"Age_years_"`', '`"Age__years_"`', '`"Age.years"`', '`"Age years"`'], 0,
      'Each run of one or more dots becomes a single `_`.',
      { code: 'gsub("\\\\.+", "_", "Age..years.")', output: '[1] "Age_years_"' }),
    mc('Why does `.` need `\\\\.` in a `gsub()` pattern?', ['It doesn\'t', 'A plain `.` means "any character"; `\\\\.` means a real dot', 'For speed', 'To make it lower case'], 1,
      'Or use `fixed = TRUE` when you mean plain text.'),
    mc('What does `gsub("^_|_$", "", "_age_")` give?', ['`"age"`', '`"_age"`', '`"age_"`', '`""`'], 0,
      '`^_` is a `_` at the start and `_$` one at the end; `|` means either.',
      { code: 'gsub("^_|_$", "", "_age_")', output: '[1] "age"' }),
    mc('After `df <- data.frame(a = 1, b = 2)` and `names(df)[2] <- "z"`, what does `names(df)` give?', ['`[1] "a" "b"`', '`[1] "a" "z"`', '`[1] "z" "b"`', '`[1] "z"`'], 1,
      'Only the second name changes.',
      { code: 'df <- data.frame(a = 1, b = 2)\nnames(df)[2] <- "z"\nnames(df)', output: '[1] "a" "z"' }),
    mc('Why tidy column names at the start?', ['R requires it', 'Short, consistent names are easy to type and hard to get wrong', 'It sorts the columns', 'It removes NAs'], 1,
      '`members$age` beats `members$Age..years.`.'),
    mc('What does `tolower("Joined.On")` give?', ['`"joined.on"`', '`"joined_on"`', '`"JOINED.ON"`', '`"joinedon"`'], 0,
      'Only the letters change.',
      { code: 'tolower("Joined.On")', output: '[1] "joined.on"' }),
    mc('Which renames the column called `E.mail` wherever it is?', ['`names(df)[2] <- "email"`', '`names(df)[names(df) == "E.mail"] <- "email"`', '`df$E.mail <- "email"`', '`rename(df, "email")`'], 1,
      'The condition finds the position from the name.'),
    qShort('Which function gives or sets the column names of a data frame?', 'names',
      '`names(df) <- c(…)`'),
  ],
})
