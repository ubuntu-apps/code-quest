// Cleaning data: Duplicates.
import { code, isTexts, makeTopic, mc, near, qShort, same, sameFrame, snippet, task } from '../_builders.mjs'

const SIGN = 'signups <- data.frame(\n  email = c("ana@example.org", "ben@example.org", "ana@example.org", "cy@example.org", "ben@example.org"),\n  workshop = c("compost", "compost", "compost", "seeds", "seeds")\n)\n'

export default makeTopic({
  id: 'duplicates',
  title: 'Duplicates',
  paragraphs: [
    'Duplicates creep in when someone submits a form twice, when two files overlap, or when the same thing is entered by two people. They make counts and totals too big, so finding them is a standard cleaning step.',
    '`duplicated()` is TRUE for every value (or row) that has **already appeared** earlier. The first copy is FALSE, later copies TRUE:',
    code('duplicated(c("a", "b", "a", "c", "a"))    # FALSE FALSE TRUE FALSE TRUE'),
    'So `sum(duplicated(x))` counts the extra copies, and `x[!duplicated(x)]` keeps the first of each, which is what `unique(x)` does too.',
    'On a data frame, `duplicated(df)` compares **whole rows**. Two rows are duplicates only if every column matches:',
    code(...SIGN.trim().split('\n'), 'duplicated(signups)          # FALSE FALSE TRUE FALSE FALSE', 'signups[!duplicated(signups), ]'),
    'Often, though, what defines a duplicate is a **key**: one person should appear once, whatever else differs. Then test that column alone: `signups[!duplicated(signups$email), ]` keeps each email\'s first row. Be sure that is what you want: here it would drop Ben\'s second, different workshop.',
    'Before deleting anything, look at the duplicates: `signups[duplicated(signups$email) | duplicated(signups$email, fromLast = TRUE), ]` shows every row whose email appears more than once.',
  ],
  sandboxCode: SIGN + 'duplicated(signups)\nsignups[!duplicated(signups), ]\nduplicated(signups$email)',
  sandboxSnippets: [snippet('Every copy', SIGN + 'e <- signups$email\nsignups[duplicated(e) | duplicated(e, fromLast = TRUE), ]')],
  readMore: { label: 'R documentation: duplicated()', url: 'https://stat.ethz.ch/R-manual/R-devel/library/base/html/duplicated.html', source: 'R documentation' },
  challenges: [
    task('easy', 'Which are repeats', {
      prompt: 'Make `again` TRUE for each email that already appeared earlier.',
      starter: 'emails <- c("ana@example.org", "ben@example.org", "ana@example.org", "cy@example.org")\n',
      hint: '`again <- duplicated(emails)`',
      solution: 'emails <- c("ana@example.org", "ben@example.org", "ana@example.org", "cy@example.org")\nagain <- duplicated(emails)',
      tests: [['again is FALSE FALSE TRUE FALSE', 'identical(again, c(FALSE, FALSE, TRUE, FALSE))']],
    }),
    task('easy', 'Count the extras', {
      prompt: 'Make `n_extra` the number of extra copies in `codes`.',
      starter: 'codes <- c("FI-104", "SC-221", "FI-104", "HI-007", "FI-104", "SC-221")\n',
      hint: '`n_extra <- sum(duplicated(codes))`',
      solution: 'codes <- c("FI-104", "SC-221", "FI-104", "HI-007", "FI-104", "SC-221")\nn_extra <- sum(duplicated(codes))',
      tests: [['n_extra is 3', near('n_extra', 3)]],
    }),
    task('easy', 'Whole rows', {
      prompt: 'Make `clean` the sign-ups without duplicated whole rows.',
      starter: SIGN,
      hint: '`clean <- signups[!duplicated(signups), ]`',
      solution: SIGN + 'clean <- signups[!duplicated(signups), ]',
      tests: [['clean has 4 rows', sameFrame('clean', 'signups[c(1, 2, 4, 5), ]')]],
    }),
    task('medium', 'One row per person', {
      prompt: 'Make `people` the first sign-up of each email.',
      starter: SIGN,
      hint: 'Test the key column: `signups[!duplicated(signups$email), ]`.',
      solution: SIGN + 'people <- signups[!duplicated(signups$email), ]',
      tests: [['people is rows 1, 2 and 4', sameFrame('people', 'signups[c(1, 2, 4), ]')]],
    }),
    task('medium', 'Look before deleting', {
      prompt: 'Make `repeats` every row whose email appears more than once, including the first copy.',
      starter: SIGN,
      hint: '`e <- signups$email`, then `signups[duplicated(e) | duplicated(e, fromLast = TRUE), ]`.',
      solution: SIGN + 'e <- signups$email\nrepeats <- signups[duplicated(e) | duplicated(e, fromLast = TRUE), ]',
      tests: [['repeats is rows 1, 2, 3 and 5', sameFrame('repeats', 'signups[c(1, 2, 3, 5), ]')]],
    }),
    task('medium', 'Who signed up twice', {
      prompt: 'Make `twice` the emails that appear more than once, each listed once.',
      starter: SIGN,
      hint: '`unique(signups$email[duplicated(signups$email)])`',
      solution: SIGN + 'twice <- unique(signups$email[duplicated(signups$email)])',
      tests: [['twice is ana@example.org, ben@example.org', isTexts('twice', 'ana@example.org', 'ben@example.org')]],
    }),
    task('hard', 'Duplicates after cleaning', {
      prompt: 'These emails only look different. Clean them (trim, small letters), then make `n_people` the number of different people.',
      starter: 'emails <- c("Ana@Example.org", "ben@example.org", " ana@example.org", "BEN@EXAMPLE.ORG", "cy@example.org")\n',
      hint: 'Clean first, then `sum(!duplicated(clean))` or `length(unique(clean))`.',
      solution: 'emails <- c("Ana@Example.org", "ben@example.org", " ana@example.org", "BEN@EXAMPLE.ORG", "cy@example.org")\nclean <- tolower(trimws(emails))\nn_people <- length(unique(clean))',
      tests: [['n_people is 3', near('n_people', 3)]],
    }),
    task('expert', 'Keep the latest', {
      prompt: 'Each member may have updated their phone number. Make `latest` the **last** row for each member, using `fromLast = TRUE`.',
      starter: 'phones <- data.frame(member = c("Ana", "Ben", "Ana", "Cy", "Ana"), phone = c("0111", "0222", "0333", "0444", "0555"))\n',
      hint: '`phones[!duplicated(phones$member, fromLast = TRUE), ]` marks the earlier copies as duplicates instead.',
      solution: 'phones <- data.frame(member = c("Ana", "Ben", "Ana", "Cy", "Ana"), phone = c("0111", "0222", "0333", "0444", "0555"))\nlatest <- phones[!duplicated(phones$member, fromLast = TRUE), ]',
      tests: [['latest is Ben 0222, Cy 0444, Ana 0555', sameFrame('latest', 'phones[c(2, 4, 5), ]')]],
    }),
  ],
  questions: [
    mc('What does `duplicated(c(1, 2, 1, 1))` give?', ['`[1] FALSE FALSE  TRUE  TRUE`', '`[1]  TRUE FALSE  TRUE  TRUE`', '`[1] 1 2`', '`[1] 2`'], 0,
      'The first 1 is not a duplicate; the later ones are.',
      { code: 'duplicated(c(1, 2, 1, 1))', output: '[1] FALSE FALSE  TRUE  TRUE' }),
    mc('What does `sum(duplicated(c("a", "b", "a", "a")))` give?', ['`3`', '`2`', '`1`', '`4`'], 1,
      'Two extra copies of "a".',
      { code: 'sum(duplicated(c("a", "b", "a", "a")))', output: '[1] 2' }),
    mc('When does `duplicated(df)` mark a row?', ['When any column repeats', 'When every column matches an earlier row', 'When the first column repeats', 'Never'], 1,
      'Whole rows are compared.'),
    mc('What does `nrow(unique(data.frame(a = c(1, 1, 2), b = c("x", "x", "y"))))` give?', ['`3`', '`2`', '`1`', 'An error'], 1,
      'The first two rows are the same.',
      { code: 'nrow(unique(data.frame(a = c(1, 1, 2), b = c("x", "x", "y"))))', output: '[1] 2' }),
    mc('What does `duplicated(c("a", "b", "a"), fromLast = TRUE)` give?', ['`[1]  TRUE FALSE FALSE`', '`[1] FALSE FALSE  TRUE`', '`[1] TRUE TRUE TRUE`', '`[1] FALSE  TRUE FALSE`'], 0,
      'Counting from the end, the last "a" is kept and the first is the duplicate.',
      { code: 'duplicated(c("a", "b", "a"), fromLast = TRUE)', output: '[1]  TRUE FALSE FALSE' }),
    mc('Why look at the duplicates before removing them?', ['It is required', 'Rows that share a key may differ in other columns that matter', 'To sort them', 'R can\'t remove them otherwise'], 1,
      'Ben signed up for two different workshops; removing by email alone would lose one.'),
    mc('Why clean text before checking for duplicates?', ['It is faster', '"Ana@Example.org" and "ana@example.org" are the same person but different texts', 'duplicated() needs small letters', 'It isn\'t needed'], 1,
      'Duplicates are found by exact match.'),
    mc('Which keeps the first row for each `email`?', ['`df[duplicated(df$email), ]`', '`df[!duplicated(df$email), ]`', '`unique(df$email)`', '`df[!duplicated(df), ]`'], 1,
      '`unique(df$email)` gives just the emails, not the rows.'),
    qShort('Which function is TRUE for values that already appeared earlier?', 'duplicated',
      '`duplicated(x)`'),
  ],
})
