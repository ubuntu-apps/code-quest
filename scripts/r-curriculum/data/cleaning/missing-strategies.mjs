// Cleaning data: Handling missing values.
import { code, makeTopic, mc, near, qShort, same, sameFrame, snippet, task } from '../_builders.mjs'

const SURVEY = 'survey <- read.csv(text = "\nvisitor,age,rating,comment\n1,34,5,Lovely\n2,,4,\n3,58,N/A,Too busy\n4,-1,3,ok\n5,27,,\n6,41,5,Great\n")\n'

export default makeTopic({
  id: 'missing_strategies',
  title: 'Handling missing values',
  paragraphs: [
    'Missing values hide in many disguises: an empty cell, `"N/A"`, `"-"`, `999`, `-1`. The first job is to make every one of them a real `NA`, so R knows. Then you choose what to do with them.',
    code(...SURVEY.trim().split('\n')),
    'Here `age` has an empty value and a `-1` (a typing error, not an age), and `rating` has `"N/A"` and an empty value, which made it a text column. Fix the disguises:',
    code('survey$rating[survey$rating %in% c("", "N/A")] <- NA', 'survey$rating <- as.numeric(survey$rating)', 'survey$age[survey$age < 0] <- NA'),
    'Then decide, column by column, and write down what you did:',
    '| Choice | How | When |\n| --- | --- | --- |\n| Leave them | `na.rm = TRUE` in summaries | Usually the honest default |\n| Drop rows | `df[!is.na(df$col), ]` | When that column is essential for the question |\n| Fill in | `x[is.na(x)] <- median(x, na.rm = TRUE)` | Only with a good reason, and say so |',
    'Filling in ("imputing") makes the data look complete, but the filled values are guesses. Filling with the median keeps the centre unchanged but makes the spread look smaller than it is. Always report how many values were missing.',
  ],
  sandboxCode: SURVEY + 'str(survey)\ncolSums(is.na(survey))',
  sandboxSnippets: [snippet('Fill with the median', 'x <- c(34, NA, 58, 27, 41)\nx[is.na(x)] <- median(x, na.rm = TRUE)\nx')],
  readMore: { label: 'R documentation: NA', url: 'https://stat.ethz.ch/R-manual/R-devel/library/base/html/NA.html', source: 'R documentation' },
  challenges: [
    task('easy', 'Disguised ratings', {
      prompt: 'Turn the empty and `"N/A"` ratings into `NA`, then make `rating` numeric.',
      starter: SURVEY,
      hint: '`survey$rating[survey$rating %in% c("", "N/A")] <- NA`, then `as.numeric()`.',
      solution: SURVEY + 'survey$rating[survey$rating %in% c("", "N/A")] <- NA\nsurvey$rating <- as.numeric(survey$rating)',
      tests: [['rating is 5, 4, NA, 3, NA, 5', 'is.numeric(survey$rating) && identical(survey$rating, c(5, 4, NA, 3, NA, 5))']],
    }),
    task('easy', 'Impossible ages', {
      prompt: 'An age below 0 is a typing error. Make those ages `NA`.',
      starter: SURVEY,
      hint: '`survey$age[survey$age < 0] <- NA`',
      solution: SURVEY + 'survey$age[survey$age < 0] <- NA',
      tests: [['age is 34, NA, 58, NA, 27, 41', 'identical(as.numeric(survey$age), c(34, NA, 58, NA, 27, 41))']],
    }),
    task('easy', 'How many missing', {
      prompt: 'Make `n_missing_age` the number of missing ages, after the last fix.',
      starter: SURVEY + 'survey$age[survey$age < 0] <- NA\n',
      hint: '`sum(is.na(survey$age))`',
      solution: SURVEY + 'survey$age[survey$age < 0] <- NA\nn_missing_age <- sum(is.na(survey$age))',
      tests: [['n_missing_age is 2', near('n_missing_age', 2)]],
    }),
    task('medium', 'Leave them out', {
      prompt: 'Make `avg_age` the mean of the known ages (after fixing the -1), rounded to 1 decimal place.',
      starter: SURVEY + 'survey$age[survey$age < 0] <- NA\n',
      hint: '`round(mean(survey$age, na.rm = TRUE), 1)`',
      solution: SURVEY + 'survey$age[survey$age < 0] <- NA\navg_age <- round(mean(survey$age, na.rm = TRUE), 1)',
      tests: [['avg_age is 40', near('avg_age', 40)]],
    }),
    task('medium', 'Drop rows without a rating', {
      prompt: 'Make `rated` the visitors who gave a rating.',
      starter: SURVEY + 'survey$rating[survey$rating %in% c("", "N/A")] <- NA\nsurvey$rating <- as.numeric(survey$rating)\n',
      hint: '`rated <- survey[!is.na(survey$rating), ]`',
      solution: SURVEY + 'survey$rating[survey$rating %in% c("", "N/A")] <- NA\nsurvey$rating <- as.numeric(survey$rating)\nrated <- survey[!is.na(survey$rating), ]',
      tests: [['rated is visitors 1, 2, 4 and 6', 'is.data.frame(rated) && identical(rated$visitor, c(1L, 2L, 4L, 6L))']],
    }),
    task('medium', 'Fill with the median', {
      prompt: 'Make `filled` the ages with each NA replaced by the median of the known ages.',
      starter: 'ages <- c(34, NA, 58, NA, 27, 41)\n',
      hint: '`filled <- ages` then `filled[is.na(filled)] <- median(ages, na.rm = TRUE)`.',
      solution: 'ages <- c(34, NA, 58, NA, 27, 41)\nfilled <- ages\nfilled[is.na(filled)] <- median(ages, na.rm = TRUE)',
      tests: [['filled is 34, 37.5, 58, 37.5, 27, 41', near('filled', 'c(34, 37.5, 58, 37.5, 27, 41)')]],
    }),
    task('hard', 'Read it right first', {
      prompt: 'Read the CSV so that empty values, `N/A` and `-` all become NA straight away, making both columns numeric.',
      starter: 'csv <- "visitor,rating\n1,5\n2,N/A\n3,-\n4,4\n5,"\n',
      hint: '`read.csv(text = csv, na.strings = c("", "N/A", "-"))`',
      solution: 'csv <- "visitor,rating\n1,5\n2,N/A\n3,-\n4,4\n5,"\nsurvey <- read.csv(text = csv, na.strings = c("", "N/A", "-"))',
      tests: [['rating is numeric with 3 NAs', 'is.numeric(survey$rating) && sum(is.na(survey$rating)) == 3']],
    }),
    task('expert', 'Report the gaps', {
      prompt: 'Make `missing_pct` the percentage of missing values in each column of the cleaned survey, rounded to whole numbers.',
      starter: SURVEY + 'survey$rating[survey$rating %in% c("", "N/A")] <- NA\nsurvey$rating <- as.numeric(survey$rating)\nsurvey$age[survey$age < 0] <- NA\nsurvey$comment[survey$comment == ""] <- NA\n',
      hint: '`colMeans(is.na(survey))` is the share missing per column; times 100, rounded.',
      solution: SURVEY + 'survey$rating[survey$rating %in% c("", "N/A")] <- NA\nsurvey$rating <- as.numeric(survey$rating)\nsurvey$age[survey$age < 0] <- NA\nsurvey$comment[survey$comment == ""] <- NA\nmissing_pct <- round(colMeans(is.na(survey)) * 100)',
      tests: [['missing_pct is visitor 0, age 33, rating 33, comment 33', same('missing_pct', 'c(visitor = 0, age = 33, rating = 33, comment = 33)')]],
    }),
  ],
  questions: [
    mc('Which of these is a missing value in disguise?', ['`34`', '`-1` in an age column', '`"Lovely"`', '`5`'], 1,
      'An impossible value usually means "not known" or a typo.'),
    mc('What does `as.numeric(c("5", "", "4"))` give?', ['`[1]  5 NA  4`', '`[1] 5 0 4`', 'An error', '`[1] 5 4`'], 0,
      'An empty text becomes NA.',
      { code: 'as.numeric(c("5", "", "4"))', output: '[1]  5 NA  4' }),
    mc('What does `colMeans(is.na(data.frame(a = c(1, NA), b = c(NA, NA))))` give?', ['`a 0.5, b 1`', '`a 1, b 2`', '`[1] 0.75`', '`a 0, b 0`'], 0,
      'The share of NAs in each column.',
      { code: 'as.vector(colMeans(is.na(data.frame(a = c(1, NA), b = c(NA, NA)))))', output: '[1] 0.5 1.0' }),
    mc('After `x <- c(2, NA, 10)` and `x[is.na(x)] <- median(x, na.rm = TRUE)`, what is `x`?', ['`[1]  2  6 10`', '`[1]  2  0 10`', '`[1]  2 NA 10`', '`[1] 6 6 6`'], 0,
      'The median of 2 and 10 is 6.',
      { code: 'x <- c(2, NA, 10)\nx[is.na(x)] <- median(x, na.rm = TRUE)\nx', output: '[1]  2  6 10' }),
    mc('What is the risk of filling NAs with the median?', ['None', 'The data looks complete and less spread out than it really is', 'It changes the median', 'It deletes rows'], 1,
      'The filled values are guesses; say how many there were.'),
    mc('When is dropping rows with NA reasonable?', ['Always', 'When that column is essential for the question you\'re answering', 'Never', 'Only for text columns'], 1,
      'A row with no rating can\'t help with "what is the average rating?".'),
    mc('What does `na.strings = c("", "-")` do in `read.csv()`?', ['Removes those rows', 'Reads empty values and "-" as NA', 'Replaces NA with "-"', 'Skips the header'], 1,
      'Fixing disguises while reading saves a step.'),
    mc('What is usually the honest default for missing values?', ['Fill them with 0', 'Leave them and use `na.rm = TRUE`, reporting how many there were', 'Delete the column', 'Guess them'], 1,
      'It doesn\'t invent data, and readers know what is behind the numbers.'),
    qShort('Which function is TRUE where a value is missing?', 'is.na',
      '`is.na(x)`'),
  ],
})
