  title: 'Recoding values',
  paragraphs: [
    '**Recoding** means changing values to the ones you want: fixing variants, shortening codes into words, or merging categories. Three ways, from the simplest:',
    '**One value:** assign to the matching positions: `crop[crop == "zucchini"] <- "courgettes"`.',
    '**A few values at once:** `%in%` finds them all: `crop[crop %in% c("courgette", "zucchini")] <- "courgettes"`.',
    '**A whole code list:** a **lookup** vector with names maps each code to its meaning. Indexing it by the codes gives the meanings, in order:',
    code('size_names <- c(S = "small", M = "medium", L = "large")', 'sizes <- c("M", "S", "M", "L")', 'unname(size_names[sizes])    # "medium" "small" "medium" "large"'),
    'A code missing from the lookup becomes `NA`, which is useful: it shows you every code you didn\'t expect.',
    'For yes/no style answers, `ifelse()` or `%in%` turns many forms into TRUE/FALSE: `answer %in% c("yes", "y", "1")`. And to merge categories, recode several into one, such as every leafy crop into `"greens"`.',
  ],
  sandboxCode: 'size_names <- c(S = "small", M = "medium", L = "large")\nsizes <- c("M", "S", "M", "L", "XL")\nunname(size_names[sizes])',
