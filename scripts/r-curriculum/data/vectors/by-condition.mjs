// Vectors: Picking items by condition.
import { R_INTRO, code, isTexts, makeTopic, mc, near, prints, qShort, same, snippet, task, uses } from '../_builders.mjs'

export default makeTopic({
  id: 'by_condition',
  title: 'Picking items by condition',
  paragraphs: [
    'Most of the time you don\'t know the positions you want. You want "the days over 8000 steps" or "the cheap items". For that, put a **condition** in the square brackets:',
    code('steps <- c(4200, 8100, 6500, 9900, 3000)', 'steps > 8000           # FALSE TRUE FALSE TRUE FALSE', 'steps[steps > 8000]    # 8100 9900'),
    'The comparison gives one `TRUE` or `FALSE` per value, and the brackets keep the values where it is `TRUE`. Read `steps[steps > 8000]` as "the steps where the steps are over 8000".',
    'The condition can come from another vector of the same length. That\'s how you pick matching values across vectors, such as the names of the days with lots of steps:',
    code('days <- c("Mon", "Tue", "Wed", "Thu", "Fri")', 'days[steps > 8000]     # "Tue" "Thu"'),
    'Combine conditions with `&` and `|`, just as in the first quest: `steps[steps > 4000 & steps < 9000]` keeps the values between the two.',
    'Because `TRUE` counts as 1, `sum()` of a condition **counts** the values that meet it, and `mean()` gives the **share** that meet it:',
    code('sum(steps > 8000)      # 2 days', 'mean(steps > 8000)     # 0.4, that is 40% of the days'),
    'You can also change all the matching values at once: `steps[steps < 0] <- 0` sets any negative count to 0.',
  ],
  sandboxCode: 'steps <- c(4200, 8100, 6500, 9900, 3000)\nsteps > 8000\nsteps[steps > 8000]\ndays <- c("Mon", "Tue", "Wed", "Thu", "Fri")\ndays[steps > 8000]\nsum(steps > 8000)',
  sandboxSnippets: [
    snippet('Between two values', 'steps <- c(4200, 8100, 6500, 9900, 3000)\nsteps[steps > 4000 & steps < 9000]'),
    snippet('Count and share', 'scores <- c(71, 64, 88, 92, 57)\nsum(scores >= 70)\nmean(scores >= 70)'),
    snippet('Change matching values', 'temps <- c(18, -999, 21, -999)\ntemps[temps == -999] <- NA\ntemps'),
  ],
  readMore: R_INTRO('Index-vectors', 'An Introduction to R: index vectors'),
  challenges: [
    task('easy', 'Busy days', {
      prompt: 'Make `busy` the step counts over 8000.',
      starter: 'steps <- c(4200, 8100, 6500, 9900, 3000)\n',
      hint: '`busy <- steps[steps > 8000]`',
      solution: 'steps <- c(4200, 8100, 6500, 9900, 3000)\nbusy <- steps[steps > 8000]',
      tests: [
        ['busy is 8100, 9900', near('busy', 'c(8100, 9900)')],
        ['Uses a condition in [ ]', uses('[steps >')],
      ],
    }),
    task('easy', 'Which passed', {
      prompt: 'Make `passed` the answer for every score to: is it 50 or more? One TRUE or FALSE per score.',
      starter: 'scores <- c(71, 44, 88, 50, 39)\n',
      hint: '`passed <- scores >= 50`',
      solution: 'scores <- c(71, 44, 88, 50, 39)\npassed <- scores >= 50',
      tests: [['passed is TRUE FALSE TRUE TRUE FALSE', same('passed', 'c(TRUE, FALSE, TRUE, TRUE, FALSE)')]],
    }),
    task('easy', 'Cheap items', {
      prompt: 'Make `cheap` the prices under 3.',
      starter: 'prices <- c(2.5, 3.4, 1.8, 4.2, 2.9)\n',
      hint: '`cheap <- prices[prices < 3]`',
      solution: 'prices <- c(2.5, 3.4, 1.8, 4.2, 2.9)\ncheap <- prices[prices < 3]',
      tests: [['cheap is 2.5, 1.8, 2.9', near('cheap', 'c(2.5, 1.8, 2.9)')]],
    }),
    task('medium', 'Names of the busy days', {
      prompt: 'Make `busy_days` the names of the days with more than 8000 steps.',
      starter: 'steps <- c(4200, 8100, 6500, 9900, 3000)\ndays <- c("Mon", "Tue", "Wed", "Thu", "Fri")\n',
      hint: 'Pick from `days` with a condition on `steps`: `days[steps > 8000]`.',
      solution: 'steps <- c(4200, 8100, 6500, 9900, 3000)\ndays <- c("Mon", "Tue", "Wed", "Thu", "Fri")\nbusy_days <- days[steps > 8000]',
      tests: [['busy_days is "Tue" "Thu"', isTexts('busy_days', 'Tue', 'Thu')]],
    }),
    task('medium', 'How many passed', {
      prompt: 'Make `n_passed` the number of scores that are 50 or more, using `sum()`.',
      starter: 'scores <- c(71, 44, 88, 50, 39, 62)\n',
      hint: 'TRUE counts as 1: `n_passed <- sum(scores >= 50)`.',
      solution: 'scores <- c(71, 44, 88, 50, 39, 62)\nn_passed <- sum(scores >= 50)',
      tests: [
        ['n_passed is 4', near('n_passed', 4)],
        ['Uses sum()', uses('sum(')],
      ],
    }),
    task('medium', 'In the comfort zone', {
      prompt: 'Make `comfy` the temperatures from 18 to 22, both included.',
      starter: 'temps <- c(16.5, 18, 21.4, 23.1, 22, 19.8)\n',
      hint: 'Two conditions joined by `&`: `temps[temps >= 18 & temps <= 22]`.',
      solution: 'temps <- c(16.5, 18, 21.4, 23.1, 22, 19.8)\ncomfy <- temps[temps >= 18 & temps <= 22]',
      tests: [['comfy is 18, 21.4, 22, 19.8', near('comfy', 'c(18, 21.4, 22, 19.8)')]],
    }),
    task('hard', 'Share of long rides', {
      prompt: 'Make `share_long` the share of rides longer than 30 minutes, as a number between 0 and 1.',
      starter: 'minutes <- c(12, 47, 30, 55, 8, 33, 21, 40)\n',
      hint: '`mean()` of a condition is the share that are TRUE: `share_long <- mean(minutes > 30)`.',
      solution: 'minutes <- c(12, 47, 30, 55, 8, 33, 21, 40)\nshare_long <- mean(minutes > 30)',
      tests: [['share_long is 0.5', near('share_long', 0.5)]],
    }),
    task('expert', 'Mark the bad readings', {
      prompt: 'The sensor writes `-999` when it fails. Replace every `-999` in `temps` with `NA`, in one line.',
      starter: 'temps <- c(18.2, -999, 21.0, 19.4, -999)\n',
      hint: 'Assign to the matching values: `temps[temps == -999] <- NA`.',
      solution: 'temps <- c(18.2, -999, 21.0, 19.4, -999)\ntemps[temps == -999] <- NA',
      tests: [['temps is 18.2, NA, 21, 19.4, NA', same('temps', 'c(18.2, NA, 21.0, 19.4, NA)')]],
    }),
  ],
  questions: [
    mc('After `x <- c(3, 8, 1, 9)`, what does `x[x > 5]` give?', ['`[1] 8 9`', '`[1] FALSE TRUE FALSE TRUE`', '`[1] 2 4`', '`[1] 3 1`'], 0,
      'The brackets keep the values where the condition is TRUE.',
      { code: 'x <- c(3, 8, 1, 9)\nx[x > 5]', output: '[1] 8 9' }),
    mc('After `x <- c(3, 8, 1, 9)`, what does `x > 5` give?', ['`[1] 8 9`', '`[1] FALSE  TRUE FALSE  TRUE`', '`TRUE`', '`[1] 2`'], 1,
      'Without brackets, a comparison gives one TRUE or FALSE per value.',
      { code: 'x <- c(3, 8, 1, 9)\nx > 5', output: '[1] FALSE  TRUE FALSE  TRUE' }),
    mc('After `x <- c(3, 8, 1, 9)`, what does `sum(x > 5)` give?', ['`17`', '`2`', '`21`', '`TRUE`'], 1,
      'TRUE counts as 1, so the sum counts the values over 5.',
      { code: 'x <- c(3, 8, 1, 9)\nsum(x > 5)', output: '[1] 2' }),
    mc('After `x <- c(3, 8, 1, 9)`, what does `mean(x > 5)` give?', ['`0.5`', '`5.25`', '`2`', '`8.5`'], 0,
      'Two of the four values are over 5: a share of 0.5.',
      { code: 'x <- c(3, 8, 1, 9)\nmean(x > 5)', output: '[1] 0.5' }),
    mc('After `x <- c(3, 8, 1, 9)`, what does `x[x > 10]` give?', ['`[1] NA`', 'An error', '`numeric(0)`: no values', '`[1] 0`'], 2,
      'No value is over 10, so you get an empty vector.',
      { code: 'x <- c(3, 8, 1, 9)\nx[x > 10]', output: 'numeric(0)' }),
    mc('After `size <- c("S", "L", "M")` and `price <- c(2, 4, 3)`, what does `size[price > 2.5]` give?', ['`[1] "L" "M"`', '`[1] 4 3`', '`[1] "S"`', 'An error'], 0,
      'The condition on `price` picks the matching positions of `size`.',
      { code: 'size <- c("S", "L", "M")\nprice <- c(2, 4, 3)\nsize[price > 2.5]', output: '[1] "L" "M"' }),
    mc('After `x <- c(3, 8, 1, 9)`, what does `x[x > 2 & x < 9]` give?', ['`[1] 3 8`', '`[1] 3 8 9`', '`[1] 8`', '`[1] 1 9`'], 0,
      'Both conditions must be TRUE: 3 and 8.',
      { code: 'x <- c(3, 8, 1, 9)\nx[x > 2 & x < 9]', output: '[1] 3 8' }),
    mc('After `x <- c(5, -1, 7)` and `x[x < 0] <- 0`, what is `x`?', ['`[1] 5 7`', '`[1] 5 0 7`', '`[1] 0`', '`[1] 0 -1 0`'], 1,
      'Only the matching values are changed.',
      { code: 'x <- c(5, -1, 7)\nx[x < 0] <- 0\nx', output: '[1] 5 0 7' }),
    qShort('Which function counts the TRUE values in a condition, as in `__(x > 5)`?', 'sum',
      '`sum()` adds up TRUE as 1 and FALSE as 0.'),
  ],
})
