// Vectors: NA in vectors.
import { R_INTRO, code, makeTopic, mc, near, qShort, same, snippet, task, uses } from '../_builders.mjs'

export default makeTopic({
  id: 'na_in_vectors',
  title: 'NA in vectors',
  paragraphs: [
    'Real vectors have gaps. One `NA` is enough to make a summary unknown, because R won\'t guess what the missing value was:',
    code('steps <- c(4200, NA, 6500, 9900, NA)', 'sum(steps)     # NA', 'mean(steps)    # NA'),
    'When you are happy to work with the values you do have, add `na.rm = TRUE` ("remove NAs"). Most summary functions accept it: `sum()`, `mean()`, `median()`, `min()`, `max()` and `range()`.',
    code('sum(steps, na.rm = TRUE)    # 20600', 'mean(steps, na.rm = TRUE)   # 6866.667: the average of the 3 known days'),
    'Be clear about what that means: the mean of the known days, not of the whole week. Always check how much is missing. `is.na()` works on a whole vector, so `sum(is.na(steps))` counts the gaps:',
    code('is.na(steps)          # FALSE TRUE FALSE FALSE TRUE', 'sum(is.na(steps))     # 2 missing days'),
    'To keep only the known values, pick with `!is.na()`: `steps[!is.na(steps)]` is `4200 6500 9900`. And to fill the gaps with a value, assign to them: `steps[is.na(steps)] <- 0`. Only do that when 0 really is right, such as a day the step counter was off and you know there was no walking.',
    'Watch out with conditions: `steps > 5000` gives `NA` for the missing days, and picking with it puts `NA`s in the result. `which()` in the next stage avoids that.',
  ],
  sandboxCode: 'steps <- c(4200, NA, 6500, 9900, NA)\nsum(steps)\nsum(steps, na.rm = TRUE)\nmean(steps, na.rm = TRUE)\nsum(is.na(steps))\nsteps[!is.na(steps)]',
  sandboxSnippets: [
    snippet('Fill the gaps', 'steps <- c(4200, NA, 6500, 9900, NA)\nsteps[is.na(steps)] <- 0\nsteps'),
    snippet('NA in a condition', 'steps <- c(4200, NA, 6500, 9900, NA)\nsteps > 5000\nsteps[steps > 5000]'),
    snippet('Share missing', 'answers <- c(4, NA, 5, 3, NA, NA, 4)\nmean(is.na(answers))'),
  ],
  readMore: R_INTRO('Missing-values', 'An Introduction to R: missing values'),
  challenges: [
    task('easy', 'Total without the gaps', {
      prompt: 'Make `total` the total of the known step counts.',
      starter: 'steps <- c(4200, NA, 6500, 9900, NA)\n',
      hint: '`total <- sum(steps, na.rm = TRUE)`',
      solution: 'steps <- c(4200, NA, 6500, 9900, NA)\ntotal <- sum(steps, na.rm = TRUE)',
      tests: [
        ['total is 20600', near('total', 20600)],
        ['Uses na.rm', uses('na.rm')],
      ],
    }),
    task('easy', 'Average of the known', {
      prompt: 'Make `avg` the average of the ratings that were given, rounded to 1 decimal place.',
      starter: 'ratings <- c(4, NA, 5, 3, 4, NA)\n',
      hint: '`avg <- round(mean(ratings, na.rm = TRUE), 1)`',
      solution: 'ratings <- c(4, NA, 5, 3, 4, NA)\navg <- round(mean(ratings, na.rm = TRUE), 1)',
      tests: [['avg is 4', near('avg', 4)]],
    }),
    task('easy', 'Count the gaps', {
      prompt: 'Make `n_missing` the number of missing ratings.',
      starter: 'ratings <- c(4, NA, 5, 3, 4, NA, NA)\n',
      hint: '`n_missing <- sum(is.na(ratings))`',
      solution: 'ratings <- c(4, NA, 5, 3, 4, NA, NA)\nn_missing <- sum(is.na(ratings))',
      tests: [
        ['n_missing is 3', near('n_missing', 3)],
        ['Uses is.na()', uses('is.na(')],
      ],
    }),
    task('medium', 'Only the known', {
      prompt: 'Make `known` the ratings that are not missing.',
      starter: 'ratings <- c(4, NA, 5, 3, 4, NA)\n',
      hint: '`known <- ratings[!is.na(ratings)]`',
      solution: 'ratings <- c(4, NA, 5, 3, 4, NA)\nknown <- ratings[!is.na(ratings)]',
      tests: [['known is 4, 5, 3, 4', near('known', 'c(4, 5, 3, 4)')]],
    }),
    task('medium', 'Highest reading', {
      prompt: 'Make `highest` the highest temperature that was recorded.',
      starter: 'temps <- c(18.2, NA, 21.0, 19.4, NA, 20.6)\n',
      hint: '`max()` takes `na.rm` too: `highest <- max(temps, na.rm = TRUE)`.',
      solution: 'temps <- c(18.2, NA, 21.0, 19.4, NA, 20.6)\nhighest <- max(temps, na.rm = TRUE)',
      tests: [['highest is 21', near('highest', 21)]],
    }),
    task('medium', 'Share missing', {
      prompt: 'Make `share_missing` the share of survey answers that are missing, as a number between 0 and 1.',
      starter: 'answers <- c(4, NA, 5, 3, NA, NA, 4, 2)\n',
      hint: '`mean()` of a TRUE/FALSE vector is the share that are TRUE: `mean(is.na(answers))`.',
      solution: 'answers <- c(4, NA, 5, 3, NA, NA, 4, 2)\nshare_missing <- mean(is.na(answers))',
      tests: [['share_missing is 0.375', near('share_missing', 0.375)]],
    }),
    task('hard', 'The counter was off', {
      prompt: 'The step counter was switched off on the missing days, so there was no walking. Replace every `NA` in `steps` with 0.',
      starter: 'steps <- c(4200, NA, 6500, 9900, NA)\n',
      hint: '`steps[is.na(steps)] <- 0`',
      solution: 'steps <- c(4200, NA, 6500, 9900, NA)\nsteps[is.na(steps)] <- 0',
      tests: [['steps is 4200, 0, 6500, 9900, 0', same('steps', 'c(4200, 0, 6500, 9900, 0)')]],
    }),
    task('expert', 'Fix the average', {
      prompt: 'This should give the average of the known scores, 75, but it gives a different number. Fix the second line.',
      starter: 'scores <- c(70, NA, 80, NA)\navg <- sum(scores, na.rm = TRUE) / length(scores)',
      hint: '`length(scores)` counts the NAs too, so it divides by 4. Use `mean(scores, na.rm = TRUE)` instead.',
      solution: 'scores <- c(70, NA, 80, NA)\navg <- mean(scores, na.rm = TRUE)',
      tests: [['avg is 75', near('avg', 75)]],
    }),
  ],
  questions: [
    mc('What does `sum(c(1, NA, 3))` give?', ['`4`', '`NA`', '`0`', 'An error'], 1,
      'One unknown value makes the total unknown.',
      { code: 'sum(c(1, NA, 3))', output: '[1] NA' }),
    mc('What does `sum(c(1, NA, 3), na.rm = TRUE)` give?', ['`4`', '`NA`', '`3`', '`5`'], 0,
      '`na.rm = TRUE` leaves the NA out: 1 + 3.',
      { code: 'sum(c(1, NA, 3), na.rm = TRUE)', output: '[1] 4' }),
    mc('What does `mean(c(2, NA, 4), na.rm = TRUE)` give?', ['`2`', '`3`', '`NA`', '`6`'], 1,
      'The average of the two known values, 2 and 4.',
      { code: 'mean(c(2, NA, 4), na.rm = TRUE)', output: '[1] 3' }),
    mc('What does `is.na(c(5, NA, 7))` give?', ['`TRUE`', '`[1] FALSE  TRUE FALSE`', '`[1] 1`', '`[1] 5 7`'], 1,
      '`is.na()` gives one TRUE or FALSE per value.',
      { code: 'is.na(c(5, NA, 7))', output: '[1] FALSE  TRUE FALSE' }),
    mc('What does `sum(is.na(c(NA, 2, NA)))` give?', ['`2`', '`NA`', '`1`', '`3`'], 0,
      'There are two TRUEs, so the count is 2.',
      { code: 'sum(is.na(c(NA, 2, NA)))', output: '[1] 2' }),
    mc('After `x <- c(5, NA, 7)`, what does `x[!is.na(x)]` give?', ['`[1] 5 NA 7`', '`[1] 5 7`', '`[1] NA`', '`[1] 2`'], 1,
      'It keeps the values that are not missing.',
      { code: 'x <- c(5, NA, 7)\nx[!is.na(x)]', output: '[1] 5 7' }),
    mc('After `x <- c(5, NA, 7)`, what does `x[x > 6]` give?', ['`[1] 7`', '`[1] NA  7`', '`[1] 5 7`', 'An error'], 1,
      '`NA > 6` is NA, and picking with NA gives an NA in the result.',
      { code: 'x <- c(5, NA, 7)\nx[x > 6]', output: '[1] NA  7' }),
    mc('What does `length(c(5, NA, 7))` give?', ['`2`', '`3`', '`NA`', '`12`'], 1,
      '`length()` counts every position, missing ones included.',
      { code: 'length(c(5, NA, 7))', output: '[1] 3' }),
    qShort('Which argument tells `sum()` and `mean()` to leave out missing values? (write it as `name = TRUE`)', 'na.rm = TRUE',
      '`na.rm` means "remove NAs".'),
  ],
})
