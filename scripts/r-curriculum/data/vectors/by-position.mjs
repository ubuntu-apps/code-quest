// Vectors: Picking items by position.
import { R_INTRO, code, isText, isTexts, makeTopic, mc, near, prints, qShort, snippet, task, uses } from '../_builders.mjs'

export default makeTopic({
  id: 'by_position',
  title: 'Picking items by position',
  paragraphs: [
    'To get values out of a vector, put their positions in square brackets after its name. Positions in R start at **1**, not 0:',
    code('days <- c("Mon", "Tue", "Wed", "Thu", "Fri")', 'days[1]          # "Mon"', 'days[c(1, 3)]    # "Mon" "Wed"', 'days[2:4]        # "Tue" "Wed" "Thu"'),
    'Inside the brackets you can use any vector of positions: one number, a `c()` of several, or a sequence like `2:4`. The values come back in the order you ask for them, so `days[c(3, 1)]` is `"Wed" "Mon"`.',
    'A **minus** sign leaves positions out: `days[-1]` is every day except Monday, and `days[-c(1, 5)]` drops the first and the last.',
    'The last value is at position `length(x)`, so `days[length(days)]` is `"Fri"` however long the vector is. Ask for a position past the end and you get `NA`: `days[9]` is `NA`, because there is no ninth day.',
    'You can also change values in place, by assigning to a position:',
    code('steps <- c(4200, 8100, 6500)', 'steps[2] <- 8300   # fix Tuesday\'s count', 'steps              # 4200 8300 6500'),
  ],
  sandboxCode: 'days <- c("Mon", "Tue", "Wed", "Thu", "Fri")\ndays[1]\ndays[c(1, 3)]\ndays[2:4]\ndays[-1]\ndays[length(days)]',
  sandboxSnippets: [
    snippet('Past the end', 'days <- c("Mon", "Tue", "Wed")\ndays[5]'),
    snippet('Change a value', 'steps <- c(4200, 8100, 6500)\nsteps[2] <- 8300\nsteps'),
    snippet('Any order', 'days <- c("Mon", "Tue", "Wed", "Thu", "Fri")\ndays[c(5, 1, 3)]'),
    snippet('From the end', 'x <- c(4, 8, 15, 16, 23)\nx[length(x)]\nx[(length(x) - 1):length(x)]'),
  ],
  readMore: R_INTRO('Index-vectors', 'An Introduction to R: index vectors'),
  challenges: [
    task('easy', 'The first day', {
      prompt: 'Make `first_day` the first value of `days`.',
      starter: 'days <- c("Mon", "Tue", "Wed", "Thu", "Fri")\n',
      hint: 'Positions start at 1: `first_day <- days[1]`.',
      solution: 'days <- c("Mon", "Tue", "Wed", "Thu", "Fri")\nfirst_day <- days[1]',
      tests: [
        ['first_day is "Mon"', isText('first_day', 'Mon')],
        ['Uses [ ]', uses('days[')],
      ],
    }),
    task('easy', 'The third score', {
      prompt: 'Show the third score in `scores`.',
      starter: 'scores <- c(71, 64, 88, 92, 57)\n',
      hint: '`scores[3]`',
      solution: 'scores <- c(71, 64, 88, 92, 57)\nscores[3]',
      tests: [
        ['Shows [1] 88', prints('[1] 88')],
        ['Uses [ ]', uses('scores[')],
      ],
    }),
    task('easy', 'Midweek', {
      prompt: 'Make `midweek` the 2nd, 3rd and 4th values of `days`, using `:` in the brackets.',
      starter: 'days <- c("Mon", "Tue", "Wed", "Thu", "Fri")\n',
      hint: '`midweek <- days[2:4]`',
      solution: 'days <- c("Mon", "Tue", "Wed", "Thu", "Fri")\nmidweek <- days[2:4]',
      tests: [
        ['midweek is "Tue" "Wed" "Thu"', isTexts('midweek', 'Tue', 'Wed', 'Thu')],
        ['Uses :', uses('2:4')],
      ],
    }),
    task('medium', 'First and last', {
      prompt: 'Make `ends` the first and the last reading of `temps`, using `c()` inside the brackets.',
      starter: 'temps <- c(16.2, 18.4, 21.0, 19.7, 17.5)\n',
      hint: '`ends <- temps[c(1, 5)]`, or use `length(temps)` for the last position.',
      solution: 'temps <- c(16.2, 18.4, 21.0, 19.7, 17.5)\nends <- temps[c(1, length(temps))]',
      tests: [['ends is 16.2, 17.5', near('ends', 'c(16.2, 17.5)')]],
    }),
    task('medium', 'All but the first', {
      prompt: 'The first lap was a warm-up. Make `real_laps` every lap time except the first, using a minus sign.',
      starter: 'laps <- c(95, 82, 80, 84, 79)\n',
      hint: '`real_laps <- laps[-1]`',
      solution: 'laps <- c(95, 82, 80, 84, 79)\nreal_laps <- laps[-1]',
      tests: [
        ['real_laps is 82, 80, 84, 79', near('real_laps', 'c(82, 80, 84, 79)')],
        ['Uses -1', uses('[-1]')],
      ],
    }),
    task('medium', 'Fix a typo in the data', {
      prompt: 'The second count was typed wrong: it should be 8300. Change it in place, keeping the other values.',
      starter: 'steps <- c(4200, 830, 6500, 9900)\n',
      hint: 'Assign to the position: `steps[2] <- 8300`.',
      solution: 'steps <- c(4200, 830, 6500, 9900)\nsteps[2] <- 8300',
      tests: [
        ['steps is 4200, 8300, 6500, 9900', near('steps', 'c(4200, 8300, 6500, 9900)')],
        ['Changes position 2', uses('steps[2]')],
      ],
    }),
    task('hard', 'The latest reading', {
      prompt: 'New readings are added all the time. Make `latest` the last value of `readings` in a way that still works when the vector gets longer.',
      starter: 'readings <- c(4.1, 3.8, 4.6, 5.0, 4.4, 4.9)\n',
      hint: 'The last position is `length(readings)`: `latest <- readings[length(readings)]`.',
      solution: 'readings <- c(4.1, 3.8, 4.6, 5.0, 4.4, 4.9)\nlatest <- readings[length(readings)]',
      tests: [
        ['latest is 4.9', near('latest', 4.9)],
        ['Uses length()', uses('length(readings)')],
      ],
    }),
    task('hard', 'Every other reading', {
      prompt: 'Make `odd` the 1st, 3rd and 5th readings.',
      starter: 'readings <- c(4.1, 3.8, 4.6, 5.0, 4.4, 4.9)\n',
      hint: 'Give several positions at once: `readings[c(1, 3, 5)]`.',
      solution: 'readings <- c(4.1, 3.8, 4.6, 5.0, 4.4, 4.9)\nodd <- readings[c(1, 3, 5)]',
      tests: [['odd is 4.1, 4.6, 4.4', near('odd', 'c(4.1, 4.6, 4.4)')]],
    }),
    task('expert', 'Drop the ends', {
      prompt: 'Judges drop the first and last score. Make `kept` every score except the first and the last, in a way that works for any length.',
      starter: 'scores <- c(6.5, 8.0, 7.5, 9.0, 7.0, 5.5)\n',
      hint: 'Leave out two positions with a minus: `scores[-c(1, length(scores))]`.',
      solution: 'scores <- c(6.5, 8.0, 7.5, 9.0, 7.0, 5.5)\nkept <- scores[-c(1, length(scores))]',
      tests: [
        ['kept is 8, 7.5, 9, 7', near('kept', 'c(8, 7.5, 9, 7)')],
        ['Uses length()', uses('length(scores)')],
      ],
    }),
    task('expert', 'The last three', {
      prompt: 'Make `last3` the last three values of `steps`. It should still work when the vector is a different length.',
      starter: 'steps <- c(4200, 8100, 6500, 9900, 3000, 7600, 5400)\n',
      alt: 'steps <- c(5000, 6000, 7000, 8000)\n',
      hint: '`length(steps)` is the last position. Brackets matter: `steps[(length(steps) - 2):length(steps)]`.',
      solution: 'steps <- c(4200, 8100, 6500, 9900, 3000, 7600, 5400)\nlast3 <- steps[(length(steps) - 2):length(steps)]',
      tests: [['last3 is 3000, 7600, 5400', near('last3', 'c(3000, 7600, 5400)')]],
    }),
  ],
  questions: [
    mc('After `x <- c(10, 20, 30)`, what does `x[2]` give?', ['`[1] 10`', '`[1] 20`', '`[1] 30`', '`[1] 10 20`'], 1,
      'Positions start at 1, so position 2 is the second value.',
      { code: 'x <- c(10, 20, 30)\nx[2]', output: '[1] 20' }),
    mc('After `x <- c(10, 20, 30)`, what does `x[-2]` give?', ['`[1] 20`', '`[1] 10 30`', '`[1] 10 20 30`', 'An error'], 1,
      'A minus leaves that position out.',
      { code: 'x <- c(10, 20, 30)\nx[-2]', output: '[1] 10 30' }),
    mc('Why does `x[5]` give NA when `x` has only three values?', ['There is no 5th value, so R says it is unknown instead of stopping with an error', 'R counts from 0', 'The 5th value was deleted', 'It gives an error'], 0,
      'Check `length(x)` when you aren\'t sure how long a vector is.',
      { code: 'x <- c(10, 20, 30)\nx[5]', output: '[1] NA' }),
    mc('After `x <- c(10, 20, 30)`, what does `x[c(3, 1)]` give?', ['`[1] 10 30`', '`[1] 30 10`', '`[1] 40`', '`[1] 30`'], 1,
      'Values come back in the order you ask for them.',
      { code: 'x <- c(10, 20, 30)\nx[c(3, 1)]', output: '[1] 30 10' }),
    mc('After `x <- c(10, 20, 30)`, what does `x[0]` give?', ['`[1] 10`', '`numeric(0)`: an empty vector', '`[1] NA`', 'An error'], 1,
      'There is no position 0 in R, so you get an empty vector of numbers.',
      { code: 'x <- c(10, 20, 30)\nx[0]', output: 'numeric(0)' }),
    mc('After `x <- c(5, 6, 7)` and `x[2] <- 0`, what is `x`?', ['`[1] 5 0 7`', '`[1] 0 6 7`', '`[1] 5 6 7 0`', '`[1] 0`'], 0,
      'Assigning to a position changes just that value.',
      { code: 'x <- c(5, 6, 7)\nx[2] <- 0\nx', output: '[1] 5 0 7' }),
    mc('Which gives the last value of any vector `x`?', ['`x[-1]`', '`x[0]`', '`x[length(x)]`', '`x[last]`'], 2,
      'The last position is the length. `x[-1]` drops the first value instead.'),
    mc('After `x <- c(4, 8, 15, 16, 23)`, what does `x[2:3]` give?', ['`[1] 8 15`', '`[1] 4 8 15`', '`[1] 8`', '`[1] 15 16`'], 0,
      '`2:3` is positions 2 and 3.',
      { code: 'x <- c(4, 8, 15, 16, 23)\nx[2:3]', output: '[1]  8 15' }),
    qShort('In R, what is the position of the first value in a vector?', '1',
      'R counts positions from 1.'),
  ],
})
