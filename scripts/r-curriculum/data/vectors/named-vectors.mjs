// Vectors: Named vectors.
import { R_INTRO, code, isText, isTexts, makeTopic, mc, near, prints, qShort, same, snippet, task, uses } from '../_builders.mjs'

export default makeTopic({
  id: 'named_vectors',
  title: 'Named vectors',
  paragraphs: [
    'So far, matching values have lived in two vectors: `days` and `steps`. R can also give each value of a vector a **name**, so the labels travel with the values:',
    code('steps <- c(Mon = 4200, Tue = 8100, Wed = 9900)', 'steps'),
    'R shows the names above the values. You can also add names to a vector you already have, with `names()`, or read them back:',
    code('prices <- c(3.4, 2.5, 4.2)', 'names(prices) <- c("latte", "tea", "cake")', 'names(prices)    # "latte" "tea" "cake"'),
    'Pick values by name, in quotes, instead of by position. That\'s easier to read and doesn\'t break when the order changes:',
    code('prices["tea"]               # tea 2.5', 'prices[c("cake", "latte")]'),
    'Names survive everything you have learned in this quest: maths (`prices * 2` keeps the names), conditions (`prices[prices > 3]`) and sorting (`sort(prices)`). Combined with `which.max()`, they answer "which one?" directly: `names(which.max(steps))` is `"Wed"`.',
    'Named vectors are a small step towards the data frames you will meet soon, where every column has a name. To drop the names and keep just the values, use `unname()`.',
  ],
  sandboxCode: 'steps <- c(Mon = 4200, Tue = 8100, Wed = 9900)\nsteps\nsteps["Tue"]\nnames(steps)\nnames(which.max(steps))',
  sandboxSnippets: [
    snippet('Add names', 'prices <- c(3.4, 2.5, 4.2)\nnames(prices) <- c("latte", "tea", "cake")\nprices'),
    snippet('Names survive', 'prices <- c(latte = 3.4, tea = 2.5, cake = 4.2)\nprices * 2\nprices[prices > 3]\nsort(prices)'),
    snippet('Drop the names', 'prices <- c(latte = 3.4, tea = 2.5)\nunname(prices)'),
  ],
  readMore: { label: 'R documentation: names()', url: 'https://stat.ethz.ch/R-manual/R-devel/library/base/html/names.html', source: 'R documentation' },
  challenges: [
    task('easy', 'A named price list', {
      prompt: 'Make `prices` a named vector: `latte` 3.4, `tea` 2.5 and `cake` 4.2.',
      hint: 'Names go before the values in `c()`: `c(latte = 3.4, tea = 2.5, cake = 4.2)`.',
      solution: 'prices <- c(latte = 3.4, tea = 2.5, cake = 4.2)',
      tests: [['prices is latte 3.4, tea 2.5, cake 4.2', same('prices', 'c(latte = 3.4, tea = 2.5, cake = 4.2)')]],
    }),
    task('easy', 'Look up by name', {
      prompt: 'Show the price of tea, picking it by name.',
      starter: 'prices <- c(latte = 3.4, tea = 2.5, cake = 4.2)\n',
      hint: '`prices["tea"]`',
      solution: 'prices <- c(latte = 3.4, tea = 2.5, cake = 4.2)\nprices["tea"]',
      tests: [
        ['Shows the tea price with its name', prints('tea', '2.5')],
        ['Picks by name', uses('"tea"')],
      ],
    }),
    task('easy', 'Read the names', {
      prompt: 'Make `items` the names of the `prices` vector.',
      starter: 'prices <- c(latte = 3.4, tea = 2.5, cake = 4.2)\n',
      hint: '`items <- names(prices)`',
      solution: 'prices <- c(latte = 3.4, tea = 2.5, cake = 4.2)\nitems <- names(prices)',
      tests: [['items is latte, tea, cake', isTexts('items', 'latte', 'tea', 'cake')]],
    }),
    task('medium', 'Label the readings', {
      prompt: 'Give the `rain` vector the names `Mon`, `Tue`, `Wed` and `Thu`, using `names()`.',
      starter: 'rain <- c(0, 4.5, 12.2, 1.0)\n',
      hint: '`names(rain) <- c("Mon", "Tue", "Wed", "Thu")`',
      solution: 'rain <- c(0, 4.5, 12.2, 1.0)\nnames(rain) <- c("Mon", "Tue", "Wed", "Thu")',
      tests: [
        ['rain has the day names', same('rain', 'c(Mon = 0, Tue = 4.5, Wed = 12.2, Thu = 1.0)')],
        ['Uses names()', uses('names(rain)')],
      ],
    }),
    task('medium', 'Two by name', {
      prompt: 'Make `pair` the prices of `cake` and `latte`, in that order, picked by name.',
      starter: 'prices <- c(latte = 3.4, tea = 2.5, cake = 4.2)\n',
      hint: '`pair <- prices[c("cake", "latte")]`',
      solution: 'prices <- c(latte = 3.4, tea = 2.5, cake = 4.2)\npair <- prices[c("cake", "latte")]',
      tests: [['pair is cake 4.2, latte 3.4', same('pair', 'c(cake = 4.2, latte = 3.4)')]],
    }),
    task('medium', 'The wettest day', {
      prompt: 'Make `wettest` the name of the day with the most rain.',
      starter: 'rain <- c(Mon = 0, Tue = 4.5, Wed = 12.2, Thu = 1.0)\n',
      hint: '`which.max()` keeps the name: `wettest <- names(which.max(rain))`.',
      solution: 'rain <- c(Mon = 0, Tue = 4.5, Wed = 12.2, Thu = 1.0)\nwettest <- names(which.max(rain))',
      tests: [
        ['wettest is "Wed"', isText('wettest', 'Wed')],
        ['Works it out from rain', uses('rain')],
      ],
    }),
    task('hard', 'Dry days', {
      prompt: 'Make `dry_days` the names of the days with less than 2 mm of rain.',
      starter: 'rain <- c(Mon = 0, Tue = 4.5, Wed = 12.2, Thu = 1.0, Fri = 0.4)\n',
      hint: 'Pick with a condition, then take the names: `names(rain[rain < 2])`.',
      solution: 'rain <- c(Mon = 0, Tue = 4.5, Wed = 12.2, Thu = 1.0, Fri = 0.4)\ndry_days <- names(rain[rain < 2])',
      tests: [['dry_days is Mon, Thu, Fri', isTexts('dry_days', 'Mon', 'Thu', 'Fri')]],
    }),
    task('expert', 'A price change', {
      prompt: 'Tea goes up to 2.7. Change it by name, then make `menu` the prices sorted from cheapest to dearest, keeping the names.',
      starter: 'prices <- c(latte = 3.4, tea = 2.5, cake = 4.2, water = 1.8)\n',
      hint: '`prices["tea"] <- 2.7`, then `menu <- sort(prices)`.',
      solution: 'prices <- c(latte = 3.4, tea = 2.5, cake = 4.2, water = 1.8)\nprices["tea"] <- 2.7\nmenu <- sort(prices)',
      tests: [
        ['tea is now 2.7', 'isTRUE(all.equal(unname(prices["tea"]), 2.7))'],
        ['menu is water, tea, latte, cake', same('menu', 'c(water = 1.8, tea = 2.7, latte = 3.4, cake = 4.2)')],
      ],
    }),
  ],
  questions: [
    mc('After `x <- c(a = 1, b = 2)`, what does `x["b"]` give?', ['`2`, with the name `b` above it', '`"b"`', '`1`', 'An error'], 0,
      'Picking by name gives the value, and its name comes along.',
      { code: 'x <- c(a = 1, b = 2)\nx["b"]', output: 'b \n2' }),
    mc('After `x <- c(a = 1, b = 2)`, what does `names(x)` give?', ['`[1] 1 2`', '`[1] "a" "b"`', '`[1] "x"`', '`NULL`'], 1,
      '`names()` gives the names as a text vector.',
      { code: 'x <- c(a = 1, b = 2)\nnames(x)', output: '[1] "a" "b"' }),
    mc('After `x <- c(a = 1, b = 2)`, what does `x * 10` give?', ['`[1] 10 20` with no names', '`10 20`, with the names `a` and `b` kept', 'An error', '`[1] 30`'], 1,
      'Arithmetic keeps the names.',
      { code: 'x <- c(a = 1, b = 2)\nx * 10', output: 'a  b \n10 20' }),
    mc('What does `names(which.max(c(x = 3, y = 8, z = 5)))` give?', ['`[1] 2`', '`[1] "y"`', '`[1] 8`', '`[1] "z"`'], 1,
      'The largest value, 8, is named "y".',
      { code: 'names(which.max(c(x = 3, y = 8, z = 5)))', output: '[1] "y"' }),
    mc('What does `names(c(5, 6))` give?', ['`NULL`: there are no names', '`[1] "" ""`', '`[1] 1 2`', 'An error'], 0,
      'A vector made without names has none, so `names()` gives `NULL`.',
      { code: 'names(c(5, 6))', output: 'NULL' }),
    mc('After `x <- c(a = 1, b = 2)`, what does `x["c"]` give?', ['An error', '`NA`, named `<NA>`', '`0`', '`[1] "c"`'], 1,
      'There is no value called "c", so R gives NA.',
      { code: 'x <- c(a = 1, b = 2)\nx["c"]', output: '<NA> \n  NA' }),
    mc('Why pick by name, like `prices["tea"]`, instead of `prices[2]`?', ['It is faster', 'It still works when the order of the values changes', 'Positions don\'t work on named vectors', 'It removes the name'], 1,
      'A name stays with its value; a position depends on the order.'),
    mc('Which drops the names and keeps the values?', ['`names(x) <- 0`', '`unname(x)`', '`x[-names]`', '`c(x)`'], 1,
      '`unname()` gives the same values without names.',
      { code: 'unname(c(a = 1, b = 2))', output: '[1] 1 2' }),
    qShort('Which function gives or sets the names of a vector?', 'names',
      '`names(x)` reads them; `names(x) <- c(...)` sets them.'),
  ],
})
