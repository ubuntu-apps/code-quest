// First steps in R: Calling functions.
import { R_INTRO, code, makeTopic, mc, near, prints, qShort, snippet, task, uses } from '../_builders.mjs'

export default makeTopic({
  id: 'functions',
  title: 'Calling functions',
  paragraphs: [
    'A **function** does a job for you. You call it by name, with its inputs, called **arguments**, in brackets. You have already used `print()`, `cat()`, `paste()` and `nchar()`. R has thousands more; here are some for numbers:',
    '| Function | What it does | Example | Result |\n| --- | --- | --- | --- |\n| `sqrt()` | square root | `sqrt(144)` | `12` |\n| `abs()` | drops the minus sign | `abs(-7)` | `7` |\n| `round()` | rounds | `round(3.14159, 2)` | `3.14` |\n| `ceiling()` | rounds up | `ceiling(4.2)` | `5` |\n| `floor()` | rounds down | `floor(4.8)` | `4` |\n| `max()`, `min()` | largest, smallest | `max(18, 42, 27)` | `42` |',
    'Some functions take several arguments, separated by commas. `round(3.14159, 2)` rounds to 2 decimal places. Arguments have names, and you can write them out, which makes code easier to read: `round(3.14159, digits = 2)` does the same thing. Named arguments can go in any order.',
    'Leave out an argument that has a default, and R uses the default: `round(3.7)` rounds to a whole number, 4.',
    'One surprise: R rounds a 5 to the nearest **even** number, so `round(2.5)` is 2 and `round(3.5)` is 4. Statisticians do this so rounding doesn\'t push totals up on average.',
    'You can put one function call inside another. R works from the inside out:',
    code('round(sqrt(50), 1)   # sqrt first: 7.071..., then round: 7.1'),
    'To read about any function, type `?` and its name, such as `?round`, in RStudio or the R console. The help pages list every argument and its default. (Help pages don\'t open inside CodeQuest; the **Read more** link at the end of each stage points to R\'s manuals.)',
  ],
  sandboxCode: 'sqrt(144)\nabs(-7)\nround(3.14159, 2)\nround(3.14159, digits = 3)\nmax(18, 42, 27)',
  sandboxSnippets: [
    snippet('Round up and down', 'ceiling(4.2)\nfloor(4.8)\nround(4.5)\nround(5.5)'),
    snippet('Inside out', 'sqrt(50)\nround(sqrt(50), 1)'),
    snippet('Named arguments', 'round(2.71828, digits = 2)\nround(digits = 2, x = 2.71828)'),
    snippet('Round to tens', 'round(1234.5678, -1)\nround(1234.5678, -2)'),
  ],
  readMore: R_INTRO('Writing-your-own-functions', 'An Introduction to R: functions and arguments'),
  challenges: [
    task('easy', 'A square root', {
      prompt: 'Show the square root of 144.',
      hint: '`sqrt(144)`',
      solution: 'sqrt(144)',
      tests: [
        ['Shows [1] 12', prints('[1] 12')],
        ['Uses sqrt()', uses('sqrt(')],
      ],
    }),
    task('easy', 'Two decimal places', {
      prompt: 'Make `short_pi` the number `3.14159` rounded to 2 decimal places.',
      hint: '`short_pi <- round(3.14159, 2)`',
      solution: 'short_pi <- round(3.14159, 2)',
      tests: [
        ['short_pi is 3.14', near('short_pi', 3.14)],
        ['Uses round()', uses('round(')],
      ],
    }),
    task('easy', 'How far apart', {
      prompt: 'Make `gap` the distance between 3 and 10, without a minus sign, by taking `abs()` of `3 - 10`.',
      hint: '`gap <- abs(3 - 10)`',
      solution: 'gap <- abs(3 - 10)',
      tests: [
        ['gap is 7', near('gap', 7)],
        ['Uses abs()', uses('abs(')],
      ],
    }),
    task('medium', 'The highest score', {
      prompt: 'Make `best` the highest of the scores 18, 42 and 27, using a function.',
      hint: '`best <- max(18, 42, 27)`',
      solution: 'best <- max(18, 42, 27)',
      tests: [
        ['best is 42', near('best', 42)],
        ['Uses max()', uses('max(')],
      ],
    }),
    task('medium', 'Name the argument', {
      prompt: 'Make `e3` the number `2.71828` rounded to 3 decimal places. Name the argument: `digits = 3`.',
      hint: '`e3 <- round(2.71828, digits = 3)`',
      solution: 'e3 <- round(2.71828, digits = 3)',
      tests: [
        ['e3 is 2.718', near('e3', 2.718)],
        ['Names the digits argument', uses('digits')],
      ],
    }),
    task('medium', 'Inside out', {
      prompt: 'Make `side` the square root of 50, rounded to 1 decimal place, in one line.',
      hint: 'Put `sqrt(50)` inside `round(…, 1)`.',
      solution: 'side <- round(sqrt(50), 1)',
      tests: [
        ['side is 7.1', near('side', 7.1)],
        ['Uses sqrt() and round()', uses('sqrt(') + ' && ' + uses('round(')],
      ],
    }),
    task('hard', 'Enough taxis', {
      prompt: 'Each taxi takes 4 people. Make `taxis` the number of taxis needed for `people`.',
      starter: 'people <- 23\n',
      hint: 'A part-full taxi still counts, so round up: `taxis <- ceiling(people / 4)`.',
      solution: 'people <- 23\ntaxis <- ceiling(people / 4)',
      tests: [['taxis is 6', near('taxis', 6)]],
    }),
    task('hard', 'Fix the call', {
      prompt: 'This line gives an error. Fix it so it shows `[1] 9.88`.',
      starter: 'round(9.876 2)',
      hint: 'Arguments are separated by commas.',
      solution: 'round(9.876, 2)',
      tests: [['Shows [1] 9.88', prints('[1] 9.88')]],
    }),
    task('expert', 'Enough boxes', {
      prompt: '50 eggs go into boxes of 6, and the last box may be part full. Make `boxes` the number of boxes needed.',
      hint: '`50 / 6` is about 8.3, and you need a whole box for the rest: round **up** with `ceiling()`.',
      solution: 'boxes <- ceiling(50 / 6)',
      tests: [
        ['boxes is 9', near('boxes', 9)],
        ['Rounds up with ceiling()', uses('ceiling(')],
      ],
    }),
  ],
  questions: [
    mc('What does `round(2.567, 1)` give?', ['`2.5`', '`2.6`', '`2.57`', '`3`'], 1,
      'One decimal place: 2.567 is nearer 2.6 than 2.5.',
      { code: 'round(2.567, 1)', output: '[1] 2.6' }),
    mc('What does `round(2.5)` give?', ['`3`', '`2.5`', '`2`', 'An error'], 2,
      'R rounds a 5 to the nearest even number: 2.5 becomes 2 (and 3.5 becomes 4).',
      { code: 'round(2.5)', output: '[1] 2' }),
    mc('What does `ceiling(4.2)` give?', ['`4`', '`4.2`', '`5`', '`4.5`'], 2,
      '`ceiling()` always rounds up.',
      { code: 'ceiling(4.2)', output: '[1] 5' }),
    mc('What does `floor(4.8)` give?', ['`4`', '`5`', '`4.8`', '`4.5`'], 0,
      '`floor()` always rounds down.',
      { code: 'floor(4.8)', output: '[1] 4' }),
    mc('What does `max(4, 9, 2)` give?', ['`4`', '`2`', '`15`', '`9`'], 3,
      '`max()` gives the largest of its arguments.',
      { code: 'max(4, 9, 2)', output: '[1] 9' }),
    mc('What does `abs(-3.5)` give?', ['`-3.5`', '`3.5`', '`3`', '`4`'], 1,
      '`abs()` drops the minus sign.',
      { code: 'abs(-3.5)', output: '[1] 3.5' }),
    mc('What does `round(1234.5678, -2)` give?', ['`1234.57`', '`1200`', '`1234.6`', '`1300`'], 1,
      'A negative number of digits rounds to tens (−1), hundreds (−2) and so on.',
      { code: 'round(1234.5678, -2)', output: '[1] 1200' }),
    mc('Do `round(3.14159, 2)` and `round(digits = 2, x = 3.14159)` give the same result?', ['No', 'Yes: named arguments can go in any order', 'Only in RStudio', 'The second gives an error'], 1,
      'With names, R knows which value is which, whatever the order.',
      { code: 'round(digits = 2, x = 3.14159)', output: '[1] 3.14' }),
    mc('What does `round(sqrt(16) + 0.46, 1)` give?', ['`4.5`', '`4.4`', '`4.46`', '`4`'], 0,
      'Inside first: sqrt(16) is 4, plus 0.46 is 4.46, rounded to 1 place is 4.5.',
      { code: 'round(sqrt(16) + 0.46, 1)', output: '[1] 4.5' }),
    qShort('Which function rounds a number up to the next whole number?', 'ceiling',
      '`ceiling()` rounds up; `floor()` rounds down.'),
  ],
})
