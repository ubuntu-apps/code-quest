// First steps in R: Missing values: NA.
import { R_INTRO, code, isLogical, makeTopic, mc, near, prints, qShort, r, snippet, task, uses } from '../_builders.mjs'

export default makeTopic({
  id: 'missing_values',
  title: 'Missing values: NA',
  paragraphs: [
    'Real data has gaps: a survey question someone skipped, a day the sensor was off, a price nobody wrote down. R marks a missing value with `NA`, short for "not available". It is written without quotes.',
    code('rating <- NA', 'rating'),
    'R is careful with `NA`. If a value is unknown, anything worked out from it is unknown too, so maths with `NA` gives `NA`:',
    code('NA + 1      # NA', 'NA * 0      # NA', 'NA > 5      # NA'),
    'Even `NA == NA` is `NA`: two unknown values might or might not be the same. So you can\'t test for a missing value with `==`. Use `is.na()`, which gives `TRUE` or `FALSE`:',
    code('is.na(rating)   # TRUE', 'is.na(42)       # FALSE', '!is.na(42)      # TRUE: it has a value'),
    'Sometimes R can answer even with a gap. `TRUE | NA` is `TRUE`, because "true or anything" is true. `FALSE & NA` is `FALSE`, because "false and anything" is false.',
    'Watch out for the text `"NA"` in quotes. That is two letters, not a missing value: `is.na("NA")` is `FALSE`. Data files sometimes contain it by mistake, and a later quest shows how to clean it up.',
    'Once you have many values, R lets you skip the `NA`s when you add them up or take an average. That\'s in the next quest, *Vectors*.',
  ],
  sandboxCode: 'steps <- NA\nsteps + 100\nis.na(steps)\nis.na(250)',
  sandboxSnippets: [
    snippet('NA spreads', 'NA + 1\nNA * 0\nNA > 5\nNA == NA'),
    snippet('Answers with a gap', 'TRUE | NA\nFALSE & NA\nTRUE & NA'),
    snippet('Text "NA"', 'is.na(NA)\nis.na("NA")'),
  ],
  readMore: R_INTRO('Missing-values', 'An Introduction to R: missing values'),
  challenges: [
    task('easy', 'A missing rating', {
      prompt: 'A customer left no rating. Make `rating` a missing value.',
      hint: '`rating <- NA` (no quotes).',
      solution: 'rating <- NA',
      tests: [['rating is NA, not text', 'length(rating) == 1 && is.na(rating) && !is.character(rating)']],
    }),
    task('easy', 'Is it missing', {
      prompt: 'Make `missing` the answer to: is `steps` missing?',
      starter: 'steps <- NA\n',
      hint: '`missing <- is.na(steps)`',
      solution: 'steps <- NA\nmissing <- is.na(steps)',
      tests: [
        ['missing is TRUE', isLogical('missing', true)],
        ['Uses is.na()', uses('is.na(')],
      ],
    }),
    task('easy', 'Maths with a gap', {
      prompt: 'Nobody recorded `steps` today. Show `steps + 100` and see what R does.',
      starter: 'steps <- NA\n',
      hint: 'Add a line: `steps + 100`. The answer is unknown too.',
      solution: 'steps <- NA\nsteps + 100',
      tests: [['Shows [1] NA', prints('[1] NA')]],
    }),
    task('medium', 'Text, not missing', {
      prompt: 'A data file had the text `"NA"` in it. Make `is_missing` the answer to: is `value` missing?',
      starter: 'value <- "NA"\n',
      hint: '`is_missing <- is.na(value)`. Text in quotes is a real value, so the answer is FALSE.',
      solution: 'value <- "NA"\nis_missing <- is.na(value)',
      tests: [
        ['is_missing is FALSE', isLogical('is_missing', false)],
        ['Uses is.na()', uses('is.na(')],
      ],
    }),
    task('medium', 'Has a value', {
      prompt: 'Make `has_value` the answer to: does `reading` have a value? Use `is.na()` and `!`.',
      starter: 'reading <- 12\n',
      hint: '`has_value <- !is.na(reading)`',
      solution: 'reading <- 12\nhas_value <- !is.na(reading)',
      tests: [
        ['has_value is TRUE', isLogical('has_value', true)],
        ['Uses !is.na()', uses('!is.na(')],
      ],
    }),
    task('medium', 'Fix the test', {
      prompt: 'The last line should show `[1] TRUE`, because `x` is missing. It shows `[1] NA`. Fix it.',
      starter: 'x <- NA\nx == NA',
      hint: '`==` can\'t test for NA. Use `is.na(x)`.',
      solution: 'x <- NA\nis.na(x)',
      tests: [['Shows [1] TRUE', prints('[1] TRUE')]],
    }),
    task('hard', 'True whatever the gap', {
      prompt: 'Make `answer` the result of `TRUE | NA`, then show it. R can answer even though one side is missing.',
      hint: '`answer <- TRUE | NA`, then `answer` on its own line.',
      solution: 'answer <- TRUE | NA\nanswer',
      tests: [
        ['answer is TRUE', isLogical('answer', true)],
        ['Shows [1] TRUE', prints('[1] TRUE')],
      ],
    }),
    task('hard', 'Count the gaps', {
      prompt: 'A rain gauge sent readings on Monday, Tuesday and Wednesday, but some are missing. Make `n_missing` the number of missing readings, by adding up three `is.na()` results.',
      starter: 'mon <- NA\ntue <- 7.5\nwed <- NA\n',
      hint: 'TRUE counts as 1: `n_missing <- is.na(mon) + is.na(tue) + is.na(wed)`.',
      solution: 'mon <- NA\ntue <- 7.5\nwed <- NA\nn_missing <- is.na(mon) + is.na(tue) + is.na(wed)',
      tests: [
        ['n_missing is 2', near('n_missing', 2)],
        ['Uses is.na()', uses('is.na(')],
      ],
    }),
    task('expert', 'Report a gap', {
      prompt: 'Show `Missing: TRUE` with `cat()`, letting `is.na()` work out the `TRUE` for `reading`.',
      starter: 'reading <- NA\n',
      hint: '`cat("Missing:", is.na(reading), "\\n")`',
      solution: r`reading <- NA
cat("Missing:", is.na(reading), "\n")`,
      tests: [
        ['Shows Missing: TRUE', prints('Missing: TRUE')],
        ['Uses is.na()', uses('is.na(')],
      ],
    }),
  ],
  questions: [
    mc('What does `NA + 1` give?', ['`1`', '`NA`', '`0`', 'An error'], 1,
      'Anything worked out from an unknown value is unknown.',
      { code: 'NA + 1', output: '[1] NA' }),
    mc('What does `NA == NA` give?', ['`TRUE`', '`FALSE`', '`NA`', 'An error'], 2,
      'Two unknown values might or might not be equal, so the answer is unknown. Use `is.na()` instead.',
      { code: 'NA == NA', output: '[1] NA' }),
    mc('What does `is.na("NA")` give?', ['`TRUE`', '`FALSE`', '`NA`', 'An error'], 1,
      '`"NA"` in quotes is two letters of text, not a missing value.',
      { code: 'is.na("NA")', output: '[1] FALSE' }),
    mc('What does `TRUE | NA` give?', ['`NA`', '`FALSE`', '`TRUE`', 'An error'], 2,
      '"TRUE or anything" is TRUE, so R doesn\'t need the missing value.',
      { code: 'TRUE | NA', output: '[1] TRUE' }),
    mc('What does `FALSE & NA` give?', ['`FALSE`', '`NA`', '`TRUE`', '`0`'], 0,
      '"FALSE and anything" is FALSE.',
      { code: 'FALSE & NA', output: '[1] FALSE' }),
    mc('What does `TRUE & NA` give?', ['`TRUE`', '`FALSE`', '`NA`', 'An error'], 2,
      'Here the answer depends on the missing value, so it is unknown.',
      { code: 'TRUE & NA', output: '[1] NA' }),
    mc('What does `!is.na(7)` give?', ['`FALSE`', '`TRUE`', '`NA`', '`7`'], 1,
      '7 is not missing, so `is.na(7)` is FALSE and `!` turns it into TRUE.',
      { code: '!is.na(7)', output: '[1] TRUE' }),
    mc('What does `NA > 5` give?', ['`TRUE`', '`FALSE`', '`NA`', '`5`'], 2,
      'R can\'t tell whether an unknown value is bigger than 5.',
      { code: 'NA > 5', output: '[1] NA' }),
    qShort('Which function tests whether a value is missing?', 'is.na',
      '`is.na(x)` is TRUE when `x` is NA.'),
  ],
})
