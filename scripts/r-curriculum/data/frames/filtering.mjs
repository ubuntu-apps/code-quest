// Data frames: Filtering rows.
import { code, isTexts, makeTopic, mc, near, qShort, sameFrame, snippet, task, uses } from '../_builders.mjs'
import { TRIPS } from '../datasets.mjs'

export default makeTopic({
  id: 'filtering',
  title: 'Filtering rows',
  paragraphs: [
    'Keeping only the rows you care about is called **filtering**. This stage uses the Riverside Bikes trips:',
    code(...TRIPS.trim().split('\n')),
    'You already know how: put a condition in the rows part of the brackets. Every tool for conditions works, because each column is a vector:',
    code('trips[trips$minutes > 30, ]                              # long trips', 'trips[trips$station == "Park" & trips$member, ]          # members from Park', 'trips[trips$station %in% c("Park", "River"), ]           # two stations', 'trips[!trips$member, ]                                   # non-members'),
    'Writing `trips$` again and again gets long. `subset()` does the same with the column names alone, and can pick columns too:',
    code('subset(trips, minutes > 30)', 'subset(trips, station == "Park" & member, select = c(id, minutes))'),
    'A filtered table is a data frame like any other, so you can count its rows or summarise a column of it: `nrow(subset(trips, member))` is the number of member trips, and `mean(subset(trips, member)$minutes)` their average length.',
    'One trap: if a column has `NA`s, a condition gives `NA` for those rows, and `trips[cond, ]` adds a row of NAs to the result. `subset()` leaves those rows out, which is one more reason to prefer it. (`which(cond)` works too.)',
  ],
  sandboxCode: TRIPS + 'trips[trips$minutes > 30, ]\nsubset(trips, station == "Park" & member)\nnrow(subset(trips, member))',
  sandboxSnippets: [
    snippet('Pick columns too', TRIPS + 'subset(trips, minutes > 30, select = c(id, station, minutes))'),
    snippet('NA in a condition', 'df <- data.frame(x = c(5, NA, 9))\ndf[df$x > 6, , drop = FALSE]\nsubset(df, x > 6)'),
    snippet('Above the average', TRIPS + 'subset(trips, minutes > mean(minutes))'),
    snippet('Brackets with which()', 'df <- data.frame(x = c(5, NA, 9))\ndf[which(df$x > 6), , drop = FALSE]'),
  ],
  readMore: { label: 'R documentation: subset()', url: 'https://stat.ethz.ch/R-manual/R-devel/library/base/html/subset.html', source: 'R documentation' },
  challenges: [
    task('easy', 'Long trips', {
      prompt: 'Make `long` the trips of more than 30 minutes.',
      starter: TRIPS,
      hint: '`long <- trips[trips$minutes > 30, ]` or `subset(trips, minutes > 30)`.',
      solution: TRIPS + 'long <- subset(trips, minutes > 30)',
      tests: [['long is trips 2, 5 and 8', sameFrame('long', 'trips[c(2, 5, 8), ]')]],
    }),
    task('easy', 'From the market', {
      prompt: 'Make `market` the trips that started at the `Market` station.',
      starter: TRIPS,
      hint: '`market <- subset(trips, station == "Market")`',
      solution: TRIPS + 'market <- subset(trips, station == "Market")',
      tests: [['market is trips 4 and 7', sameFrame('market', 'trips[c(4, 7), ]')]],
    }),
    task('easy', 'Non-members', {
      prompt: 'Make `guests` the trips by non-members.',
      starter: TRIPS,
      hint: '`!` turns TRUE into FALSE: `guests <- subset(trips, !member)`.',
      solution: TRIPS + 'guests <- subset(trips, !member)',
      tests: [['guests is trips 2, 5 and 7', sameFrame('guests', 'trips[c(2, 5, 7), ]')]],
    }),
    task('medium', 'Members from the park', {
      prompt: 'Make `park_members` the trips from `Park` by members.',
      starter: TRIPS,
      hint: 'Join the two conditions with `&`: `subset(trips, station == "Park" & member)`.',
      solution: TRIPS + 'park_members <- subset(trips, station == "Park" & member)',
      tests: [['park_members is trips 1, 3 and 6', sameFrame('park_members', 'trips[c(1, 3, 6), ]')]],
    }),
    task('medium', 'Two stations', {
      prompt: 'Make `two` the trips from `Park` or `Market`, using `%in%`.',
      starter: TRIPS,
      hint: '`subset(trips, station %in% c("Park", "Market"))`',
      solution: TRIPS + 'two <- subset(trips, station %in% c("Park", "Market"))',
      tests: [['two is trips 1, 3, 4, 6 and 7', sameFrame('two', 'trips[c(1, 3, 4, 6, 7), ]')], ['Uses %in%', uses('%in%')]],
    }),
    task('medium', 'How many short trips', {
      prompt: 'Make `n_short` the number of trips of 15 minutes or less.',
      starter: TRIPS,
      hint: 'Filter, then count the rows: `nrow(subset(trips, minutes <= 15))`.',
      solution: TRIPS + 'n_short <- nrow(subset(trips, minutes <= 15))',
      tests: [['n_short is 3', near('n_short', 3)]],
    }),
    task('hard', 'Pick the columns too', {
      prompt: 'Make `far` the `id` and `km` of the trips longer than 5 km.',
      starter: TRIPS,
      hint: '`subset(trips, km > 5, select = c(id, km))`',
      solution: TRIPS + 'far <- subset(trips, km > 5, select = c(id, km))',
      tests: [['far is id and km of trips 2, 3, 5 and 8', sameFrame('far', 'trips[c(2, 3, 5, 8), c("id", "km")]')]],
    }),
    task('hard', 'Short or a member', {
      prompt: 'Make `picked` the trips that are under 15 minutes **or** were made by a member.',
      starter: TRIPS,
      hint: '`|` means "or": `subset(trips, minutes < 15 | member)`.',
      solution: TRIPS + 'picked <- subset(trips, minutes < 15 | member)',
      tests: [['picked is the right trips', sameFrame('picked', 'trips[trips$minutes < 15 | trips$member, ]')]],
    }),
    task('expert', 'Average for members', {
      prompt: 'Make `member_avg` the average trip length in minutes for members only, and `guest_avg` for non-members, each rounded to 1 decimal place.',
      starter: TRIPS,
      hint: 'Filter, take the column, average: `round(mean(subset(trips, member)$minutes), 1)`.',
      solution: TRIPS + 'member_avg <- round(mean(subset(trips, member)$minutes), 1)\nguest_avg <- round(mean(subset(trips, !member)$minutes), 1)',
      tests: [['member_avg is 20', near('member_avg', 20)], ['guest_avg is 41.3', near('guest_avg', 41.3)]],
    }),
    task('expert', 'Longer than average', {
      prompt: 'Make `long` the trips longer than the average trip, with only the `id` and `minutes` columns.',
      starter: TRIPS,
      hint: 'Inside `subset()`, `mean(minutes)` works too. Add `select = c(id, minutes)`.',
      solution: TRIPS + 'long <- subset(trips, minutes > mean(minutes), select = c(id, minutes))',
      tests: [['long is trips 2, 3, 5 and 8', sameFrame('long', 'trips[trips$minutes > mean(trips$minutes), c("id", "minutes")]')]],
    }),
  ],
  questions: [
    mc('After `df <- data.frame(x = c(3, 8, 6))`, what does `nrow(subset(df, x > 5))` give?', ['`1`', '`2`', '`3`', '`14`'], 1,
      'Two rows have x over 5.',
      { code: 'df <- data.frame(x = c(3, 8, 6))\nnrow(subset(df, x > 5))', output: '[1] 2' }),
    mc('Why can `subset()` be safer than `df[df$x > 6, ]` when `x` has gaps?', ['subset() drops rows where the condition is NA; brackets keep them as rows of NAs', 'subset() is faster', 'Brackets can\'t filter', 'There is no difference'], 0,
      'With brackets, `df[which(df$x > 6), ]` does the same.'),
    mc('After `df <- data.frame(x = c(5, NA, 9))`, what does `nrow(subset(df, x > 6))` give?', ['`1`', '`2`', '`0`', '`NA`'], 0,
      '`subset()` leaves out the row where the condition is NA.',
      { code: 'df <- data.frame(x = c(5, NA, 9))\nnrow(subset(df, x > 6))', output: '[1] 1' }),
    mc('After `df <- data.frame(x = c(5, NA, 9))`, what does `nrow(df[df$x > 6, , drop = FALSE])` give?', ['`1`', '`2`', '`0`', '`3`'], 1,
      'With brackets, the NA condition adds a row of NAs to the result.',
      { code: 'df <- data.frame(x = c(5, NA, 9))\nnrow(df[df$x > 6, , drop = FALSE])', output: '[1] 2' }),
    mc('Which keeps rows where `day` is `"Sat"` or `"Sun"`?', ['`subset(df, day == "Sat" & day == "Sun")`', '`subset(df, day %in% c("Sat", "Sun"))`', '`subset(df, day == c("Sat", "Sun"))`', '`df["Sat", "Sun"]`'], 1,
      '`%in%` checks against a list; a value can\'t be both at once, so `&` keeps nothing.'),
    mc('What does `select = c(id, km)` do in `subset()`?', ['Sorts by id and km', 'Keeps only those two columns', 'Filters on id and km', 'Removes those columns'], 1,
      '`select` picks the columns of the result.'),
    mc('After `df <- data.frame(g = c("a", "b", "a"), v = c(2, 5, 4))`, what does `mean(subset(df, g == "a")$v)` give?', ['`3`', '`3.67`', '`5`', '`11`'], 0,
      'The rows with g "a" have v 2 and 4, averaging 3.',
      { code: 'df <- data.frame(g = c("a", "b", "a"), v = c(2, 5, 4))\nmean(subset(df, g == "a")$v)', output: '[1] 3' }),
    mc('Which keeps the rows where `paid` (TRUE/FALSE) is FALSE?', ['`subset(df, paid)`', '`subset(df, !paid)`', '`subset(df, paid == "FALSE")`', '`df[-paid, ]`'], 1,
      '`!` turns the TRUE/FALSE column around.'),
    qShort('Which function filters the rows of a data frame using column names directly?', 'subset',
      '`subset(df, condition)`'),
  ],
})
