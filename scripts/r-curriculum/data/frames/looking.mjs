// Data frames: Looking at a data frame.
import { code, isTexts, makeTopic, mc, near, prints, qShort, snippet, task, uses } from '../_builders.mjs'
import { TRIPS } from '../datasets.mjs'

export default makeTopic({
  id: 'looking_at_data',
  title: 'Looking at a data frame',
  paragraphs: [
    'Real data comes as a table: one **row** per thing (a trip, an order, a student) and one **column** per fact about it. In R, a table is a **data frame**. Each column is a vector, so everything from the last quests works on it.',
    'This quest uses trips from Riverside Bikes. Each challenge starts with the code that makes the data frame:',
    code(...TRIPS.trim().split('\n')),
    'The first thing to do with any data is look at it. Type the name to see the whole table, or use these for a quick look:',
    '| Function | Shows |\n| --- | --- |\n| `head(trips)` | the first 6 rows (`head(trips, 3)` for 3) |\n| `tail(trips)` | the last 6 rows |\n| `nrow(trips)`, `ncol(trips)` | the number of rows and columns |\n| `dim(trips)` | both: rows, then columns |\n| `names(trips)` | the column names |\n| `str(trips)` | every column with its type and first values |',
    '`str()` is the most useful of all: it shows at a glance whether each column has the type you expect. `num` is numeric, `int` integer, `chr` text and `logi` TRUE/FALSE. A column of numbers that comes up as `chr` needs fixing before you can calculate with it.',
  ],
  sandboxCode: TRIPS + 'head(trips, 3)\nnrow(trips)\nnames(trips)\nstr(trips)',
  sandboxSnippets: [
    snippet('The whole table', TRIPS + 'trips'),
    snippet('Size', TRIPS + 'dim(trips)\nncol(trips)'),
  ],
  readMore: { label: 'R documentation: data.frame()', url: 'https://stat.ethz.ch/R-manual/R-devel/library/base/html/data.frame.html', source: 'R documentation' },
  challenges: [
    task('easy', 'How many trips', {
      prompt: 'Make `n_trips` the number of rows in `trips`.',
      starter: TRIPS,
      hint: '`n_trips <- nrow(trips)`',
      solution: TRIPS + 'n_trips <- nrow(trips)',
      tests: [['n_trips is 8', near('n_trips', 8)], ['Uses nrow()', uses('nrow(')]],
    }),
    task('easy', 'The column names', {
      prompt: 'Make `columns` the column names of `trips`.',
      starter: TRIPS,
      hint: '`columns <- names(trips)`',
      solution: TRIPS + 'columns <- names(trips)',
      tests: [['columns is id, station, minutes, km, member', isTexts('columns', 'id', 'station', 'minutes', 'km', 'member')]],
    }),
    task('easy', 'The first three', {
      prompt: 'Make `first3` the first 3 rows of `trips`.',
      starter: TRIPS,
      hint: '`first3 <- head(trips, 3)`',
      solution: TRIPS + 'first3 <- head(trips, 3)',
      tests: [['first3 is the first 3 trips', 'is.data.frame(first3) && identical(first3$id, 1:3) && ncol(first3) == 5']],
    }),
    task('medium', 'Rows and columns', {
      prompt: 'Make `size` the number of rows and columns of `trips`, in one call.',
      starter: TRIPS,
      hint: '`size <- dim(trips)`',
      solution: TRIPS + 'size <- dim(trips)',
      tests: [['size is 8, 5', near('size', 'c(8, 5)')], ['Uses dim()', uses('dim(')]],
    }),
    task('medium', 'The last two', {
      prompt: 'Make `last2` the last 2 rows of `trips`.',
      starter: TRIPS,
      hint: '`last2 <- tail(trips, 2)`',
      solution: TRIPS + 'last2 <- tail(trips, 2)',
      tests: [['last2 is trips 7 and 8', 'is.data.frame(last2) && identical(last2$id, 7:8)']],
    }),
    task('medium', 'Look at the structure', {
      prompt: 'Show the structure of `trips`, with each column\'s type.',
      starter: TRIPS,
      hint: '`str(trips)`',
      solution: TRIPS + 'str(trips)',
      tests: [
        ['Shows the structure', 'grepl("8 obs. of  5 variables", ._cq_stdout, fixed = TRUE)'],
        ['Uses str()', uses('str(')],
      ],
    }),
    task('hard', 'What type is km', {
      prompt: 'Make `km_class` the class of the `km` column. (Write `trips$km` to get the column; the next stages say more.)',
      starter: TRIPS,
      hint: '`km_class <- class(trips$km)`',
      solution: TRIPS + 'km_class <- class(trips$km)',
      tests: [['km_class is "numeric"', 'identical(km_class, "numeric")']],
    }),
    task('expert', 'A one-line summary', {
      prompt: 'Show `trips has 8 rows and 5 columns`, letting R work out both numbers.',
      starter: TRIPS,
      hint: '`cat("trips has", nrow(trips), "rows and", ncol(trips), "columns\\n")`',
      solution: TRIPS + 'cat("trips has", nrow(trips), "rows and", ncol(trips), "columns\\n")',
      tests: [['Shows the line', prints('trips has 8 rows and 5 columns')], ['Works out the numbers', uses('nrow(') + ' && ' + uses('ncol(')]],
    }),
  ],
  questions: [
    mc('In a data frame, what is one row?', ['One fact, such as all the prices', 'One thing, such as one trip', 'The column names', 'The whole table'], 1,
      'Rows are the things; columns are the facts about them.'),
    mc('What does `nrow(data.frame(x = 1:4, y = 5:8))` give?', ['`2`', '`4`', '`8`', '`1`'], 1,
      'There are four values in each column, so four rows.',
      { code: 'nrow(data.frame(x = 1:4, y = 5:8))', output: '[1] 4' }),
    mc('What does `dim(data.frame(x = 1:4, y = 5:8))` give?', ['`[1] 4 2`', '`[1] 2 4`', '`[1] 8`', '`[1] 4`'], 0,
      'Rows first, then columns.',
      { code: 'dim(data.frame(x = 1:4, y = 5:8))', output: '[1] 4 2' }),
    mc('What does `names(data.frame(a = 1, b = 2))` give?', ['`[1] 1 2`', '`[1] "a" "b"`', '`[1] "data.frame"`', '`NULL`'], 1,
      'The names of a data frame are its column names.',
      { code: 'names(data.frame(a = 1, b = 2))', output: '[1] "a" "b"' }),
    mc('How many rows does `head(trips)` show when trips has 8 rows?', ['3', '8', '6', '1'], 2,
      '`head()` shows 6 rows unless you give a number.'),
    mc('In `str()`, what does `chr` mean for a column?', ['A number', 'Text', 'TRUE/FALSE', 'A date'], 1,
      '`chr` is character: text.'),
    mc('What does `class(data.frame(x = 1))` give?', ['`"list"`', '`"table"`', '`"data.frame"`', '`"numeric"`'], 2,
      'A data frame is its own type.',
      { code: 'class(data.frame(x = 1))', output: '[1] "data.frame"' }),
    mc('A column of prices shows as `chr` in `str()`. What does that mean?', ['It is fine', 'The prices are stored as text and must be converted before maths', 'The column is empty', 'The prices are rounded'], 1,
      'Text can\'t be added up; `as.numeric()` fixes it.'),
    qShort('Which function shows each column of a data frame with its type?', 'str',
      '`str()` shows the structure.'),
  ],
})
