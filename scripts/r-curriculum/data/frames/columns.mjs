// Data frames: Columns with $.
import { code, makeTopic, mc, near, qShort, same, snippet, task, uses } from '../_builders.mjs'
import { TRIPS } from '../datasets.mjs'

export default makeTopic({
  id: 'columns',
  title: 'Columns with $',
  paragraphs: [
    'A data frame is a set of named columns, and `$` gets one out by name. What you get is an ordinary vector, so everything from the Vectors quest works on it:',
    code('trips$minutes                # 12 47 30 8 55 15 22 35', 'mean(trips$minutes)          # 28', 'sum(trips$member)            # 5 members', 'trips$station[trips$minutes > 40]'),
    '`trips[["minutes"]]` does the same as `trips$minutes`. It is handy when the column name is in a variable: `col <- "km"; trips[[col]]`.',
    '**Making a new column** works the same way: assign to a name that doesn\'t exist yet. Because columns are vectors, a calculation on one column gives a value for every row:',
    code('trips$cost <- 1 + 0.15 * trips$minutes', 'trips$speed <- round(trips$km / (trips$minutes / 60), 1)', 'trips$long <- trips$minutes > 30'),
    'Assigning to an existing column replaces it, for example to fix its type: `trips$station <- factor(trips$station)`. To remove a column, assign `NULL` to it: `trips$long <- NULL`.',
    '`ifelse()` is great for new columns: `trips$fare <- ifelse(trips$member, 0, trips$cost)` makes the ride free for members.',
  ],
  sandboxCode: TRIPS + 'trips$minutes\nmean(trips$minutes)\ntrips$cost <- 1 + 0.15 * trips$minutes\nhead(trips, 3)',
  sandboxSnippets: [
    snippet('A condition on a column', TRIPS + 'trips$station[trips$minutes > 40]\nsum(trips$member)'),
    snippet('Remove a column', TRIPS + 'trips$km <- NULL\nnames(trips)'),
  ],
  readMore: { label: 'R documentation: Extract ($ and [[ ]])', url: 'https://stat.ethz.ch/R-manual/R-devel/library/base/html/Extract.data.frame.html', source: 'R documentation' },
  challenges: [
    task('easy', 'The average ride', {
      prompt: 'Make `avg_minutes` the average of the `minutes` column.',
      starter: TRIPS,
      hint: '`avg_minutes <- mean(trips$minutes)`',
      solution: TRIPS + 'avg_minutes <- mean(trips$minutes)',
      tests: [['avg_minutes is 28', near('avg_minutes', 28)], ['Uses $', uses('trips$minutes')]],
    }),
    task('easy', 'Total distance', {
      prompt: 'Make `total_km` the total distance of all trips.',
      starter: TRIPS,
      hint: '`total_km <- sum(trips$km)`',
      solution: TRIPS + 'total_km <- sum(trips$km)',
      tests: [['total_km is 41.1', near('total_km', 41.1)]],
    }),
    task('easy', 'How many members', {
      prompt: 'Make `n_members` the number of trips made by members (the `member` column is TRUE/FALSE).',
      starter: TRIPS,
      hint: 'TRUE counts as 1: `n_members <- sum(trips$member)`.',
      solution: TRIPS + 'n_members <- sum(trips$member)',
      tests: [['n_members is 5', near('n_members', 5)]],
    }),
    task('medium', 'A cost column', {
      prompt: 'Add a column `cost` to `trips`: 1 to unlock plus 0.15 per minute.',
      starter: TRIPS,
      hint: '`trips$cost <- 1 + 0.15 * trips$minutes`',
      solution: TRIPS + 'trips$cost <- 1 + 0.15 * trips$minutes',
      tests: [['cost is right for every trip', 'isTRUE(all.equal(trips$cost, 1 + 0.15 * c(12, 47, 30, 8, 55, 15, 22, 35)))']],
    }),
    task('medium', 'A speed column', {
      prompt: 'Add a column `speed`: the speed in km per hour, rounded to 1 decimal place.',
      starter: TRIPS,
      hint: '`trips$speed <- round(trips$km / (trips$minutes / 60), 1)`',
      solution: TRIPS + 'trips$speed <- round(trips$km / (trips$minutes / 60), 1)',
      tests: [['speed is right for every trip', 'isTRUE(all.equal(trips$speed, round(c(2.4, 9.4, 5.1, 1.2, 10.3, 2.9, 3.8, 6.0) / (c(12, 47, 30, 8, 55, 15, 22, 35) / 60), 1)))']],
    }),
    task('medium', 'Long rides', {
      prompt: 'Add a column `long`: TRUE for trips over 30 minutes.',
      starter: TRIPS,
      hint: '`trips$long <- trips$minutes > 30`',
      solution: TRIPS + 'trips$long <- trips$minutes > 30',
      tests: [['long is TRUE for trips 2, 5 and 8', same('trips$long', 'c(FALSE, TRUE, FALSE, FALSE, TRUE, FALSE, FALSE, TRUE)')]],
    }),
    task('hard', 'Members and visitors', {
      prompt: 'Add a column `rider`: `"member"` for members and `"visitor"` for everyone else.',
      starter: TRIPS,
      hint: '`trips$rider <- ifelse(trips$member, "member", "visitor")`',
      solution: TRIPS + 'trips$rider <- ifelse(trips$member, "member", "visitor")',
      tests: [['rider is right for every trip', 'identical(trips$rider, c("member", "visitor", "member", "member", "visitor", "member", "visitor", "member"))']],
    }),
    task('expert', 'Tidy up the columns', {
      prompt: 'Make `station` a factor with the levels `Park`, `River`, `Market`, and remove the `id` column.',
      starter: TRIPS,
      hint: '`trips$station <- factor(trips$station, levels = c("Park", "River", "Market"))` and `trips$id <- NULL`.',
      solution: TRIPS + 'trips$station <- factor(trips$station, levels = c("Park", "River", "Market"))\ntrips$id <- NULL',
      tests: [
        ['station is a factor with levels Park, River, Market', 'is.factor(trips$station) && identical(levels(trips$station), c("Park", "River", "Market"))'],
        ['id is gone', 'identical(names(trips), c("station", "minutes", "km", "member"))'],
      ],
    }),
  ],
  questions: [
    mc('After `df <- data.frame(x = c(2, 4), y = c(10, 20))`, what does `df$y` give?', ['`[1] 10 20`', '`[1] 2 4`', 'The whole table', '`"y"`'], 0,
      '`$` gives the column as a vector.',
      { code: 'df <- data.frame(x = c(2, 4), y = c(10, 20))\ndf$y', output: '[1] 10 20' }),
    mc('After `df <- data.frame(x = c(2, 4))`, what does `mean(df$x)` give?', ['`2`', '`3`', '`6`', 'An error'], 1,
      'A column is a vector, so `mean()` works on it.',
      { code: 'df <- data.frame(x = c(2, 4))\nmean(df$x)', output: '[1] 3' }),
    mc('After `df <- data.frame(x = c(2, 4))` and `df$z <- df$x * 10`, what is `df$z`?', ['`[1] 20 40`', '`[1] 60`', 'An error: z doesn\'t exist', '`[1] 2 4`'], 0,
      'Assigning to a new name adds a column, worked out for every row.',
      { code: 'df <- data.frame(x = c(2, 4))\ndf$z <- df$x * 10\ndf$z', output: '[1] 20 40' }),
    mc('After `df <- data.frame(x = 1, y = 2)` and `df$y <- NULL`, what does `names(df)` give?', ['`[1] "x" "y"`', '`[1] "x"`', '`NULL`', 'An error'], 1,
      'Assigning NULL removes a column.',
      { code: 'df <- data.frame(x = 1, y = 2)\ndf$y <- NULL\nnames(df)', output: '[1] "x"' }),
    mc('After `df <- data.frame(km = c(5, 12))` and `col <- "km"`, what does `df[[col]]` give?', ['`[1] 5 12`', '`NULL`', '`"km"`', 'An error'], 0,
      '`[[ ]]` takes the column name from a variable.',
      { code: 'df <- data.frame(km = c(5, 12))\ncol <- "km"\ndf[[col]]', output: '[1]  5 12' }),
    mc('What does `df$colour` give when there is no column `colour`?', ['An error', '`NULL`', '`NA`', '`""`'], 1,
      'A missing column gives NULL, without an error, so check the spelling of column names.',
      { code: 'df <- data.frame(x = 1)\ndf$colour', output: 'NULL' }),
    mc('After `df <- data.frame(m = c(10, 40))`, what does `df$m[df$m > 20]` give?', ['`[1] 40`', '`[1] FALSE TRUE`', '`[1] 10`', 'The second row'], 0,
      'The column is a vector, picked with a condition as usual.',
      { code: 'df <- data.frame(m = c(10, 40))\ndf$m[df$m > 20]', output: '[1] 40' }),
    mc('After `df <- data.frame(a = c(TRUE, FALSE, TRUE))`, what does `sum(df$a)` give?', ['`3`', '`2`', '`TRUE`', 'An error'], 1,
      'TRUE counts as 1.',
      { code: 'df <- data.frame(a = c(TRUE, FALSE, TRUE))\nsum(df$a)', output: '[1] 2' }),
    qShort('Which symbol gets a column out of a data frame by name, as in `trips__minutes`?', '$',
      '`trips$minutes` is the minutes column.'),
  ],
})
