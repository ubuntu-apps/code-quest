  paragraphs: [
    'An **array** is a list of values in one variable, written in square brackets with commas between them. It keeps its values in order.',
    '```\nconst fruits = ["apple", "banana", "cherry"]\nconst scores = [72, 88, 95]\nconsole.log(fruits)\nconsole.log(scores.length)\n```',
    'Like the characters of a string, each item has an **index** starting at 0: `fruits[0]` is `"apple"`, `fruits[2]` is `"cherry"`. `length` is how many items there are, so the last one is `fruits[fruits.length - 1]`, or `fruits.at(-1)`. An index past the end gives `undefined`.',
    'An array can hold any values, even a mix: `["Sam", 12, true]`. Usually though, one array holds one kind of thing: all names, or all scores. An empty array is `[]`.',
    '`console.log` shows an array with brackets and quotes around the text, like `[ \'apple\', \'banana\' ]`, so you can see exactly what is in it.',
    'An index can be any expression that gives a number: `scores[i]`, `scores[scores.length - 1]`, `fruits[Math.floor(fruits.length / 2)]`. Together with a `for` loop over the indexes, that lets you visit every item:',
    '```\nconst scores = [72, 88, 95]\nfor (let i = 0; i < scores.length; i++) {\n  console.log(`Score ${i + 1}: ${scores[i]}`)\n}\n```',
  ],
