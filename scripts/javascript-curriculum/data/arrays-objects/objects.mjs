// Arrays and objects: Objects. Lesson, Try-it snippets, challenges and quiz.
import { MDN, is, makeTopic, matches, mc, prints, qShort, same, snippet, task, uses } from '../_builders.mjs'

export default makeTopic({
  id: 'objects',
  title: 'Objects: named values',
  paragraphs: [
    'An array keeps values in order by number. An **object** keeps values by **name**. It is written in curly braces, as `key: value` pairs separated by commas:',
    '```\nconst pet = { name: "Rex", species: "dog", age: 4 }\nconsole.log(pet.name, pet.age)\nconsole.log(pet)\n```',
    'Each key is a **property**. Read one with a dot, `pet.name`, or with square brackets and the key as text, `pet["name"]`. Brackets are needed when the key is in a variable: `const field = "age"; pet[field]`. A property that isn\'t there gives `undefined`.',
    'Properties can be changed, added and removed, even on a `const` object (as with arrays, `const` only fixes which object it is):',
    '```\nconst pet = { name: "Rex", age: 4 }\npet.age = 5\npet.owner = "Sam"\ndelete pet.name\nconsole.log(pet)\n```',
    '`"key" in object` checks whether a property exists. `Object.keys(obj)` gives an array of the keys, `Object.values(obj)` the values, and `Object.entries(obj)` `[key, value]` pairs, which a `for…of` can loop over.',
    '```\nconst stock = { apples: 12, pears: 0, plums: 7 }\nfor (const [fruit, count] of Object.entries(stock)) {\n  console.log(`${fruit}: ${count}`)\n}\n```',
    'When a variable has the same name as the key, there is a shortcut: `{ name, age }` means `{ name: name, age: age }`.',
  ],
  sandboxCode: 'const pet = { name: "Rex", species: "dog", age: 4 }\nconsole.log(pet.name, pet["species"])\npet.age = 5\npet.owner = "Sam"\nconsole.log(pet)',
  sandboxSnippets: [
    snippet('Read', 'const book = { title: "Dune", year: 1965 }\nconst field = "year"\nconsole.log(book.title, book[field], book.author)'),
    snippet('Change', 'const user = { name: "Ana", score: 10 }\nuser.score += 5\nuser.level = 2\nconsole.log(user)'),
    snippet('Keys and values', 'const stock = { apples: 12, pears: 0, plums: 7 }\nconsole.log(Object.keys(stock), Object.values(stock))\nconsole.log("pears" in stock, "kiwis" in stock)'),
    snippet('Loop', 'const stock = { apples: 12, pears: 0, plums: 7 }\nfor (const [fruit, count] of Object.entries(stock)) {\n  console.log(`${fruit}: ${count}`)\n}'),
  ],
  readMore: MDN('Web/JavaScript/Guide/Working_with_objects', 'MDN: working with objects'),
  challenges: [
    task('easy', 'Make an object', {
      prompt: 'Make a `const` called `book` with a `title` of `"Dune"` and a `year` of `1965`.',
      hint: '`const book = { title: "Dune", year: 1965 }`.',
      solution: 'const book = { title: "Dune", year: 1965 }',
      tests: [['book is right', 'book.title === "Dune" && book.year === 1965'], ['Has just those two', 'Object.keys(book).length === 2']],
      typedOk: true,
    }),
    task('easy', 'Read a property', {
      prompt: 'Set `city` to the `city` property of `user`.',
      starter: 'const user = { name: "Kim", city: "Oslo", age: 31 }\n',
      hint: '`user.city`.',
      solution: 'const user = { name: "Kim", city: "Oslo", age: 31 }\nconst city = user.city',
      tests: [['city is Oslo', is('city', 'Oslo')]],
    }),
    task('easy', 'Change a property', {
      prompt: 'It\'s Kim\'s birthday: add 1 to `user.age`.',
      starter: 'const user = { name: "Kim", age: 31 }\n',
      hint: '`user.age += 1` (or `user.age++`).',
      solution: 'const user = { name: "Kim", age: 31 }\nuser.age += 1',
      tests: [['age is 32', 'user.age === 32'], ['Changes the property', matches('user\\.age\\s*(\\+=|\\+\\+|=\\s*user\\.age)')]],
    }),
    task('medium', 'Add and remove', {
      prompt: 'Add an `email` of `"kim@mail.com"` to `user`, and remove its `password`.',
      starter: 'const user = { name: "Kim", password: "1234" }\n',
      hint: '`user.email = "kim@mail.com"`, then `delete user.password`.',
      solution: 'const user = { name: "Kim", password: "1234" }\nuser.email = "kim@mail.com"\ndelete user.password',
      tests: [['email is set', 'user.email === "kim@mail.com"'], ['password is gone', '!("password" in user)']],
      typedOk: true,
    }),
    task('medium', 'A key in a variable', {
      prompt: 'Set `value` to the property of `settings` whose name is in `key`.',
      starter: 'const settings = { volume: 7, theme: "dark", lang: "en" }\nconst key = "theme"\n',
      hint: 'Use brackets: `settings[key]`. (`settings.key` looks for a property called "key".)',
      solution: 'const settings = { volume: 7, theme: "dark", lang: "en" }\nconst key = "theme"\nconst value = settings[key]',
      tests: [['value is dark', is('value', 'dark')], ['Uses brackets', uses('settings[key]')]],
      alt: 'const settings = { volume: 7, theme: "dark", lang: "en" }\nconst key = "lang"',
    }),
    task('medium', 'Does it have it?', {
      prompt: 'Set `hasPhone` to whether `contact` has a `phone` property.',
      starter: 'const contact = { name: "Lou", email: "lou@mail.com" }\n',
      hint: '`"phone" in contact`.',
      solution: 'const contact = { name: "Lou", email: "lou@mail.com" }\nconst hasPhone = "phone" in contact',
      tests: [['hasPhone is false', is('hasPhone', false)], ['Uses in', matches('"phone"\\s+in\\s+contact')]],
      alt: 'const contact = { name: "Lou", phone: "555-0100" }',
    }),
    task('hard', 'Total stock', {
      prompt: 'Set `total` to the sum of all the numbers in `stock`, with `Object.values`.',
      starter: 'const stock = { apples: 12, pears: 3, plums: 7 }\n',
      hint: '`for (const n of Object.values(stock)) { total += n }`.',
      solution: 'const stock = { apples: 12, pears: 3, plums: 7 }\nlet total = 0\nfor (const n of Object.values(stock)) {\n  total += n\n}',
      tests: [['total is 22', is('total', 22)], ['Uses Object.values', uses('Object.values(')]],
    }),
    task('hard', 'Show each setting', {
      prompt: 'Show each property of `settings` as `volume = 7` and so on, with `Object.entries`.',
      starter: 'const settings = { volume: 7, theme: "dark" }\n',
      hint: '`for (const [key, value] of Object.entries(settings))`.',
      solution: 'const settings = { volume: 7, theme: "dark" }\nfor (const [key, value] of Object.entries(settings)) {\n  console.log(`${key} = ${value}`)\n}',
      tests: [['Shows each setting', prints('volume = 7', 'theme = dark')], ['Uses Object.entries', uses('Object.entries(')]],
    }),
    task('expert', 'Build from variables', {
      prompt: 'Set `player` to an object with `name`, `level` and `alive` from the variables, using the shortcut `{ name, level, alive }`.',
      starter: 'const name = "Ziggy"\nconst level = 4\nconst alive = true\n',
      hint: 'When the variable has the key\'s name, `{ name }` is enough.',
      solution: 'const name = "Ziggy"\nconst level = 4\nconst alive = true\nconst player = { name, level, alive }',
      tests: [['player is right', same('player', '{ name: "Ziggy", level: 4, alive: true }')], ['Uses the shortcut', matches('\\{\\s*name\\s*,\\s*level\\s*,\\s*alive\\s*\\}')]],
    }),
    task('expert', 'The most stock', {
      prompt: 'Set `most` to the name of the fruit with the highest count in `stock`.',
      starter: 'const stock = { apples: 12, pears: 30, plums: 7 }\n',
      hint: 'Loop over `Object.entries(stock)`, keeping the best count and its name.',
      solution: 'const stock = { apples: 12, pears: 30, plums: 7 }\nlet most = null\nlet best = -Infinity\nfor (const [fruit, count] of Object.entries(stock)) {\n  if (count > best) {\n    best = count\n    most = fruit\n  }\n}',
      tests: [['most is pears', is('most', 'pears')]],
      alt: 'const stock = { apples: 12, pears: 3, plums: 70 }',
    }),
  ],
  questions: [
    mc('After `const p = { x: 3, y: 4 }`, what is `p.y`?', ['4', '3', '"y"', 'undefined'], 0, 'p.y reads the y property.', { code: 'const p = { x: 3, y: 4 }\nconsole.log(p.y)', output: '4' }),
    mc('After `const p = { x: 3 }`, what is `p.z`?', ['undefined', '0', 'null', 'An error'], 0, 'A missing property gives undefined.', { code: 'const p = { x: 3 }\nconsole.log(p.z)', output: 'undefined' }),
    mc('With `const k = "x"`, which reads the `x` property of `p`?', ['`p[k]`', '`p.k`', '`p["k"]`', '`p(k)`'], 0, 'Brackets use the variable\'s value as the key.'),
    mc('Can you add a property to a `const` object?', ['Yes', 'No', 'Only with let', 'Only numbers'], 0, 'const fixes which object it is, not what is in it.'),
    mc('What does `Object.keys({ a: 1, b: 2 })` give?', ['["a", "b"]', '[1, 2]', '2', '"ab"'], 0, 'keys gives the property names.', { code: 'console.log(Object.keys({ a: 1, b: 2 }))', output: "[ 'a', 'b' ]" }),
    mc('What does `"age" in { name: "Al" }` give?', ['false', 'true', 'undefined', 'An error'], 0, 'There is no age property.', { code: 'console.log("age" in { name: "Al" })', output: 'false' }),
    mc('With `const n = "Bo"`, what is `{ n }`?', ['{ n: "Bo" }', '{ "Bo": "Bo" }', '{ n: n }', 'An error'], 0, 'The shortcut uses the variable name as the key.', { code: 'const n = "Bo"\nconsole.log({ n })', output: "{ n: 'Bo' }" }),
    mc('After `const o = { a: 1 }` and `delete o.a`, what is `o`?', ['{}', '{ a: undefined }', '{ a: 1 }', 'undefined'], 0, 'delete removes the property.', { code: 'const o = { a: 1 }\ndelete o.a\nconsole.log(o)', output: '{}' }),
    qShort('What is a named value in an object called?', 'property', 'Each key: value pair is a property.'),
  ],
})
