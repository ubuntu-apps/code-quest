// First steps: Types and conversion. Lesson, Try-it snippets, challenges and quiz.
import { MDN, is, makeTopic, matches, mc, prints, qShort, snippet, task, uses } from '../_builders.mjs'

export default makeTopic({
  id: 'types',
  title: 'Types and conversion',
  paragraphs: [
    'Every value has a **type**. So far you have met `number` (`7`, `2.5`), `string` (`"hi"`) and, in the next stage, `boolean` (`true` or `false`). `undefined` means "no value yet". `typeof` tells you a value\'s type, as text:',
    '```\nconsole.log(typeof 42, typeof "42", typeof true, typeof undefined)\n```',
    '`42` and `"42"` look alike but are different: one is a number, the other is text. Text that comes from outside a program, such as what someone types into a form, is always a string, even when it is digits.',
    'That matters with `+`. If either side is a string, `+` joins instead of adding: `"5" + 3` is `"53"`. The other maths operators only work on numbers, so they turn the text into a number first: `"5" * 3` is `15` and `"5" - 3` is `2`. Relying on that is confusing, so convert on purpose.',
    '```\nconsole.log("5" + 3, "5" * 3, "5" - 3)\nconsole.log(Number("5") + 3)\n```',
    '`Number(text)` turns text into a number. `parseInt(text)` and `parseFloat(text)` read a number from the start of text and stop at the first character that doesn\'t fit, so `parseInt("12px")` is `12`; `parseInt` also drops any decimals. `String(value)` turns a value into text.',
    'When text isn\'t a number at all, the result is `NaN`, "Not a Number": `Number("hello")` is `NaN`. Any maths with `NaN` gives `NaN` again, so check with `Number.isNaN(value)`. Oddly, `typeof NaN` is `"number"`.',
    '```\nconsole.log(Number("hello"), parseInt("12px"), parseFloat("3.75kg"))\nconsole.log(Number.isNaN(Number("abc")))\n```',
  ],
  sandboxCode: 'console.log(typeof 42, typeof "42", typeof true)\nconsole.log("5" + 3, "5" * 3)\nconsole.log(Number("5") + 3)\nconsole.log(Number("hello"), parseInt("12px"))',
  sandboxSnippets: [
    snippet('typeof', 'console.log(typeof 3.5)\nconsole.log(typeof "text")\nconsole.log(typeof false)\nconsole.log(typeof undefined)'),
    snippet('Text that looks like a number', 'const a = "10"\nconst b = "5"\nconsole.log(a + b)\nconsole.log(Number(a) + Number(b))'),
    snippet('Reading numbers', 'console.log(parseInt("42 apples"))\nconsole.log(parseFloat("1.5 litres"))\nconsole.log(parseInt("7.9"))'),
    snippet('NaN', 'const n = Number("ten")\nconsole.log(n, n + 1, Number.isNaN(n), typeof n)'),
  ],
  readMore: MDN('Web/JavaScript/Guide/Data_structures', 'MDN: JavaScript data types'),
  challenges: [
    task('easy', 'What type?', {
      prompt: 'Set `kind` to the type of `value`, using `typeof`.',
      starter: 'const value = "2026"\n',
      hint: '`typeof value` gives the type as text.',
      solution: 'const value = "2026"\nconst kind = typeof value',
      tests: [['kind is "string"', is('kind', 'string')], ['Uses typeof', uses('typeof')]],
      alt: 'const value = 2026',
    }),
    task('easy', 'Text to number', {
      prompt: 'Set `count` to the number in the text `typed`.',
      starter: 'const typed = "42"\n',
      hint: '`Number(typed)`.',
      solution: 'const typed = "42"\nconst count = Number(typed)',
      tests: [['count is the number 42', is('count', 42)]],
    }),
    task('easy', 'Number to text', {
      prompt: 'Set `text` to `year` as a string.',
      starter: 'const year = 2026\n',
      hint: '`String(year)`.',
      solution: 'const year = 2026\nconst text = String(year)',
      tests: [['text is "2026"', is('text', '2026')]],
    }),
    task('medium', 'Add, don\'t join', {
      prompt: 'This shows `105` instead of `15`. Convert both values to numbers so it adds them.',
      starter: 'const a = "10"\nconst b = "5"\nconsole.log(a + b)',
      hint: '`Number(a) + Number(b)`.',
      solution: 'const a = "10"\nconst b = "5"\nconsole.log(Number(a) + Number(b))',
      tests: [['Shows 15', prints('15')], ['Converts them', uses('Number(')]],
    }),
    task('medium', 'Read the width', {
      prompt: 'Set `width` to the number at the start of `css`: `120` from `"120px"`.',
      starter: 'const css = "120px"\n',
      hint: '`Number("120px")` is NaN, but `parseInt` stops at the `p`.',
      solution: 'const css = "120px"\nconst width = parseInt(css)',
      tests: [['width is 120', is('width', 120)], ['Uses parseInt', uses('parseInt(')]],
    }),
    task('medium', 'A decimal price', {
      prompt: 'Set `price` to the decimal number in `label`: `4.75` from `"4.75 EUR"`.',
      starter: 'const label = "4.75 EUR"\n',
      hint: '`parseFloat` keeps the decimals; `parseInt` would drop them.',
      solution: 'const label = "4.75 EUR"\nconst price = parseFloat(label)',
      tests: [['price is 4.75', is('price', 4.75)], ['Uses parseFloat', uses('parseFloat(')]],
    }),
    task('hard', 'Is it a number?', {
      prompt: 'Set `bad` to whether `Number(answer)` is NaN.',
      starter: 'const answer = "twelve"\n',
      hint: '`Number.isNaN(Number(answer))`.',
      solution: 'const answer = "twelve"\nconst bad = Number.isNaN(Number(answer))',
      tests: [['bad is true', is('bad', true)], ['Uses Number.isNaN', uses('Number.isNaN(')]],
      alt: 'const answer = "12"',
    }),
    task('hard', 'Total of a form', {
      prompt: 'A form gives quantities as text. Set `total` to the three added up as numbers.',
      starter: 'const small = "3"\nconst medium = "4"\nconst large = "2"\n',
      hint: 'Convert each one: `Number(small) + Number(medium) + Number(large)`.',
      solution: 'const small = "3"\nconst medium = "4"\nconst large = "2"\nconst total = Number(small) + Number(medium) + Number(large)',
      tests: [['total is the number 9', is('total', 9)]],
      alt: 'const small = "10"\nconst medium = "1"\nconst large = "7"',
    }),
    task('expert', 'Digits in a number', {
      prompt: 'Set `digits` to how many digits `n` has, by turning it into text and taking its length.',
      starter: 'const n = 123456\n',
      hint: '`String(n).length`.',
      solution: 'const n = 123456\nconst digits = String(n).length',
      tests: [['digits is 6', is('digits', 6)], ['Uses the length', uses('.length')]],
      alt: 'const n = 98',
    }),
    task('expert', 'Fix the average', {
      prompt: 'The scores come as text, so the average is wrong (`4528.5`). Fix it so `average` is `48.5`.',
      starter: 'const s1 = "45"\nconst s2 = "52"\nconst average = (s1 + s2) / 2',
      hint: '`+` joins text. Convert before adding: `(Number(s1) + Number(s2)) / 2`.',
      solution: 'const s1 = "45"\nconst s2 = "52"\nconst average = (Number(s1) + Number(s2)) / 2',
      tests: [['average is 48.5', is('average', 48.5)]],
    }),
  ],
  questions: [
    mc('What does `"5" + 3` give?', ['"53"', '8', '"8"', 'An error'], 0,
      'With a string on one side, + joins.', { code: 'console.log("5" + 3)', output: '53' }),
    mc('What does `"5" * 3` give?', ['15', '"53"', '"555"', 'NaN'], 0,
      '* only works on numbers, so the text becomes 5 first.', { code: 'console.log("5" * 3)', output: '15' }),
    mc('What does `typeof "42"` give?', ['"string"', '"number"', '"text"', '42'], 0,
      'It\'s in quotes, so it\'s a string.', { code: 'console.log(typeof "42")', output: 'string' }),
    mc('What does `Number("hello")` give?', ['NaN', '0', '"hello"', 'An error'], 0,
      'Text that isn\'t a number converts to NaN, "Not a Number".', { code: 'console.log(Number("hello"))', output: 'NaN' }),
    mc('What does `parseInt("12px")` give?', ['12', 'NaN', '"12"', '12px'], 0,
      'parseInt reads digits from the start and stops at the first letter.', { code: 'console.log(parseInt("12px"))', output: '12' }),
    mc('What does `parseInt("7.9")` give?', ['7', '8', '7.9', 'NaN'], 0,
      'parseInt keeps only the whole part; use parseFloat for decimals.', { code: 'console.log(parseInt("7.9"))', output: '7' }),
    mc('What does `typeof NaN` give?', ['"number"', '"NaN"', '"undefined"', '"string"'], 0,
      'Strange but true: NaN is a special number value.', { code: 'console.log(typeof NaN)', output: 'number' }),
    mc('What does `NaN + 1` give?', ['NaN', '1', '0', 'An error'], 0,
      'Any maths with NaN gives NaN.', { code: 'console.log(NaN + 1)', output: 'NaN' }),
    qShort('What does `typeof true` give? (just the word)', 'boolean',
      'true and false are booleans.'),
  ],
})
