// First steps: String methods. Lesson, Try-it snippets, challenges and quiz.
import { MDN, is, makeTopic, matches, mc, prints, qShort, snippet, task, uses } from '../_builders.mjs'

export default makeTopic({
  id: 'string_methods',
  title: 'String methods',
  paragraphs: [
    'Strings come with **methods**: things a string can do, written after a dot with brackets. Each gives back a **new** string (or another value) and leaves the original as it was.',
    '```\nconst name = "  ada Lovelace  "\nconsole.log(name.trim())\nconsole.log(name.toUpperCase())\nconsole.log(name.toLowerCase())\n```',
    '`trim()` removes spaces from both ends. `toUpperCase()` and `toLowerCase()` change the letters. Methods can be chained, one after another: `name.trim().toUpperCase()`.',
    '`includes("x")` tells you whether some text appears (`true` or `false`), and `startsWith` and `endsWith` check the two ends. `indexOf("x")` gives where it first appears, or `-1` if it doesn\'t.',
    '`slice(start, end)` cuts out a part: from index `start` up to, but not including, `end`. Leave out `end` to go to the end, and use a negative number to count from the end: `slice(-4)` is the last 4 characters.',
    '```\nconst word = "JavaScript"\nconsole.log(word.slice(0, 4), word.slice(4), word.slice(-6))\nconsole.log(word.includes("Script"), word.indexOf("S"))\n```',
    '`replace(a, b)` swaps the first `a` for `b`, and `replaceAll` swaps every one. `repeat(n)` repeats a string, and `padStart(length, fill)` adds fill at the start until the string is that long, which is handy for lining up numbers: `"7".padStart(3, "0")` is `"007"`.',
    'Because strings never change, a method on its own does nothing you can see: `name.trim()` gives a trimmed copy, so store it (`const clean = name.trim()`) or show it.',
  ],
  sandboxCode: 'const name = "  ada Lovelace  "\nconsole.log(name.trim().toUpperCase())\nconst word = "JavaScript"\nconsole.log(word.slice(0, 4), word.slice(-6))\nconsole.log(word.includes("Script"))',
  sandboxSnippets: [
    snippet('Tidy text', 'const raw = "   Hello there   "\nconsole.log(`[${raw.trim()}]`)\nconsole.log(raw.trim().toLowerCase())'),
    snippet('Search', 'const email = "sam@example.com"\nconsole.log(email.includes("@"), email.endsWith(".com"), email.indexOf("@"))'),
    snippet('Slices', 'const date = "2026-11-06"\nconsole.log(date.slice(0, 4), date.slice(5, 7), date.slice(-2))'),
    snippet('Replace and pad', 'console.log("a-b-c".replace("-", "+"), "a-b-c".replaceAll("-", "+"))\nconsole.log("7".padStart(3, "0"), "=".repeat(10))'),
  ],
  readMore: MDN('Web/JavaScript/Reference/Global_Objects/String#instance_methods', 'MDN: string methods'),
  challenges: [
    task('easy', 'Shout it', {
      prompt: 'Set `loud` to `message` in capital letters.',
      starter: 'const message = "help"\n',
      hint: '`message.toUpperCase()`.',
      solution: 'const message = "help"\nconst loud = message.toUpperCase()',
      tests: [['loud is HELP', is('loud', 'HELP')], ['Uses toUpperCase', uses('toUpperCase()')]],
    }),
    task('easy', 'Trim the spaces', {
      prompt: 'Set `clean` to `input` without the spaces at either end.',
      starter: 'const input = "   pizza   "\n',
      hint: '`input.trim()`.',
      solution: 'const input = "   pizza   "\nconst clean = input.trim()',
      tests: [['clean is pizza', is('clean', 'pizza')], ['Uses trim', uses('trim()')]],
    }),
    task('easy', 'Does it include?', {
      prompt: 'Set `hasAt` to whether `email` includes an `@`.',
      starter: 'const email = "kim@school.org"\n',
      hint: '`email.includes("@")` gives true or false.',
      solution: 'const email = "kim@school.org"\nconst hasAt = email.includes("@")',
      tests: [['hasAt is true', is('hasAt', true)], ['Uses includes', uses('includes(')]],
      alt: 'const email = "kim.school.org"',
    }),
    task('medium', 'The year', {
      prompt: 'Set `year` to the first 4 characters of `date`.',
      starter: 'const date = "2026-11-06"\n',
      hint: '`date.slice(0, 4)`: from index 0 up to (not including) 4.',
      solution: 'const date = "2026-11-06"\nconst year = date.slice(0, 4)',
      tests: [['year is "2026"', is('year', '2026')], ['Uses slice', uses('slice(')]],
      alt: 'const date = "1999-01-31"',
    }),
    task('medium', 'Tidy a name', {
      prompt: 'Set `tidy` to `raw` trimmed and in lower case, by chaining two methods.',
      starter: 'const raw = "  ALEX  "\n',
      hint: '`raw.trim().toLowerCase()`.',
      solution: 'const raw = "  ALEX  "\nconst tidy = raw.trim().toLowerCase()',
      tests: [['tidy is alex', is('tidy', 'alex')], ['Chains the methods', matches('trim\\(\\)\\s*\\.toLowerCase\\(\\)|toLowerCase\\(\\)\\s*\\.trim\\(\\)')]],
    }),
    task('medium', 'Swap a word', {
      prompt: 'Set `fixed` to `text` with `cat` replaced by `dog`.',
      starter: 'const text = "I love my cat"\n',
      hint: '`text.replace("cat", "dog")`.',
      solution: 'const text = "I love my cat"\nconst fixed = text.replace("cat", "dog")',
      tests: [['fixed is I love my dog', is('fixed', 'I love my dog')], ['Uses replace', uses('replace(')]],
      alt: 'const text = "My cat is called Tom"',
    }),
    task('hard', 'Mask a card number', {
      prompt: 'Show only the last 4 digits of `card`, after `**** `: `**** 4321`.',
      starter: 'const card = "1234567887654321"\n',
      hint: '`card.slice(-4)` is the last 4 characters. Put it in a template literal after `**** `.',
      solution: 'const card = "1234567887654321"\nconsole.log(`**** ${card.slice(-4)}`)',
      tests: [['Shows **** 4321', prints('**** 4321')], ['Uses slice', uses('slice(')]],
      alt: 'const card = "4000123412349876"',
    }),
    task('hard', 'Order number', {
      prompt: 'Order numbers are 5 digits with zeros in front. Set `code` to `n` written that way: 42 becomes `"00042"`.',
      starter: 'const n = 42\n',
      hint: 'Make it text first: `String(n).padStart(5, "0")`.',
      solution: 'const n = 42\nconst code = String(n).padStart(5, "0")',
      tests: [['code is "00042"', is('code', '00042')], ['Uses padStart', uses('padStart(')]],
    }),
    task('expert', 'Capitalise a word', {
      prompt: 'Set `nice` to `word` with its first letter in capitals and the rest in lower case: `hELLO` becomes `Hello`.',
      starter: 'const word = "hELLO"\n',
      hint: '`word[0].toUpperCase() + word.slice(1).toLowerCase()`.',
      solution: 'const word = "hELLO"\nconst nice = word[0].toUpperCase() + word.slice(1).toLowerCase()',
      tests: [['nice is Hello', is('nice', 'Hello')]],
      alt: 'const word = "wORLD"',
    }),
    task('expert', 'The username', {
      prompt: 'Set `user` to the part of `email` before the `@`. Find the `@` with `indexOf`, then slice up to it.',
      starter: 'const email = "maya.lopez@mail.com"\n',
      hint: '`email.slice(0, email.indexOf("@"))`.',
      solution: 'const email = "maya.lopez@mail.com"\nconst user = email.slice(0, email.indexOf("@"))',
      tests: [['user is maya.lopez', is('user', 'maya.lopez')], ['Uses indexOf', uses('indexOf(')]],
      alt: 'const email = "sam@school.org"',
    }),
  ],
  questions: [
    mc('What does `"Hi".toUpperCase()` give?', ['"HI"', '"hi"', '"Hi"', 'An error'], 0,
      'toUpperCase gives a copy in capitals.', { code: 'console.log("Hi".toUpperCase())', output: 'HI' }),
    mc('What does `"  a b  ".trim()` give?', ['"a b"', '"ab"', '"  a b"', '"a b  "'], 0,
      'trim removes spaces from both ends only, not the middle.', { code: 'console.log(`[${"  a b  ".trim()}]`)', output: '[a b]' }),
    mc('What does `"banana".indexOf("n")` give?', ['2', '1', '3', '-1'], 0,
      'It gives the first position: b is 0, a is 1, n is 2.', { code: 'console.log("banana".indexOf("n"))', output: '2' }),
    mc('What does `"JavaScript".slice(0, 4)` give?', ['"Java"', '"JavaS"', '"Scri"', '"avaS"'], 0,
      'From index 0 up to, not including, index 4.', { code: 'console.log("JavaScript".slice(0, 4))', output: 'Java' }),
    mc('What does `"hello".slice(-3)` give?', ['"llo"', '"hel"', '"lo"', '"he"'], 0,
      'A negative start counts from the end.', { code: 'console.log("hello".slice(-3))', output: 'llo' }),
    mc('What does `"a-b-c".replace("-", "+")` give?', ['"a+b-c"', '"a+b+c"', '"abc"', '"a-b-c"'], 0,
      'replace swaps only the first match; replaceAll swaps every one.', { code: 'console.log("a-b-c".replace("-", "+"))', output: 'a+b-c' }),
    mc('After `const s = "hi"` and `s.toUpperCase()`, what is `s`?', ['"hi"', '"HI"', 'undefined', 'An error'], 0,
      'Methods give new strings; the original never changes.', { code: 'const s = "hi"\ns.toUpperCase()\nconsole.log(s)', output: 'hi' }),
    mc('What does `"7".padStart(3, "0")` give?', ['"007"', '"700"', '"0007"', '"7"'], 0,
      'It adds zeros at the start until the text is 3 characters long.', { code: 'console.log("7".padStart(3, "0"))', output: '007' }),
    qShort('What does `"cat".includes("dog")` give?', 'false',
      'includes gives true or false; "cat" doesn\'t contain "dog".'),
  ],
})
