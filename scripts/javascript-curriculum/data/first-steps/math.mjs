// First steps: Math. Lesson, Try-it snippets, challenges and quiz.
import { MDN, avoids, is, makeTopic, matches, mc, near, prints, qShort, snippet, task, uses } from '../_builders.mjs'

export default makeTopic({
  id: 'math',
  title: 'Math: rounding and more',
  paragraphs: [
    '`Math` is a built-in toolbox of maths functions. You use each one as `Math.` and its name, with the number in brackets.',
    '```\nconsole.log(Math.round(4.6), Math.floor(4.6), Math.ceil(4.2))\nconsole.log(Math.max(3, 9, 5), Math.min(3, 9, 5))\nconsole.log(Math.abs(-7), Math.sqrt(81))\n```',
    'There are three ways to round to a whole number. `Math.round` goes to the nearest (`4.5` becomes `5`), `Math.floor` always goes down, and `Math.ceil` always goes up. `Math.trunc` simply cuts off the decimals.',
    '`Math.max` and `Math.min` take any number of values and give the largest or smallest. `Math.abs` gives the distance from zero, so it turns `-7` into `7`. `Math.sqrt` is the square root, and `Math.PI` is π.',
    'To round to 2 decimal places for showing, use a number\'s `toFixed(2)`: `(4.567).toFixed(2)` gives `"4.57"`. It gives **text**, which is right for showing a price but not for more maths.',
    '```\nconst price = 19.999\nconsole.log(price.toFixed(2))\nconsole.log((0.1 + 0.2).toFixed(2))\n```',
    'To round and keep a number, scale up, round and scale back: `Math.round(price * 100) / 100`.',
    '`Math.random()` gives a different decimal between 0 and 1 each time, which games use for dice and shuffling. Because its answer changes, the challenges here don\'t use it.',
  ],
  sandboxCode: 'console.log(Math.round(4.6), Math.floor(4.6), Math.ceil(4.2))\nconsole.log(Math.max(3, 9, 5), Math.min(3, 9, 5))\nconsole.log(Math.abs(-7), Math.sqrt(81))\nconsole.log((19.999).toFixed(2))',
  sandboxSnippets: [
    snippet('Three roundings', 'const x = 7.5\nconsole.log(Math.round(x), Math.floor(x), Math.ceil(x), Math.trunc(x))'),
    snippet('Largest and smallest', 'console.log(Math.max(12, 48, 7), Math.min(12, 48, 7))'),
    snippet('Two decimals', 'const total = 10 / 3\nconsole.log(total)\nconsole.log(total.toFixed(2))\nconsole.log(Math.round(total * 100) / 100)'),
    snippet('A circle', 'const r = 3\nconsole.log(Math.PI * r ** 2)'),
  ],
  readMore: MDN('Web/JavaScript/Reference/Global_Objects/Math', 'MDN: Math'),
  challenges: [
    task('easy', 'Round to the nearest', {
      prompt: 'Set `rounded` to `score` rounded to the nearest whole number.',
      starter: 'const score = 8.6\n',
      hint: '`Math.round(score)`.',
      solution: 'const score = 8.6\nconst rounded = Math.round(score)',
      tests: [['rounded is 9', is('rounded', 9)], ['Uses Math.round', uses('Math.round')]],
    }),
    task('easy', 'The biggest', {
      prompt: 'Set `best` to the largest of the three scores.',
      starter: 'const a = 42\nconst b = 87\nconst c = 65\n',
      hint: '`Math.max(a, b, c)`.',
      solution: 'const a = 42\nconst b = 87\nconst c = 65\nconst best = Math.max(a, b, c)',
      tests: [['best is 87', is('best', 87)], ['Uses Math.max', uses('Math.max')]],
    }),
    task('easy', 'How far apart', {
      prompt: 'Set `gap` to the distance between `x` and `y`, always positive: `Math.abs(x - y)`.',
      starter: 'const x = 3\nconst y = 11\n',
      hint: '`x - y` is `-8`; `Math.abs` makes it `8`.',
      solution: 'const x = 3\nconst y = 11\nconst gap = Math.abs(x - y)',
      tests: [['gap is 8', is('gap', 8)], ['Uses Math.abs', uses('Math.abs')]],
    }),
    task('medium', 'Boxes needed', {
      prompt: 'Each box holds 6 eggs. Set `boxes` to how many boxes 26 eggs need (a part-full box still counts).',
      starter: 'const eggs = 26\nconst perBox = 6\n',
      hint: 'Divide and always round up: `Math.ceil(eggs / perBox)`.',
      solution: 'const eggs = 26\nconst perBox = 6\nconst boxes = Math.ceil(eggs / perBox)',
      tests: [['boxes is 5', is('boxes', 5)], ['Rounds up', uses('Math.ceil')]],
    }),
    task('medium', 'Full teams', {
      prompt: '`players` people form teams of 5. Set `teams` to the number of full teams.',
      starter: 'const players = 23\n',
      hint: 'Divide and round down: `Math.floor(players / 5)`.',
      solution: 'const players = 23\nconst teams = Math.floor(players / 5)',
      tests: [['teams is 4', is('teams', 4)], ['Rounds down', uses('Math.floor')]],
    }),
    task('medium', 'Show a price', {
      prompt: 'Show `price` with exactly 2 decimal places: `3.50`.',
      starter: 'const price = 3.5\n',
      hint: '`price.toFixed(2)` gives the text `"3.50"`.',
      solution: 'const price = 3.5\nconsole.log(price.toFixed(2))',
      tests: [['Shows 3.50', prints('3.50')], ['Uses toFixed', uses('toFixed(2)')]],
    }),
    task('hard', 'Round and keep a number', {
      prompt: 'Set `share` to the bill divided by 3, rounded to 2 decimal places, as a number (not text).',
      starter: 'const bill = 100\n',
      hint: 'Scale up, round, scale back: `Math.round(bill / 3 * 100) / 100`.',
      solution: 'const bill = 100\nconst share = Math.round(bill / 3 * 100) / 100',
      tests: [['share is the number 33.33', near('share', 33.33)], ['Uses Math.round', uses('Math.round')]],
    }),
    task('hard', 'The longest side', {
      prompt: 'A right-angled triangle has short sides `a` and `b`. Set `c`, the long side, to the square root of `a ** 2 + b ** 2`.',
      starter: 'const a = 6\nconst b = 8\n',
      hint: '`Math.sqrt(a ** 2 + b ** 2)`.',
      solution: 'const a = 6\nconst b = 8\nconst c = Math.sqrt(a ** 2 + b ** 2)',
      tests: [['c is 10', near('c', 10)], ['Uses Math.sqrt', uses('Math.sqrt')]],
    }),
    task('expert', 'Area of a circle', {
      prompt: 'Show the area of a circle of radius `r` (π times r squared), rounded to 1 decimal place: `Area: 50.3`.',
      starter: 'const r = 4\n',
      hint: '`(Math.PI * r ** 2).toFixed(1)`, shown after the text `"Area:"`.',
      solution: 'const r = 4\nconsole.log("Area:", (Math.PI * r ** 2).toFixed(1))',
      tests: [['Shows Area: 50.3', prints('Area: 50.3')], ['Uses Math.PI', uses('Math.PI')], ['Works it out', avoids('50.3')]],
    }),
    task('expert', 'Keep it in range', {
      prompt: 'A volume must stay between 0 and 10. Set `safe` to `volume` limited to that range, using `Math.min` and `Math.max` together.',
      starter: 'const volume = 14\n',
      hint: '`Math.max(0, Math.min(10, volume))`: the inner one caps it at 10, the outer keeps it at least 0.',
      solution: 'const volume = 14\nconst safe = Math.max(0, Math.min(10, volume))',
      tests: [['safe is 10', is('safe', 10)], ['Uses Math.min and Math.max', uses('Math.min') + ' && ' + uses('Math.max')]],
      alt: (starter) => starter.replace('14', '-3'),
    }),
  ],
  questions: [
    mc('What does `Math.floor(7.9)` give?', ['7', '8', '7.9', '8.0'], 0,
      'floor always rounds down.', { code: 'console.log(Math.floor(7.9))', output: '7' }),
    mc('What does `Math.ceil(7.1)` give?', ['8', '7', '7.1', '7.0'], 0,
      'ceil always rounds up.', { code: 'console.log(Math.ceil(7.1))', output: '8' }),
    mc('What does `Math.round(2.5)` give?', ['3', '2', '2.5', '2.0'], 0,
      'round goes to the nearest whole number, and .5 goes up.', { code: 'console.log(Math.round(2.5))', output: '3' }),
    mc('What does `Math.max(4, 11, 2)` give?', ['11', '4', '2', '17'], 0,
      'max gives the largest of its values.', { code: 'console.log(Math.max(4, 11, 2))', output: '11' }),
    mc('What does `(2.456).toFixed(2)` give?', ['The text "2.46"', 'The number 2.46', 'The text "2.45"', 'The number 2.45'], 0,
      'toFixed rounds and gives text, ready to show.'),
    mc('What does `Math.abs(-12)` give?', ['12', '-12', '0', '144'], 0,
      'abs gives the distance from zero.', { code: 'console.log(Math.abs(-12))', output: '12' }),
    mc('Which gives the number of full teams of 4 from 18 players?', ['`Math.floor(18 / 4)`', '`Math.ceil(18 / 4)`', '`Math.round(18 / 4)`', '`18 % 4`'], 0,
      'Full teams means rounding down: 4 teams, with 2 players left over.'),
    mc('What does `Math.sqrt(49)` give?', ['7', '49', '24.5', '2401'], 0,
      'The square root of 49 is 7, because 7 × 7 is 49.', { code: 'console.log(Math.sqrt(49))', output: '7' }),
    qShort('Which `Math` function always rounds down? (just its name)', 'floor',
      '`Math.floor` rounds down; `Math.ceil` rounds up.'),
  ],
})
