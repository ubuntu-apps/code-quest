// First steps: Showing values. Lesson, Try-it snippets, challenges and quiz.
import { MDN, avoids, makeTopic, matches, mc, prints, qShort, snippet, task, uses } from '../_builders.mjs'

export default makeTopic({
  id: 'showing_values',
  title: 'Showing values',
  paragraphs: [
    '`console.log()` can show several values at once. Separate them with commas and it puts one space between each:',
    '```\nconsole.log("Apples:", 3, "Pears:", 5)\nconsole.log(10, 20, 30)\n```',
    'Numbers can be whole (`7`), decimal (`2.5`) or negative (`-4`). JavaScript works out any maths before it shows the result, so `console.log(20 - 13.75)` shows `6.25`.',
    'An empty `console.log()` shows an empty line, which is handy for spacing output out.',
    'Text can hold the other kind of quote: `"It\'s sunny"` uses double quotes around a single quote, and `\'She said "hi"\'` the other way round.',
    'A backslash starts an **escape**: a special character inside text. `\\n` starts a new line, `\\t` is a tab, `\\"` is a double quote inside double quotes, and `\\\\` is one backslash.',
    '```\nconsole.log("Line one\\nLine two")\nconsole.log("Name\\tScore")\nconsole.log("She said \\"hi\\"")\n```',
    'Lines are shown in the order the code runs them, top to bottom. To change the order of the output, change the order of the lines.',
  ],
  sandboxCode: 'console.log("Apples:", 3, "Pears:", 5)\nconsole.log()\nconsole.log("Change:", 20 - 13.75)\nconsole.log("Line one\\nLine two")',
  sandboxSnippets: [
    snippet('Several values', 'console.log("Score:", 7, "of", 10)'),
    snippet('Quotes inside', 'console.log("It\'s sunny")\nconsole.log(\'She said "hi"\')\nconsole.log("She said \\"hi\\"")'),
    snippet('Escapes', 'console.log("One\\nTwo\\nThree")\nconsole.log("Name\\tScore")\nconsole.log("C:\\\\Users")'),
    snippet('Blank line', 'console.log("Top")\nconsole.log()\nconsole.log("Bottom")'),
  ],
  readMore: MDN('Web/API/console/log_static', 'MDN: console.log()'),
  challenges: [
    task('easy', 'Three values', {
      prompt: 'Show `Apples 3 Pears 5` by giving `console.log` four values separated by commas: two texts and two numbers.',
      starter: 'console.log()',
      hint: '`console.log("Apples", 3, "Pears", 5)`: the commas become spaces.',
      solution: 'console.log("Apples", 3, "Pears", 5)',
      tests: [
        ['Shows Apples 3 Pears 5', prints('Apples 3 Pears 5')],
        ['Gives the numbers as numbers', matches(',\\s*3\\s*,') + ' && ' + matches(',\\s*5\\s*\\)')],
      ],
    }),
    task('easy', 'A blank line', {
      prompt: 'Show `Top`, then an empty line, then `Bottom`.',
      starter: 'console.log("Top")\n\nconsole.log("Bottom")',
      hint: 'An empty `console.log()` shows an empty line.',
      solution: 'console.log("Top")\nconsole.log()\nconsole.log("Bottom")',
      tests: [['Shows Top, an empty line, then Bottom', prints('Top', '', 'Bottom')]],
      typedOk: true,
    }),
    task('easy', 'A quote inside', {
      prompt: 'Show `It\'s sunny`.',
      starter: 'console.log()',
      hint: 'Put the text in double quotes, so the single quote inside is just a character: `"It\'s sunny"`.',
      solution: 'console.log("It\'s sunny")',
      tests: [['Shows It\'s sunny', prints('It\'s sunny')]],
      typedOk: true,
    }),
    task('medium', 'Double quotes inside', {
      prompt: 'Show `She said "hi"`, with the double quotes.',
      starter: 'console.log()',
      hint: 'Use single quotes around the text, or write each inner quote as `\\"`.',
      solution: 'console.log(\'She said "hi"\')',
      tests: [['Shows She said "hi"', prints('She said "hi"')]],
      typedOk: true,
    }),
    task('medium', 'Two lines, one log', {
      prompt: 'Show `Line one` and `Line two` on separate lines with a single `console.log`.',
      starter: 'console.log()',
      hint: 'Put `\\n` in the text where the new line starts: `"Line one\\nLine two"`.',
      solution: 'console.log("Line one\\nLine two")',
      tests: [
        ['Shows the two lines', prints('Line one', 'Line two')],
        ['Uses one console.log', '(_cq_code.match(/console\\.log/g) || []).length === 1'],
        ['Uses \\n for the new line', uses('\\n')],
      ],
      typedOk: true,
    }),
    task('medium', 'Work out the change', {
      prompt: 'A snack costs 13.75 and you pay with 20. Show `Change: 6.25`, letting JavaScript work out the change.',
      starter: 'console.log()',
      hint: 'Two values: the text `"Change:"` and the sum `20 - 13.75`.',
      solution: 'console.log("Change:", 20 - 13.75)',
      tests: [
        ['Shows Change: 6.25', prints('Change: 6.25')],
        ['Lets JavaScript work it out', avoids('6.25')],
      ],
    }),
    task('hard', 'Put it in order', {
      prompt: 'Rearrange the lines so the countdown shows `3`, `2`, `1`, `Go!`, one per line.',
      starter: 'console.log("Go!")\nconsole.log(2)\nconsole.log(3)\nconsole.log(1)',
      hint: 'Lines run from top to bottom. Move `console.log(3)` to the top and `console.log("Go!")` to the bottom.',
      solution: 'console.log(3)\nconsole.log(2)\nconsole.log(1)\nconsole.log("Go!")',
      tests: [['Shows 3, 2, 1, Go!', prints('3', '2', '1', 'Go!')]],
      typedOk: true,
    }),
    task('hard', 'A tab between', {
      prompt: 'Show `Name`, a tab, then `Score`, with one text that uses the tab escape.',
      starter: 'console.log()',
      hint: 'The tab escape is `\\t`: `"Name\\tScore"`.',
      solution: 'console.log("Name\\tScore")',
      tests: [
        ['Shows Name, a tab, then Score', prints('Name\tScore')],
        ['Uses \\t', uses('\\t')],
      ],
      typedOk: true,
    }),
    task('expert', 'Minutes in a day and a week', {
      prompt: 'Show `Minutes in a day: 1440` and then `Minutes in a week: 10080`. Let JavaScript calculate both numbers from 24 hours, 60 minutes and 7 days.',
      starter: 'console.log("Minutes in a day:", )\n',
      hint: 'A day is `24 * 60` minutes, and a week is `7 * 24 * 60`.',
      solution: 'console.log("Minutes in a day:", 24 * 60)\nconsole.log("Minutes in a week:", 7 * 24 * 60)',
      tests: [
        ['Shows both lines', prints('Minutes in a day: 1440', 'Minutes in a week: 10080')],
        ['Lets JavaScript work them out', avoids('1440') + ' && ' + avoids('10080')],
      ],
    }),
    task('expert', 'Fix the backslash', {
      prompt: 'This should show `Saved in C:\\new folder`, but the `\\n` starts a new line instead. Fix it so it shows one backslash and the word `new`.',
      starter: 'console.log("Saved in C:\\new folder")',
      hint: 'In text, `\\\\` is one backslash. Write `C:\\\\new`.',
      solution: 'console.log("Saved in C:\\\\new folder")',
      tests: [['Shows the path on one line', prints('Saved in C:\\new folder')]],
      typedOk: true,
    }),
  ],
  questions: [
    mc('What does `console.log("Total:", 4, 2)` show?', ['Total: 4 2', 'Total:42', 'Total: 6', 'Total: 4, 2'], 0,
      'Each value is shown with one space between; nothing is added together.',
      { code: 'console.log("Total:", 4, 2)', output: 'Total: 4 2' }),
    mc('What does an empty `console.log()` show?', ['An empty line', 'Nothing at all', 'undefined', 'An error'], 0,
      'With nothing inside, it writes a line with nothing on it.'),
    mc('Which line shows `It\'s late`?', ['`console.log("It\'s late")`', '`console.log(\'It\'s late\')`', '`console.log(It\'s late)`', '`console.log("It"s late")`'], 0,
      'In double quotes, a single quote is just a character. In single quotes it would end the text early.'),
    mc('What does `\\n` do inside text?', ['Starts a new line', 'Shows the letter n', 'Ends the text', 'Adds a space'], 0,
      '`\\n` is the escape for a new line.'),
    mc('What does `console.log(10 - 2.5)` show?', ['7.5', '10 - 2.5', '8', '7,5'], 0,
      'JavaScript works out the sum first. Decimals are written with a dot.',
      { code: 'console.log(10 - 2.5)', output: '7.5' }),
    mc('How many lines does `console.log("a\\nb\\nc")` show?', ['3', '1', '2', '0'], 0,
      'Each `\\n` starts a new line, so a, b and c are on three lines.'),
    mc('How do you show one backslash, `\\`?', ['`"\\\\"`', '`"\\"`', '`"/"`', '`"\\n"`'], 0,
      'A backslash starts an escape, so a real backslash is written as two.'),
    qShort('Which escape puts a tab inside text? (two characters)', '\\t',
      '`\\t` is the tab escape.'),
    mc('Code logs `"B"` on its first line and `"A"` on its second. What does it show?', ['B, then A', 'A, then B', 'Only B', 'Only A'], 0,
      'Lines run from top to bottom, so the output is in the same order.'),
  ],
})
