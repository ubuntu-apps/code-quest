// First steps: True or false (booleans and comparing). Lesson, Try-it snippets, challenges and quiz.
import { MDN, is, makeTopic, matches, mc, prints, qShort, snippet, task, uses } from '../_builders.mjs'

export default makeTopic({
  id: 'comparing',
  title: 'True or false: comparing values',
  paragraphs: [
    'A **boolean** is one of two values, `true` or `false`. You get one whenever you compare two values:',
    '```\nconst age = 14\nconsole.log(age > 12, age < 10, age >= 14, age <= 13)\n```',
    '`>` and `<` are greater and less than, and `>=` and `<=` include equal. `===` asks whether two values are the same, and `!==` whether they are different. A single `=` is not a comparison: it gives a variable a value.',
    '```\nconst password = "open-sesame"\nconsole.log(password === "open-sesame", password !== "letmein")\n```',
    '`===` is strict: the type has to match too, so `5 === "5"` is `false` (a number isn\'t a string). There is also a loose `==` that converts types first, so `5 == "5"` is `true`, along with surprises like `0 == ""`. Always use `===` and `!==`.',
    'Strings compare letter by letter and are case-sensitive: `"cat" === "Cat"` is `false`. To compare without caring about case, change both first: `a.toLowerCase() === b.toLowerCase()`.',
    'Booleans can be stored and combined. `&&` (and) is true only when both sides are true; `||` (or) is true when at least one is; `!` (not) turns one around.',
    '```\nconst age = 15\nconst hasTicket = true\nconst canEnter = age >= 12 && hasTicket\nconsole.log(canEnter, !canEnter, age < 12 || hasTicket)\n```',
    'In the next quest, these true-or-false values decide what a program does, with `if` and loops.',
  ],
  sandboxCode: 'const age = 14\nconsole.log(age > 12, age === 14, age !== 14)\nconsole.log(5 === "5", 5 == "5")\nconsole.log(age >= 12 && age < 18)',
  sandboxSnippets: [
    snippet('Comparing numbers', 'const score = 72\nconsole.log(score > 50, score >= 72, score < 72, score === 100)'),
    snippet('Comparing text', 'console.log("cat" === "cat", "cat" === "Cat")\nconsole.log("Cat".toLowerCase() === "cat")'),
    snippet('Strict or loose', 'console.log(5 === "5", 5 == "5")\nconsole.log(0 == "", 0 === "")'),
    snippet('And, or, not', 'const sunny = true\nconst warm = false\nconsole.log(sunny && warm, sunny || warm, !warm)'),
  ],
  readMore: MDN('Web/JavaScript/Guide/Expressions_and_operators#comparison_operators', 'MDN: comparison operators'),
  challenges: [
    task('easy', 'Old enough?', {
      prompt: 'Set `canVote` to whether `age` is 18 or more.',
      starter: 'const age = 21\n',
      hint: '`age >= 18`.',
      solution: 'const age = 21\nconst canVote = age >= 18',
      tests: [['canVote is true', is('canVote', true)], ['Compares with >=', uses('>=')]],
      alt: 'const age = 16',
    }),
    task('easy', 'Below zero', {
      prompt: 'Set `freezing` to whether `temp` is less than 0.',
      starter: 'const temp = -4\n',
      hint: '`temp < 0`.',
      solution: 'const temp = -4\nconst freezing = temp < 0',
      tests: [['freezing is true', is('freezing', true)]],
      alt: 'const temp = 6',
    }),
    task('easy', 'The right code', {
      prompt: 'Set `correct` to whether `guess` is exactly `"1234"`, using `===`.',
      starter: 'const guess = "1234"\n',
      hint: '`guess === "1234"`.',
      solution: 'const guess = "1234"\nconst correct = guess === "1234"',
      tests: [['correct is true', is('correct', true)], ['Uses ===', uses('===')]],
      alt: 'const guess = "4321"',
    }),
    task('medium', 'Not the same', {
      prompt: 'Set `changed` to whether `newName` is different from `oldName`.',
      starter: 'const oldName = "Sam"\nconst newName = "Sami"\n',
      hint: '`newName !== oldName`.',
      solution: 'const oldName = "Sam"\nconst newName = "Sami"\nconst changed = newName !== oldName',
      tests: [['changed is true', is('changed', true)], ['Uses !==', uses('!==')]],
      alt: 'const oldName = "Sam"\nconst newName = "Sam"',
    }),
    task('medium', 'Strict, please', {
      prompt: 'This says the number and the text match. Change the comparison so `same` is `false`: they are different types.',
      starter: 'const id = 7\nconst typed = "7"\nconst same = id == typed',
      hint: 'Use the strict `===`, which checks the type too.',
      solution: 'const id = 7\nconst typed = "7"\nconst same = id === typed',
      tests: [['same is false', is('same', false)], ['Uses ===', uses('===')]],
    }),
    task('medium', 'Any case', {
      prompt: 'Set `match` to whether `answer` is `paris` in any mix of capitals, by changing it to lower case first.',
      starter: 'const answer = "PaRiS"\n',
      hint: '`answer.toLowerCase() === "paris"`.',
      solution: 'const answer = "PaRiS"\nconst match = answer.toLowerCase() === "paris"',
      tests: [['match is true', is('match', true)], ['Uses toLowerCase', uses('toLowerCase()')]],
      alt: 'const answer = "London"',
    }),
    task('hard', 'A teenager', {
      prompt: 'Set `teen` to whether `age` is from 13 up to 19, with `&&`.',
      starter: 'const age = 15\n',
      hint: '`age >= 13 && age <= 19`.',
      solution: 'const age = 15\nconst teen = age >= 13 && age <= 19',
      tests: [['teen is true', is('teen', true)], ['Uses &&', uses('&&')]],
      alt: 'const age = 21',
    }),
    task('hard', 'A day off', {
      prompt: 'Set `dayOff` to whether `day` is `"Saturday"` or `"Sunday"`, with `||`.',
      starter: 'const day = "Sunday"\n',
      hint: 'Each side is a full comparison: `day === "Saturday" || day === "Sunday"`.',
      solution: 'const day = "Sunday"\nconst dayOff = day === "Saturday" || day === "Sunday"',
      tests: [['dayOff is true', is('dayOff', true)], ['Uses ||', uses('||')]],
      alt: 'const day = "Monday"',
    }),
    task('expert', 'Free entry', {
      prompt: 'Entry is free for children under 5 and adults 65 or over. Set `free` to whether `age` gets in free, then show `Free: true`.',
      starter: 'const age = 70\n',
      hint: '`age < 5 || age >= 65`, then `` console.log(`Free: ${free}`) ``.',
      solution: 'const age = 70\nconst free = age < 5 || age >= 65\nconsole.log(`Free: ${free}`)',
      tests: [['free is true', is('free', true)], ['Shows Free: true', prints('Free: true')]],
      alt: 'const age = 30',
    }),
    task('expert', 'Password rules', {
      prompt: 'A password is good when it is at least 8 characters long and is not `"password"`. Set `good` for `pw`.',
      starter: 'const pw = "sunflower"\n',
      hint: '`pw.length >= 8 && pw !== "password"`.',
      solution: 'const pw = "sunflower"\nconst good = pw.length >= 8 && pw !== "password"',
      tests: [['good is true', is('good', true)], ['Checks the length', uses('length')], ['Combines with &&', uses('&&')]],
      alt: 'const pw = "password"',
    }),
  ],
  questions: [
    mc('What does `7 > 3` give?', ['true', 'false', '4', '"7 > 3"'], 0,
      '7 is greater than 3.', { code: 'console.log(7 > 3)', output: 'true' }),
    mc('What does `5 === "5"` give?', ['false', 'true', 'An error', 'NaN'], 0,
      '=== checks the type too: a number isn\'t a string.', { code: 'console.log(5 === "5")', output: 'false' }),
    mc('What does `5 == "5"` give?', ['true', 'false', 'An error', '"55"'], 0,
      'The loose == converts types first, which is why it\'s best avoided.', { code: 'console.log(5 == "5")', output: 'true' }),
    mc('What does `"cat" === "Cat"` give?', ['false', 'true', 'An error', 'undefined'], 0,
      'Comparing strings is case-sensitive.', { code: 'console.log("cat" === "Cat")', output: 'false' }),
    mc('What does `10 >= 10` give?', ['true', 'false', '10', '20'], 0,
      '>= includes equal.', { code: 'console.log(10 >= 10)', output: 'true' }),
    mc('What does `true && false` give?', ['false', 'true', 'undefined', 'An error'], 0,
      '&& needs both sides to be true.', { code: 'console.log(true && false)', output: 'false' }),
    mc('What does `false || true` give?', ['true', 'false', 'undefined', 'An error'], 0,
      '|| needs only one side to be true.', { code: 'console.log(false || true)', output: 'true' }),
    mc('What\'s the difference between `=` and `===`?', ['`=` gives a value; `===` compares', 'None', '`===` gives a value; `=` compares', '`=` is for text only'], 0,
      'A single = assigns; === asks whether two values are the same.'),
    qShort('What does `!true` give?', 'false',
      '! turns true into false and false into true.'),
  ],
})
