// First steps: Template literals. Lesson, Try-it snippets, challenges and quiz.
import { MDN, avoids, is, makeTopic, matches, mc, prints, qShort, snippet, task, uses } from '../_builders.mjs'

export default makeTopic({
  id: 'template_literals',
  title: 'Template literals',
  paragraphs: [
    'Joining text with `+` gets fiddly: quotes, plus signs and spaces everywhere. A **template literal** is easier. It is text in backticks (`` ` ``, usually at the top left of the keyboard), and `${…}` drops a value straight into it:',
    '```\nconst name = "Sam"\nconst age = 12\nconsole.log(`${name} is ${age} years old`)\n```',
    'Inside `${…}` you can put any expression, not just a variable: `${price * 2}`, `${name.length}` or `${Math.round(score)}` are worked out first, then put in the text.',
    '```\nconst price = 4.5\nconst count = 3\nconsole.log(`${count} items cost ${price * count}`)\nconsole.log(`Total: $${(price * count).toFixed(2)}`)\n```',
    'The `$` before `{` is what marks the gap. A `$` on its own, as in `$13.50`, is just a character, so `$${total}` shows a dollar sign and then the value.',
    'A template literal can also go over several lines: the line breaks inside the backticks are kept. And both kinds of quote can go inside one without escapes: `` `It\'s "fine"` ``.',
    '```\nconst poem = `Roses are red,\nViolets are blue.`\nconsole.log(poem)\n```',
    'Only backticks do this. In `"Hi ${name}"`, with ordinary quotes, `${name}` is just shown as it is.',
  ],
  sandboxCode: 'const name = "Sam"\nconst age = 12\nconsole.log(`${name} is ${age} years old`)\nconsole.log(`Next year: ${age + 1}`)',
  sandboxSnippets: [
    snippet('Expressions', 'const w = 8\nconst h = 3\nconsole.log(`${w} × ${h} = ${w * h}`)'),
    snippet('Money', 'const total = 13.5\nconsole.log(`Total: $${total.toFixed(2)}`)'),
    snippet('Several lines', 'const name = "Ana"\nconst card = `Name: ${name}\nLevel: 3\nXP: 120`\nconsole.log(card)'),
    snippet('Quotes or backticks?', 'const name = "Ana"\nconsole.log("Hi ${name}")\nconsole.log(`Hi ${name}`)'),
  ],
  readMore: MDN('Web/JavaScript/Reference/Template_literals', 'MDN: template literals'),
  challenges: [
    task('easy', 'Say hi', {
      prompt: 'Use a template literal to show `Hi, Zoe!` with the name from the variable.',
      starter: 'const name = "Zoe"\n',
      hint: '`` console.log(`Hi, ${name}!`) ``, with backticks around the text.',
      solution: 'const name = "Zoe"\nconsole.log(`Hi, ${name}!`)',
      tests: [['Shows Hi, Zoe!', prints('Hi, Zoe!')], ['Uses a template literal', uses('${name}')]],
    }),
    task('easy', 'Two values', {
      prompt: 'Show `Rex is 4 years old` with one template literal and both variables.',
      starter: 'const pet = "Rex"\nconst age = 4\n',
      hint: '`${pet} is ${age} years old`.',
      solution: 'const pet = "Rex"\nconst age = 4\nconsole.log(`${pet} is ${age} years old`)',
      tests: [['Shows the sentence', prints('Rex is 4 years old')], ['Uses ${pet} and ${age}', uses('${pet}') + ' && ' + uses('${age}')]],
    }),
    task('easy', 'Store it', {
      prompt: 'Set `label` to a template literal that gives `Room 12`, using `room`.',
      starter: 'const room = 12\n',
      hint: '`` const label = `Room ${room}` ``.',
      solution: 'const room = 12\nconst label = `Room ${room}`',
      tests: [['label is Room 12', is('label', 'Room 12')], ['Uses a template literal', uses('${room}')]],
    }),
    task('medium', 'Work it out inside', {
      prompt: 'Show `3 tickets cost 27` with the total worked out inside the `${…}`.',
      starter: 'const tickets = 3\nconst price = 9\n',
      hint: '`${tickets} tickets cost ${tickets * price}`.',
      solution: 'const tickets = 3\nconst price = 9\nconsole.log(`${tickets} tickets cost ${tickets * price}`)',
      tests: [['Shows the line', prints('3 tickets cost 27')], ['Works it out inside ${}', matches('\\$\\{[^}]*\\*[^}]*\\}')], ['Doesn\'t type the total in', avoids('27')]],
    }),
    task('medium', 'A price tag', {
      prompt: 'Show `Total: $7.50`, with the dollar sign and 2 decimal places.',
      starter: 'const total = 7.5\n',
      hint: 'A `$` before `${…}` is just a character: `` `Total: $${total.toFixed(2)}` ``.',
      solution: 'const total = 7.5\nconsole.log(`Total: $${total.toFixed(2)}`)',
      tests: [['Shows Total: $7.50', prints('Total: $7.50')], ['Uses toFixed', uses('toFixed(2)')]],
    }),
    task('medium', 'From + to backticks', {
      prompt: 'Rewrite the line with a template literal instead of `+`. It should still show `Ada scored 95 points`.',
      starter: 'const player = "Ada"\nconst points = 95\nconsole.log(player + " scored " + points + " points")',
      hint: '`` `${player} scored ${points} points` ``, with no `+` left.',
      solution: 'const player = "Ada"\nconst points = 95\nconsole.log(`${player} scored ${points} points`)',
      tests: [['Shows the line', prints('Ada scored 95 points')], ['Uses a template literal', uses('${player}')], ['No + left', avoids('+')]],
    }),
    task('hard', 'Fix the quotes', {
      prompt: 'This shows `Welcome, ${user}` instead of the name. Fix it so it shows `Welcome, Kim`.',
      starter: 'const user = "Kim"\nconsole.log("Welcome, ${user}")',
      hint: 'Only backticks fill in `${…}`. Swap the double quotes for backticks.',
      solution: 'const user = "Kim"\nconsole.log(`Welcome, ${user}`)',
      tests: [['Shows Welcome, Kim', prints('Welcome, Kim')]],
    }),
    task('hard', 'A name card', {
      prompt: 'Set `card` to one template literal over two lines that shows `Name: Leo` on the first line and `Age: 10` on the second, then show it.',
      starter: 'const name = "Leo"\nconst age = 10\n',
      hint: 'Press Enter inside the backticks: write `Name: ${name}`, a new line, then `Age: ${age}`, all inside one pair of backticks.',
      solution: 'const name = "Leo"\nconst age = 10\nconst card = `Name: ${name}\nAge: ${age}`\nconsole.log(card)',
      tests: [['Shows the two lines', prints('Name: Leo', 'Age: 10')], ['card holds both lines', is('card', 'Name: Leo\nAge: 10')]],
    }),
    task('expert', 'Next birthday', {
      prompt: 'Show `Mia is 9 now and will be 10 next year`, working out the next age inside the template literal.',
      starter: 'const name = "Mia"\nconst age = 9\n',
      hint: '`${age + 1}` works out the next age.',
      solution: 'const name = "Mia"\nconst age = 9\nconsole.log(`${name} is ${age} now and will be ${age + 1} next year`)',
      tests: [['Shows the sentence', prints('Mia is 9 now and will be 10 next year')], ['Works out the next age', matches('\\$\\{\\s*age\\s*\\+\\s*1\\s*\\}')]],
    }),
    task('expert', 'Quotes inside', {
      prompt: 'Show `Sam said "it\'s done" at 5`, with both kinds of quote, using one template literal and both variables.',
      starter: 'const who = "Sam"\nconst hour = 5\n',
      hint: 'Inside backticks, `"` and `\'` are just characters: `` `${who} said "it\'s done" at ${hour}` ``.',
      solution: 'const who = "Sam"\nconst hour = 5\nconsole.log(`${who} said "it\'s done" at ${hour}`)',
      tests: [['Shows the line', prints('Sam said "it\'s done" at 5')], ['Uses both variables', uses('${who}') + ' && ' + uses('${hour}')]],
    }),
  ],
  questions: [
    mc('After `const n = 3`, what does `` console.log(`n is ${n}`) `` show?', ['n is 3', 'n is ${n}', '`n is 3`', 'An error'], 0,
      'Backticks fill in `${n}` with its value.', { code: 'const n = 3\nconsole.log(`n is ${n}`)', output: 'n is 3' }),
    mc('After `const n = 3`, what does `console.log("n is ${n}")` show?', ['n is ${n}', 'n is 3', 'An error', 'n is'], 0,
      'Ordinary quotes don\'t fill anything in.', { code: 'const n = 3\nconsole.log("n is ${n}")', output: 'n is ${n}' }),
    mc('What does `` `${2 + 3}` `` give?', ['"5"', '"2 + 3"', '"23"', '5 as a number'], 0,
      'The expression is worked out, then put in the text.', { code: 'console.log(`${2 + 3}`)', output: '5' }),
    mc('Which character surrounds a template literal?', ['The backtick `', 'The double quote "', 'The single quote \'', 'The slash /'], 0,
      'Template literals use backticks.'),
    mc('After `const p = 4`, what does `` `$${p}` `` give?', ['"$4"', '"4"', '"$p"', 'An error'], 0,
      'The first `$` is just a character; `${p}` is the gap.', { code: 'const p = 4\nconsole.log(`$${p}`)', output: '$4' }),
    mc('Can a template literal go over several lines?', ['Yes: the line breaks are kept', 'No, never', 'Only with \\n', 'Only in comments'], 0,
      'Line breaks inside backticks are part of the text.'),
    mc('After `const a = "x"`, what does `` `${a}${a}` `` give?', ['"xx"', '"x x"', '"${a}${a}"', '"aa"'], 0,
      'Two gaps next to each other give the value twice, with nothing between.', { code: 'const a = "x"\nconsole.log(`${a}${a}`)', output: 'xx' }),
    mc('Why use template literals instead of `+`?', ['They are easier to read and need no extra quotes or plus signs', 'They run much faster', 'They are the only way to join text', 'They change numbers into words'], 0,
      'They make text with values in it simpler to write and read.'),
    qShort('What two characters start a gap for a value in a template literal?', '${',
      '`${` starts the gap and `}` ends it.'),
  ],
})
