// First steps: Strings. Lesson, Try-it snippets, challenges and quiz.
import { MDN, avoids, is, makeTopic, matches, mc, prints, qShort, snippet, task, uses } from '../_builders.mjs'

export default makeTopic({
  id: 'strings',
  title: 'Strings: working with text',
  paragraphs: [
    'A piece of text is called a **string**. `+` joins strings together; this is called **concatenation**. It adds no spaces of its own, so put them in the text where you want them:',
    '```\nconst first = "Ada"\nconst last = "Lovelace"\nconst full = first + " " + last\nconsole.log(full)\n```',
    '`+=` adds to the end of a string you already have: `message += "!"`.',
    'Every string has a `length`: how many characters it has, counting spaces and punctuation. `"Hello".length` is `5`. It has no brackets, because it is a value the string carries, not something it does.',
    'Each character has a position, its **index**, counting from **0**. `word[0]` is the first character, and the last one is `word[word.length - 1]`, because a 5-letter word\'s indexes go from 0 to 4. `word.at(-1)` is a shortcut for the last character.',
    '```\nconst word = "Hello"\nconsole.log(word.length, word[0], word[4], word.at(-1))\n```',
    'An index past the end gives `undefined`, JavaScript\'s value for "nothing here".',
    'Strings can\'t be changed in place: `word[0] = "J"` does nothing. To change a string you build a new one, such as `"J" + word.slice(1)` (you will meet `slice` in the string methods stage).',
  ],
  sandboxCode: 'const first = "Ada"\nconst last = "Lovelace"\nconst full = first + " " + last\nconsole.log(full)\nconsole.log(full.length, full[0], full.at(-1))',
  sandboxSnippets: [
    snippet('Joining', 'const greeting = "Hello, " + "world" + "!"\nconsole.log(greeting)'),
    snippet('Adding on', 'let message = "Well done"\nmessage += ", Sam"\nmessage += "!"\nconsole.log(message)'),
    snippet('Length and indexes', 'const word = "JavaScript"\nconsole.log(word.length)\nconsole.log(word[0], word[4], word[word.length - 1])'),
    snippet('Past the end', 'const word = "cat"\nconsole.log(word[3])'),
  ],
  readMore: MDN('Web/JavaScript/Reference/Global_Objects/String', 'MDN: String'),
  challenges: [
    task('easy', 'Join two words', {
      prompt: 'Set `full` to `first` and `last` joined with a space between them.',
      starter: 'const first = "Grace"\nconst last = "Hopper"\n',
      hint: '`first + " " + last`.',
      solution: 'const first = "Grace"\nconst last = "Hopper"\nconst full = first + " " + last',
      tests: [['full is Grace Hopper', is('full', 'Grace Hopper')], ['Joins with +', uses('+')]],
    }),
    task('easy', 'How long?', {
      prompt: 'Set `count` to the number of characters in `password`.',
      starter: 'const password = "sunflower42"\n',
      hint: '`password.length`, without brackets.',
      solution: 'const password = "sunflower42"\nconst count = password.length',
      tests: [['count is 11', is('count', 11)], ['Uses length', uses('.length')]],
    }),
    task('easy', 'The first letter', {
      prompt: 'Set `initial` to the first character of `name`.',
      starter: 'const name = "Maya"\n',
      hint: 'Indexes start at 0: `name[0]`.',
      solution: 'const name = "Maya"\nconst initial = name[0]',
      tests: [['initial is M', is('initial', 'M')]],
      alt: 'const name = "Leo"',
    }),
    task('medium', 'The last letter', {
      prompt: 'Set `lastLetter` to the last character of `word`, without counting the letters yourself.',
      starter: 'const word = "keyboard"\n',
      hint: 'The last index is `word.length - 1`, or use `word.at(-1)`.',
      solution: 'const word = "keyboard"\nconst lastLetter = word[word.length - 1]',
      tests: [['lastLetter is d', is('lastLetter', 'd')]],
    }),
    task('medium', 'A greeting', {
      prompt: 'Set `greeting` to `Hello, ` followed by the name and `!`, then show it: `Hello, Sam!`.',
      starter: 'const name = "Sam"\n',
      hint: '`"Hello, " + name + "!"`: the space is inside the first text.',
      solution: 'const name = "Sam"\nconst greeting = "Hello, " + name + "!"\nconsole.log(greeting)',
      tests: [['greeting is right', is('greeting', 'Hello, Sam!')], ['Shows it', prints('Hello, Sam!')]],
    }),
    task('medium', 'Build it up', {
      prompt: 'Start `list` as `"Milk"` and use `+=` twice to make it `"Milk, Eggs, Bread"`.',
      starter: 'let list = "Milk"\n',
      hint: '`list += ", Eggs"`, then `list += ", Bread"`.',
      solution: 'let list = "Milk"\nlist += ", Eggs"\nlist += ", Bread"',
      tests: [['list is right', is('list', 'Milk, Eggs, Bread')], ['Uses += twice', '(_cq_code.match(/\\+=/g) || []).length >= 2']],
      typedOk: true,
    }),
    task('hard', 'Initials', {
      prompt: 'Set `initials` to the first letters of `first` and `last` with a dot after each: `A.L.`',
      starter: 'const first = "Ada"\nconst last = "Lovelace"\n',
      hint: '`first[0] + "." + last[0] + "."`.',
      solution: 'const first = "Ada"\nconst last = "Lovelace"\nconst initials = first[0] + "." + last[0] + "."',
      tests: [['initials is A.L.', is('initials', 'A.L.')]],
      alt: 'const first = "Tim"\nconst last = "Berners"',
    }),
    task('hard', 'First and last', {
      prompt: 'Show the first and last characters of `city` together with a dash: `L-n` for London.',
      starter: 'const city = "London"\n',
      hint: '`city[0] + "-" + city[city.length - 1]`.',
      solution: 'const city = "London"\nconsole.log(city[0] + "-" + city[city.length - 1])',
      tests: [['Shows L-n', prints('L-n')]],
      alt: 'const city = "Paris"',
    }),
    task('expert', 'Fix the join', {
      prompt: 'This should show `I have 3 cats`, but it shows `I have3cats`. Fix the joins.',
      starter: 'const count = 3\nconsole.log("I have" + count + "cats")',
      hint: '`+` adds no spaces. Put a space at the end of `"I have "` and the start of `" cats"`.',
      solution: 'const count = 3\nconsole.log("I have " + count + " cats")',
      tests: [['Shows I have 3 cats', prints('I have 3 cats')], ['Still uses count', matches('\\+\\s*count\\s*\\+')]],
    }),
    task('expert', 'Middle character', {
      prompt: '`word` has an odd number of letters. Set `middle` to the letter in the middle (`e` in `level`, `n` in `banjo`). Work out its index from the length.',
      starter: 'const word = "level"\n',
      hint: 'The middle index is `Math.floor(word.length / 2)`.',
      solution: 'const word = "level"\nconst middle = word[Math.floor(word.length / 2)]',
      tests: [['middle is v', is('middle', 'v')], ['Uses the length', uses('length')]],
      alt: 'const word = "banjo"',
    }),
  ],
  questions: [
    mc('What does `"ice" + "cream"` give?', ['"icecream"', '"ice cream"', '"ice+cream"', 'An error'], 0,
      '`+` joins strings exactly, with no space added.', { code: 'console.log("ice" + "cream")', output: 'icecream' }),
    mc('What is `"Hello".length`?', ['5', '4', '6', 'An error: it needs brackets'], 0,
      'length counts the characters; it\'s a value, so no brackets.', { code: 'console.log("Hello".length)', output: '5' }),
    mc('After `const w = "cat"`, what is `w[0]`?', ['"c"', '"a"', '"t"', 'undefined'], 0,
      'Indexes start at 0.', { code: 'const w = "cat"\nconsole.log(w[0])', output: 'c' }),
    mc('After `const w = "cat"`, what is `w[3]`?', ['undefined', '"t"', '""', 'An error'], 0,
      'The indexes are 0, 1 and 2; past the end there is nothing.', { code: 'const w = "cat"\nconsole.log(w[3])', output: 'undefined' }),
    mc('Which gives the last character of `word`?', ['`word[word.length - 1]`', '`word[word.length]`', '`word[-1]`', '`word.last`'], 0,
      'The last index is one less than the length. (`word.at(-1)` works too.)'),
    mc('What does `"A" + 1 + 2` give?', ['"A12"', '"A3"', '3', 'An error'], 0,
      'Once the left side is text, each `+` joins: "A" + 1 is "A1", then "A12".', { code: 'console.log("A" + 1 + 2)', output: 'A12' }),
    mc('What is `" hi ".length`?', ['4', '2', '3', '6'], 0,
      'Spaces count as characters.', { code: 'console.log(" hi ".length)', output: '4' }),
    mc('After `let s = "go"` and `s += "al"`, what is `s`?', ['"goal"', '"go al"', '"algo"', '"go"'], 0,
      '`+=` adds to the end.', { code: 'let s = "go"\ns += "al"\nconsole.log(s)', output: 'goal' }),
    qShort('What is the index of the first character of a string?', '0',
      'Counting starts at 0.'),
  ],
})
