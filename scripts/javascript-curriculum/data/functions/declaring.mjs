    'Functions let you name a job, write it once, and use it many times. If the job changes, you change one place. A good function name says what it does, usually with a verb: `showMenu`, `printReceipt`, `drawLine`.',
    'A function declared with `function` can be called even from lines above it in the file, because JavaScript reads all such declarations first. Most people still put them before the code that uses them, so it reads top to bottom.',
