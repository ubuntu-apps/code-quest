  paragraphs: [
    'An `if` doesn\'t need a real boolean. Any value works, and JavaScript treats it as true or false. Six values count as false, the **falsy** ones: `false`, `0`, `""` (empty text), `null`, `undefined` and `NaN`. Everything else is **truthy**, even `"0"`, `"false"` and `-1`.',
    '```\nconst name = ""\nif (name) {\n  console.log(`Hello, ${name}`)\n} else {\n  console.log("Please enter your name")\n}\n```',
    'That makes checks short: `if (name)` asks "is there a name?", and `if (count)` asks "is the count not zero?". `!` turns it around: `if (!name)` means "no name".',
    '`Boolean(value)` shows how a value counts, and `!!value` is a shortcut for the same thing.',
    '```\nconsole.log(Boolean(0), Boolean("0"), Boolean(""), Boolean(" "))\nconsole.log(!!"hello", !!null)\n```',
    '`||` and `&&` give back one of their values, not just `true` or `false`. `a || b` gives `a` if it is truthy, else `b`, which sets a **default**: `const shown = nickname || "Guest"`.',
    '`??` is a safer default: it only skips `null` and `undefined`, so a real `0` or `""` is kept. Use it for numbers where 0 is a fair answer: `const volume = saved ?? 50`.',
    '```\nconst saved = 0\nconsole.log(saved || 50)\nconsole.log(saved ?? 50)\n```',
  ],
