// Errors and debugging: Finding bugs. Lesson, Try-it snippets, challenges and quiz.
import { MDN, is, makeTopic, mc, qShort, same, snippet, task } from '../_builders.mjs'

export default makeTopic({
  id: 'debugging',
  title: 'Debugging: finding bugs that don\'t crash',
  paragraphs: [
    'The worst bugs give no error at all: the code runs, but the answer is wrong. Finding them is **debugging**, and it is a skill you can learn like any other.',
    'Step one: know what you **expected**, and find the first place where reality is different. The simplest tool is `console.log`: show the values in the middle of the code and see where they stop making sense.',
    '```\nconst prices = [4, 10, 6]\nlet total = 0\nfor (let i = 1; i < prices.length; i++) {\n  console.log("adding", prices[i])\n  total += prices[i]\n}\nconsole.log(total)\n```',
    'The log shows `adding 10` and `adding 6`, but never `adding 4`: the loop starts at 1, not 0. This is an **off-by-one** bug, one of the most common there is.',
    'A checklist of usual suspects:',
    '- **Off by one**: `<` vs `<=`, starting at 1 vs 0, `length` vs `length - 1`.\n- **`=` vs `===`**: `if (x = 5)` *sets* `x` and is always true.\n- **Text vs number**: `"5" + 1` is `"51"`. Values from input are text until you convert them.\n- **The wrong variable**: updating `total` inside the loop but showing `sum`.\n- **Changed when it shouldn\'t be**: `sort` and `push` change an array that other code still uses.\n- **Missing `return`**: the function gives `undefined`.',
    'Label your logs (`console.log("total after loop", total)`) so you know which is which, and log `typeof x` when the kind of value matters. Remove them when you\'re done.',
    'When the code is long, cut the problem down: try the smallest input that still goes wrong, and test pieces on their own. Explaining the code line by line, even to nobody, finds a surprising number of bugs; programmers call it "rubber duck debugging".',
  ],
  sandboxCode: 'const prices = [4, 10, 6]\nlet total = 0\nfor (let i = 1; i < prices.length; i++) {\n  console.log("adding", prices[i])\n  total += prices[i]\n}\nconsole.log("total", total)',
  sandboxSnippets: [
    snippet('Text plus number', 'const qty = "5"\nconsole.log(qty + 1, Number(qty) + 1, typeof qty)'),
    snippet('= vs ===', 'let level = 1\nif (level = 5) {\n  console.log("level is now", level)\n}'),
    snippet('Label your logs', 'const items = ["a", "b"]\nconsole.log("items:", items, "count:", items.length)'),
    snippet('Sort changes it', 'const scores = [3, 1, 2]\nconst best = scores.sort((a, b) => b - a)[0]\nconsole.log(best, scores)'),
  ],
  readMore: MDN('Learn_web_development/Core/Scripting/What_went_wrong', 'MDN: What went wrong? Troubleshooting JavaScript'),
  challenges: [
    task('easy', 'Off by one', {
      prompt: '`total` should be 20 but is 16. Fix the loop.',
      starter: 'const prices = [4, 10, 6]\nlet total = 0\nfor (let i = 1; i < prices.length; i++) {\n  total += prices[i]\n}\n',
      hint: 'Indexes start at 0.',
      solution: 'const prices = [4, 10, 6]\nlet total = 0\nfor (let i = 0; i < prices.length; i++) {\n  total += prices[i]\n}',
      tests: [['total is 20', is('total', 20)]],
    }),
    task('easy', 'Text, not a number', {
      prompt: '`next` should be 6, but it comes out as `"51"`. Fix it.',
      starter: 'const qty = "5"\nconst next = qty + 1\n',
      hint: 'Turn `qty` into a number first: `Number(qty) + 1`.',
      solution: 'const qty = "5"\nconst next = Number(qty) + 1',
      tests: [['next is 6', is('next', 6)]],
    }),
    task('easy', 'Always true', {
      prompt: 'This says `Winner!` even for a score of 3. Fix the comparison.',
      starter: 'let score = 3\nlet message = "Try again"\nif (score = 10) {\n  message = "Winner!"\n}\n',
      hint: '`=` sets a value; `===` compares.',
      solution: 'let score = 3\nlet message = "Try again"\nif (score === 10) {\n  message = "Winner!"\n}',
      tests: [['message is Try again', is('message', 'Try again')], ['score is still 3', is('score', 3)]],
      alt: 'let score = 10',
    }),
    task('medium', 'One too many', {
      prompt: '`last` comes out `undefined`. Fix it so it is the last letter.',
      starter: 'const word = "planet"\nconst last = word[word.length]\n',
      hint: 'The last index is `length - 1`.',
      solution: 'const word = "planet"\nconst last = word[word.length - 1]',
      tests: [['last is t', is('last', 't')]],
    }),
    task('medium', 'The wrong variable', {
      prompt: '`average` is always 0. Find the wrong variable and fix it.',
      starter: 'const scores = [70, 80, 90]\nlet sum = 0\nlet total = 0\nfor (const s of scores) {\n  total += s\n}\nconst average = sum / scores.length\n',
      hint: 'The loop adds to one variable, the average uses the other.',
      solution: 'const scores = [70, 80, 90]\nlet total = 0\nfor (const s of scores) {\n  total += s\n}\nconst average = total / scores.length',
      tests: [['average is 80', is('average', 80)]],
    }),
    task('medium', 'Up to and including', {
      prompt: '`evens` should be every even number from 2 to 10, but 10 is missing. Fix it.',
      starter: 'const evens = []\nfor (let n = 2; n < 10; n += 2) {\n  evens.push(n)\n}\n',
      hint: '`<` stops before 10; use `<=`.',
      solution: 'const evens = []\nfor (let n = 2; n <= 10; n += 2) {\n  evens.push(n)\n}',
      tests: [['evens is right', same('evens', '[2, 4, 6, 8, 10]')]],
    }),
    task('hard', 'It changed the original', {
      prompt: '`best` is right, but `scores` has been put in a different order. Fix it so `scores` stays as it was.',
      starter: 'const scores = [72, 95, 41]\nconst best = scores.sort((a, b) => b - a)[0]\n',
      hint: 'Use `toSorted`, or `Math.max(...scores)`.',
      solution: 'const scores = [72, 95, 41]\nconst best = scores.toSorted((a, b) => b - a)[0]',
      tests: [['best is 95', is('best', 95)], ['scores unchanged', same('scores', '[72, 95, 41]')]],
    }),
    task('hard', 'Counting vowels', {
      prompt: '`vowels("Apple")` should be 2, but gives 1. Fix the function.',
      starter: 'function vowels(text) {\n  let count = 0\n  for (const ch of text) {\n    if ("aeiou".includes(ch)) count++\n  }\n  return count\n}\n',
      hint: '"A" is a capital. Compare in lower case: `ch.toLowerCase()`.',
      solution: 'function vowels(text) {\n  let count = 0\n  for (const ch of text) {\n    if ("aeiou".includes(ch.toLowerCase())) count++\n  }\n  return count\n}',
      tests: [['Apple is 2', is('vowels("Apple")', 2)], ['EIEIO is 5', is('vowels("EIEIO")', 5)], ['sky is 0', is('vowels("sky")', 0)]],
    }),
    task('expert', 'The shared list', {
      prompt: '`addTag` is meant to return a new list, but every call adds to the same one. Fix it so `a` is `["js"]` and `b` is `["css"]`.',
      starter: 'const empty = []\nfunction addTag(tags, tag) {\n  tags.push(tag)\n  return tags\n}\nconst a = addTag(empty, "js")\nconst b = addTag(empty, "css")\n',
      hint: 'Make a new array instead of changing the one passed in: `return [...tags, tag]`.',
      solution: 'const empty = []\nfunction addTag(tags, tag) {\n  return [...tags, tag]\n}\nconst a = addTag(empty, "js")\nconst b = addTag(empty, "css")',
      tests: [['a is right', same('a', '["js"]')], ['b is right', same('b', '["css"]')], ['empty is still empty', 'empty.length === 0']],
    }),
    task('expert', 'Two bugs in a total', {
      prompt: '`cartTotal` should give 17 for the cart below. It has two bugs. Fix them.',
      starter: 'function cartTotal(cart) {\n  let total = 0\n  for (let i = 0; i <= cart.length; i++) {\n    total += cart[i].price + cart[i].qty\n  }\n  return total\n}\nconst result = cartTotal([{ price: 3, qty: 2 }, { price: 5.5, qty: 2 }])\n',
      hint: 'The loop goes one past the end (`<=`), and price and qty should be multiplied.',
      solution: 'function cartTotal(cart) {\n  let total = 0\n  for (let i = 0; i < cart.length; i++) {\n    total += cart[i].price * cart[i].qty\n  }\n  return total\n}\nconst result = cartTotal([{ price: 3, qty: 2 }, { price: 5.5, qty: 2 }])',
      tests: [['result is 17', is('result', 17)], ['Works for others', is('cartTotal([{ price: 1, qty: 4 }])', 4)]],
    }),
  ],
  questions: [
    mc('What is "off by one"?', ['A loop or index that goes one too far or stops one short', 'A number that is wrong by 1%', 'A missing bracket', 'An error type'], 0, 'Very common with < and <=.'),
    mc('What does `"5" + 1` give?', ['"51"', '6', 'NaN', 'An error'], 0, 'Text plus anything is text.', { code: 'console.log("5" + 1)', output: '51' }),
    mc('What does `if (x = 5)` do?', ['Sets x to 5, and is always true', 'Checks if x is 5', 'Gives a SyntaxError', 'Nothing'], 0, '= sets; === compares.'),
    mc('What is the best first step with a wrong answer?', ['Show values in the middle with console.log to find where they go wrong', 'Rewrite all the code', 'Add more code', 'Restart the computer'], 0, 'Find the first place reality differs.'),
    mc('What does this show?\n```\nconst s = [3, 1, 2]\nconst top = s.sort((a, b) => b - a)[0]\nconsole.log(s)\n```', ['`[ 3, 2, 1 ]`', '`[ 3, 1, 2 ]`', '`3`', 'An error'], 0, 'sort changed s.', { code: 'const s = [3, 1, 2]\nconst top = s.sort((a, b) => b - a)[0]\nconsole.log(s)', output: '[ 3, 2, 1 ]' }),
    mc('What does `"word"[4]` give?', ['undefined', '"d"', 'An error', '""'], 0, 'The last index is 3.', { code: 'console.log("word"[4])', output: 'undefined' }),
    mc('Why label your logs, like `console.log("total", total)`?', ['To tell which value is which', 'It is faster', 'Labels fix bugs', 'Logs need two values'], 0, 'Many bare numbers are hard to read.'),
    mc('What is "rubber duck debugging"?', ['Explaining the code line by line, even to an object', 'Testing with ducks', 'Deleting code until it works', 'A kind of error'], 0, 'Saying it out loud finds bugs.'),
    qShort('What do you call finding and fixing bugs?', 'debugging', 'Debugging.'),
  ],
})
