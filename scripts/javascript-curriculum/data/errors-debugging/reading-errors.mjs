// Errors and debugging: Reading error messages. Lesson, Try-it snippets, challenges and quiz.
import { MDN, is, makeTopic, mc, qShort, same, snippet, task, uses } from '../_builders.mjs'

export default makeTopic({
  id: 'reading_errors',
  title: 'Reading error messages',
  paragraphs: [
    'Every programmer sees errors all day. They are not a sign you did badly; they are JavaScript telling you, as exactly as it can, what went wrong and where. Learning to read them is the fastest way to get unstuck.',
    'An error message has two parts: the **type** of error, and a **message**. The editor also points at the **line** where it happened.',
    '```\n// This shows an error: run it and read the message\nconst price = 10\nconsole.log(pirce * 2)\n```',
    '`ReferenceError: pirce is not defined` says the kind of problem (a name JavaScript doesn\'t know) and which name. The fix is often a typo.',
    'The four you will meet most:',
    '- **SyntaxError**: the code can\'t even be read, like a missing bracket or quote. Nothing runs at all.\n- **ReferenceError**: a name that doesn\'t exist (a typo, or used before its `let`/`const`).\n- **TypeError**: a value is the wrong kind for what you did, like calling something that isn\'t a function, or reading a property of `undefined`.\n- **RangeError**: a value is out of the allowed range, like a function that calls itself forever.',
    '```\n// This shows an error: reading a property of undefined\nconst user = undefined\nconsole.log(user.name)\n```',
    'The line pointed at is where JavaScript *noticed* the problem, which isn\'t always where the mistake *is*. Here the error is on the second line, but the real bug is that `user` was never given a value. Ask "where did this value come from?" and work backwards.',
    'When code stops with an error, the lines after it don\'t run. Output before it is still shown, which helps you see how far it got.',
  ],
  sandboxCode: '// Run it, read the error, then fix the typo\nconst price = 10\nconsole.log(pirce * 2)',
  sandboxSnippets: [
    snippet('SyntaxError', '// This shows an error: a bracket is missing\nconsole.log("hi"'),
    snippet('TypeError', '// This shows an error: not a function\nconst total = 5\ntotal()'),
    snippet('Before initialization', '// This shows an error: used before const\nconsole.log(score)\nconst score = 3'),
    snippet('How far it got', '// This shows an error after the first line\nconsole.log("start")\nnull.length\nconsole.log("never shown")'),
  ],
  readMore: MDN('Web/JavaScript/Reference/Errors', 'MDN: JavaScript error reference'),
  challenges: [
    task('easy', 'Fix the typo', {
      prompt: 'This stops with a `ReferenceError`. Fix it so it shows `20`.',
      starter: 'const price = 10\nconsole.log(pirce * 2)\n',
      hint: 'Read the name in the message: `pirce` should be `price`.',
      solution: 'const price = 10\nconsole.log(price * 2)',
      tests: [['Shows 20', '_cq_prints("20")'], ['Uses price', uses('price * 2')]],
      typedOk: true,
    }),
    task('easy', 'Fix the brackets', {
      prompt: 'This has a `SyntaxError`. Fix it so it shows `Hello`.',
      starter: 'console.log("Hello"\n',
      hint: 'Every `(` needs a `)`.',
      solution: 'console.log("Hello")',
      tests: [['Shows Hello', '_cq_prints("Hello")']],
      typedOk: true,
    }),
    task('easy', 'Capital letters count', {
      prompt: 'Fix the `ReferenceError` so it shows `3`.',
      starter: 'const items = ["a", "b", "c"]\nConsole.log(items.length)\n',
      hint: 'JavaScript names are case-sensitive: `console`, not `Console`.',
      solution: 'const items = ["a", "b", "c"]\nconsole.log(items.length)',
      tests: [['Shows 3', '_cq_prints("3")']],
      typedOk: true,
    }),
    task('medium', 'Name the error', {
      prompt: 'Set `kind` to the type of error this code gives, as text (like `"SyntaxError"`): `const n = 5` then `n = 6`. Run it in the sandbox if you like.',
      hint: 'Changing a `const` is a wrong kind of action on a value.',
      solution: 'const kind = "TypeError"',
      tests: [['kind is right', is('kind', 'TypeError')]],
      typedOk: true,
    }),
    task('medium', 'Used too early', {
      prompt: 'Fix the order so it shows `Total: 12` without an error.',
      starter: 'console.log(`Total: ${total}`)\nconst total = 4 * 3\n',
      hint: 'A `const` must be made before it is used.',
      solution: 'const total = 4 * 3\nconsole.log(`Total: ${total}`)',
      tests: [['Shows the total', '_cq_prints("Total: 12")']],
    }),
    task('medium', 'Not a function', {
      prompt: '`shout` is called with the wrong name. Fix it so it shows `HEY!`.',
      starter: 'function shout(text) {\n  return text.toUpperCase() + "!"\n}\nconst word = "hey"\nconsole.log(word.shout())\n',
      hint: '`shout` is your own function, not a method of the text: `shout(word)`.',
      solution: 'function shout(text) {\n  return text.toUpperCase() + "!"\n}\nconst word = "hey"\nconsole.log(shout(word))',
      tests: [['Shows HEY!', '_cq_prints("HEY!")'], ['Calls shout', uses('shout(word)')]],
    }),
    task('hard', 'Where it came from', {
      prompt: 'This says it can\'t read `name` of `undefined`, but the bug is earlier. Fix it so it shows `Ben`.',
      starter: 'const users = [{ name: "Ana" }, { name: "Ben" }]\nconst second = users[2]\nconsole.log(second.name)\n',
      hint: 'Indexes start at 0: the second user is `users[1]`.',
      solution: 'const users = [{ name: "Ana" }, { name: "Ben" }]\nconst second = users[1]\nconsole.log(second.name)',
      tests: [['Shows Ben', '_cq_prints("Ben")'], ['Uses users[1]', uses('users[1]')]],
    }),
    task('hard', 'Missing return', {
      prompt: '`cleanName` should return the name without spaces at the ends, but the last line gives a `TypeError`. Fix the function.',
      starter: 'function cleanName(name) {\n  name.trim()\n}\nconsole.log(cleanName("  ada ").toUpperCase())\n',
      hint: 'The function returns nothing, so `.toUpperCase()` is called on `undefined`. Add `return`.',
      solution: 'function cleanName(name) {\n  return name.trim()\n}\nconsole.log(cleanName("  ada ").toUpperCase())',
      tests: [['Shows ADA', '_cq_prints("ADA")'], ['cleanName returns', is('cleanName(" x ")', 'x')]],
    }),
    task('expert', 'Three bugs', {
      prompt: 'Fix all three errors so it shows `Average: 4`.',
      starter: 'const nums = [2, 4, 6\nlet total = 0\nfor (const n of nums) {\n  totl += n\n}\nconsole.log(`Average: ${total / nums.lenght}`)\n',
      hint: 'A missing `]`, a typo in `total`, and `length` spelled wrong (that one gives `NaN`, not an error).',
      solution: 'const nums = [2, 4, 6]\nlet total = 0\nfor (const n of nums) {\n  total += n\n}\nconsole.log(`Average: ${total / nums.length}`)',
      tests: [['Shows the average', '_cq_prints("Average: 4")']],
    }),
    task('expert', 'The forever function', {
      prompt: '`countDown` gives a `RangeError`. Fix it so `countDown(3)` returns `[3, 2, 1]`.',
      starter: 'function countDown(n) {\n  return [n, ...countDown(n - 1)]\n}\n',
      hint: 'It never stops. Add a base case: `if (n === 0) return []`.',
      solution: 'function countDown(n) {\n  if (n === 0) return []\n  return [n, ...countDown(n - 1)]\n}',
      tests: [['countDown(3)', same('countDown(3)', '[3, 2, 1]')], ['countDown(0)', same('countDown(0)', '[]')]],
    }),
  ],
  questions: [
    mc('Which error means a name JavaScript doesn\'t know?', ['ReferenceError', 'TypeError', 'SyntaxError', 'RangeError'], 0, 'Often a typo.', { code: '// This shows an error\nconsole.log(nope)', error: 'ReferenceError' }),
    mc('Which error means the code can\'t be read at all?', ['SyntaxError', 'ReferenceError', 'TypeError', 'RangeError'], 0, 'A missing bracket or quote.'),
    mc('What kind of error does `null.length` give?', ['TypeError', 'ReferenceError', 'SyntaxError', 'None'], 0, 'null has no properties.', { code: '// This shows an error\nnull.length', error: 'TypeError' }),
    mc('What kind of error does `const x = 1` then `x = 2` give?', ['TypeError', 'SyntaxError', 'RangeError', 'None'], 0, 'Assignment to a constant.', { code: '// This shows an error\nconst x = 1\nx = 2', error: 'TypeError' }),
    mc('Is the line in an error always where the mistake is?', ['No: it is where JavaScript noticed the problem', 'Yes, always', 'Only for SyntaxErrors', 'Never'], 0, 'Work backwards from it.'),
    mc('After an error, do the next lines run?', ['No, the code stops', 'Yes', 'Only console.log lines', 'Only once'], 0, 'Output before it still shows.'),
    mc('What does `[1, 2].lenght` give?', ['undefined (no error)', 'A ReferenceError', 'A TypeError', '2'], 0, 'A missing property is undefined, not an error.', { code: 'console.log([1, 2].lenght)', output: 'undefined' }),
    mc('A function that calls itself forever gives…', ['RangeError', 'TypeError', 'SyntaxError', 'ReferenceError'], 0, 'Maximum call stack size exceeded.'),
    qShort('Which error type do you get for calling something that isn\'t a function?', 'TypeError', 'x is not a function.'),
  ],
})
