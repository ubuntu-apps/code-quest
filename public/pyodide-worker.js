  'def _cq_sql_table(columns, rows, limit=_CQ_SQL_MAX_ROWS):',
  '    """A result as a text table, like a database shell shows it."""',
  '    shown = rows[:limit]',
  '    cells = [[_cq_sql_value(v) for v in row] for row in shown]',
  '    widths = [len(c) for c in columns]',
  '    for row in cells:',
  '        for i, text in enumerate(row):',
  '            widths[i] = max(widths[i], len(text))',
  '    def line(values):',
  '        return " | ".join(v.ljust(widths[i]) for i, v in enumerate(values)).rstrip()',
  '    out = [line(columns), "-+-".join("-" * w for w in widths)]',
  '    out.extend(line(row) for row in cells)',
  '    n = len(rows)',
  '    note = "(" + str(n) + (" row)" if n == 1 else " rows)")',
  '    if n > limit:',
  '        note = "(" + str(n) + " rows; the first " + str(limit) + " are shown)"',
  '    out.append(note)',
  '    return "\\n".join(out)',
  '',
