  'def _cq_sql_exec(con, sql):',
  '    """Runs every statement. Returns a list of results: (columns, rows) for a statement',
  '    that returns rows, or (None, rows changed) for one that changes the data (-1 when the',
  '    statement changes no rows, such as BEGIN or CREATE TABLE)."""',
  '    import sqlite3',
  '    results = []',
  '    for number, statement in enumerate(_cq_sql_statements(sql), 1):',
  '        try:',
  '            before = con.total_changes',
  '            cur = con.execute(statement)',
  '            if cur.description is not None:',
  '                columns = [d[0] for d in cur.description]',
  '                results.append((columns, cur.fetchall()))',
  '            else:',
  '                changed = con.total_changes - before',
  '                results.append((None, changed if _cq_sql_counts_rows(statement) else -1))',
  '        except sqlite3.Error as e:',
  '            raise _CqSqlError(str(e), statement.strip(), number)',
  '        except sqlite3.Warning as e:',
  '            raise _CqSqlError(str(e), statement.strip(), number)',
  '    return results',
